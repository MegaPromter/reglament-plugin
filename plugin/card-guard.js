// Ворота «карточка согласования — только после показанного проекта заметки».
//
// Зачем. Согласование заметки делает человек: он кликает вариант «Согласовано» в
// карточке вопроса. Если проекта заметки в чате нет, кликать не на что — человек
// либо соглашается вслепую, либо отвечает «не вижу, что согласовывать» (так и
// случилось 04.10.2026). Правило «сперва проект, потом карточка» записано в навыке
// регламента; здесь оно принуждается: вызов карточки согласования без показанного
// проекта отклоняется. Решение и варианты — ADR «Показ проекта заметки до карточки
// согласования».
//
// Ворота отвечают только за ПОРЯДОК. Полнота заметки, снятые маркеры «уточнить» и
// валидатор vault — не их дело.

/** Сколько последних реплик одного хода помним. */
export const ГЛУБИНА = 3;

/** Сколько последних ходов помним: проект показывают отдельным сообщением, а
 *  карточку задают следующим; повторная карточка после закрытой без ответа тоже
 *  законна — но ссылка на проект «десять ходов назад» уже не проходит. */
export const ХОДОВ = 2;

/** Опорные секции шаблона заметки: по ним видно, что показан проект, а не пересказ. */
export const СЕКЦИИ = ['Зачем', 'Что именно делаем', 'Затрагивает', 'Как проверим'];

/** Сколько секций достаточно, чтобы считать проект показанным. */
export const СЕКЦИЙ_ДОСТАТОЧНО = 2;

/** Что сказать ассистенту вместо запрета-загадки. */
export const ТЕКСТ_ОТКАЗА =
  'Карточка согласования без показанного проекта заметки не задаётся: ' +
  'согласовывать нечего, пока проекта нет в чате. Покажите проект заметки целиком — ' +
  'секции «Зачем», «Что именно делаем», «Затрагивает», «Бизнес-правила», ' +
  '«Как проверим», «Связи», «История» — и задайте карточку после этого. ' +
  'Пересказ и отсылка «см. выше» проектом не считаются.';

/**
 * Карточка ли это про согласование заметки.
 *
 * Признаки: в вопросе есть вариант, начинающийся со слова «Согласовано», и само
 * слово «заметка». Карточки другого назначения (выбор варианта интерфейса,
 * уточняющий вопрос) ворота не трогают.
 */
export function карточкаСогласования(аргументы) {
  const вопросы = Array.isArray(аргументы?.questions) ? аргументы.questions : [];
  return вопросы.some((вопрос) => {
    const текст = String(вопрос?.question ?? '');
    const варианты = Array.isArray(вопрос?.options) ? вопрос.options : [];
    const согласие = варианты.some((вариант) =>
      String(вариант?.label ?? '').startsWith('Согласовано'),
    );
    return согласие && /заметк/i.test(текст);
  });
}

/** Показан ли проект заметки: в репликах есть хотя бы две опорные секции. */
export function проектПоказан(тексты) {
  const всё = (Array.isArray(тексты) ? тексты : []).join('\n');
  const найдено = СЕКЦИИ.filter((секция) => всё.includes(секция));
  return найдено.length >= СЕКЦИЙ_ДОСТАТОЧНО;
}

/**
 * Память о репликах ассистента для ворот: по сессии — последние ходы и реплики.
 *
 * Читать журнал сессии напрямую в ДСХ запрещено (способ объявлен устаревшим),
 * поэтому реплики запоминаются подпиской на события — как у сторожа конца хода.
 */
export function учётПоказа({ глубина = ГЛУБИНА, ходов = ХОДОВ } = {}) {
  const память = new Map(); // сессия → { ходы: [{ ход, тексты: string[] }] }

  function запомнить(сессия, ход, текст) {
    const запись = память.get(сессия) ?? { ходы: [] };
    let текущий = запись.ходы.find((звено) => звено.ход === ход);
    if (!текущий) {
      текущий = { ход, тексты: [] };
      запись.ходы.push(текущий);
    }
    текущий.тексты.push(String(текст ?? ''));
    while (текущий.тексты.length > глубина) текущий.тексты.shift();
    while (запись.ходы.length > ходов) запись.ходы.shift();
    память.set(сессия, запись);
  }

  function тексты(сессия) {
    const запись = память.get(сессия);
    return запись ? запись.ходы.flatMap((звено) => звено.тексты) : [];
  }

  function показан(сессия) {
    return проектПоказан(тексты(сессия));
  }

  function забыть(сессия) {
    память.delete(сессия);
  }

  return { запомнить, тексты, показан, забыть };
}
