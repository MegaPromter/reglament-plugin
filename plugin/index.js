// Сторож регламента для ДСХ — слой совместимости с хуками прежней среды.
//
// Плагин правил не содержит: он переводит вызов инструмента ДСХ во вход хука,
// запускает ТОТ ЖЕ скрипт `.reglament/hooks/*` и переводит «код 2 — запрет» в
// решение ДСХ. Содержание правил живёт в одном месте — у прежней среды.
//
// Подключается ВНУТРЬ пресета агента: перехват на уровне профиля вызовов
// инструментов из пресета не видит (проверено опытом, раздел 14 отчёта).
//
// Настройки строки плагина (`config`):
//   корень  — папка проекта: идёт в `cwd` и в `REGLAMENT_PROJECT_DIR`;
//   python  — чем запускать `.py`-хуки;
//   bash    — чем запускать `.sh`-хуки. ВНИМАНИЕ: `bash` из PATH на этой машине
//             оказался WSL без установленного дистрибутива, поэтому по умолчанию
//             берётся bash из Git for Windows;
//   журнал  — файл, куда пишется каждое решение сторожа;
//   канарейка — проверять ли ворота при старте (по умолчанию да);
//   повторов — сколько раз за один ход разрешено возвращать ассистента
//             (правило «в фазе „заметка" ход не заканчивается молча»).

