// Сторож регламента для ДСХ — слой совместимости с хуками Claude Code.
//
// Плагин правил не содержит: он переводит вызов инструмента ДСХ во вход хука,
// запускает ТОТ ЖЕ скрипт `.claude/hooks/*` и переводит «код 2 — запрет» в
// решение ДСХ. Содержание правил живёт в одном месте — у Claude Code.
//
// Подключается ВНУТРЬ пресета агента: перехват на уровне профиля вызовов
// инструментов из пресета не видит (проверено опытом, раздел 14 отчёта).
//
// Настройки строки плагина (`config`):
//   корень  — папка проекта: идёт в `cwd` и в `CLAUDE_PROJECT_DIR`;
//   python  — чем запускать `.py`-хуки;
//   bash    — чем запускать `.sh`-хуки. ВНИМАНИЕ: `bash` из PATH на этой машине
//             оказался WSL без установленного дистрибутива, поэтому по умолчанию
//             берётся bash из Git for Windows;
//   журнал  — файл, куда пишется каждое решение сторожа;
//   канарейка — проверять ли ворота при старте (по умолчанию да);
//   повторов — сколько раз за один ход разрешено возвращать ассистента
//             (правило «в фазе „заметка" ход не заканчивается молча»).

import { execFileSync } from 'node:child_process';
import { appendFileSync } from 'node:fs';
import путь from 'node:path';

import {
  СОБЫТИЕ_ПОСЛЕ,
  перевестиКомандуКоммита,
  собратьPayload,
  собратьPayloadОстановки,
  решениеПоОстановке,
  решениеПоХуку,
  сообщениеСторожа,
  текстРеплики,
  хукиОстановки,
  хукиПередВызовом,
  хукиПослеВызова,
} from './claude-hooks.js';
import {
  найтиСогласие,
  прочитатьТабло,
  разобратьОтвет,
  штампСогласования,
  записатьТабло,
} from './approval.js';
import { ТЕКСТ_ОТКАЗА, карточкаСогласования, учётПоказа } from './card-guard.js';
import { учётВозвратов } from './stop-guard.js';
import { проверитьBash, прогнатьКанарейку } from './canary.js';

const ПО_УМОЛЧАНИЮ = {
  корень: 'D:\\Program\\Body\\planapp_django(DSH)',
  python: 'python',
  bash: 'C:\\Program Files\\Git\\bin\\bash.exe',
  журнал: 'D:\\Program\\Body\\planapp_django(DSH)\\.dsh\\plugin-reglament.log',
  канарейка: true,
  повторов: 2,
};

/** Инструмент карточки вопроса в ДСХ. */
const ИНСТРУМЕНТ_КАРТОЧКИ = 'ask_user_question';

/** Запустить процесс и вернуть код и оба потока (сбой запуска — тоже ответ). */
export function запуститьПроцесс({ команда, аргументы, рабочаяПапка, payload }) {
  try {
    const stdout = execFileSync(команда, аргументы, {
      cwd: рабочаяПапка,
      env: { ...process.env, CLAUDE_PROJECT_DIR: рабочаяПапка, PYTHONUTF8: '1' },
      input: JSON.stringify(payload),
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    return { код: 0, stdout: stdout ?? '', stderr: '' };
  } catch (ошибка) {
    return {
      код: typeof ошибка?.status === 'number' ? ошибка.status : 1,
      stdout: String(ошибка?.stdout ?? ''),
      stderr: String(ошибка?.stderr ?? ''),
    };
  }
}

/** Запустить один хук регламента. */
export function запуститьХук({ корень, python, bash, рабочаяПапка, скрипт, тип, payload }) {
  const файл = путь.join(корень, ...скрипт.split('/'));
  // bash ждёт путь с прямыми слэшами: обратные он съедает как экранирование
  const команда = тип === 'sh' ? bash : python;
  const аргументы = тип === 'sh' ? [файл.replace(/\\/g, '/')] : [файл];
  return запуститьПроцесс({ команда, аргументы, рабочаяПапка: рабочаяПапка ?? корень, payload });
}

export function apply(ctx, config) {
  const настройки = { ...ПО_УМОЛЧАНИЮ, ...(config ?? {}) };
  const корень = настройки.корень;
  // Предохранитель от петли: сколько раз за ход разрешено вернуть ассистента.
  const возвраты = учётВозвратов({ потолок: настройки.повторов });
  // Последняя реплика ассистента по сессии: { ход, текст }. Читать журнал
  // сессии напрямую (`session.eventAt`, `session.snapshotEvents`) в ДСХ
  // запрещено — способ объявлен устаревшим, поэтому запоминаем по событиям.
  const реплики = new Map();
  // Память ворот карточки: показан ли проект заметки в последних репликах хода.
  const показ = учётПоказа();
  let последняяСессия = '';

  function отметить(текст) {
    try {
      appendFileSync(настройки.журнал, `${new Date().toISOString()} | ${текст}\n`, 'utf8');
    } catch {
      // журнал недоступен — сторож работать не перестаёт
    }
  }

  /** Прогнать список хуков; первый запрет останавливает проверку. */
  function прогнатьХуки(список, payload) {
    for (const хук of список) {
      const итог = запуститьХук({ ...настройки, ...хук, payload });
      const решение = решениеПоХуку(итог);
      // Каждый прогон — в журнал: иначе «пропуск» неотличим от «хук не дошёл»
      отметить(`хук ${хук.скрипт}: код ${итог.код}${решение.блок ? ' — ЗАПРЕТ' : ''}`);
      if (решение.блок) {
        отметить(`ЗАПРЕТ (${хук.скрипт}): ${решение.причина.split('\n')[0]}`);
        return решение;
      }
    }
    return { блок: false };
  }

  /** Канарейка: проверка, что ворота ещё кусают (см. canary.js). */
  function проверитьВорота() {
    const bash = проверитьBash({
      запуститьBash: (команда) =>
        запуститьПроцесс({
          команда: настройки.bash,
          аргументы: ['-c', команда],
          рабочаяПапка: корень,
          payload: {},
        }),
    });
    отметить(bash.строка);

    const итог = прогнатьКанарейку({
      корень,
      запустить: (описание) => запуститьХук({ ...настройки, ...описание }),
    });
    for (const строка of итог.строки) отметить(строка);

    if (!bash.жив || итог.слепых.length) {
      const слепые = [...(bash.жив ? [] : ['bash']), ...итог.слепых];
      отметить(
        `ВНИМАНИЕ: ворота регламента ОСЛЕПЛИ — ${слепые.join('; ')}. ` +
          'Формат входа хуков разошёлся, защиты сейчас нет.',
      );
    }
  }

  // ── перед вызовом инструмента ──────────────────────────────────────────────
  const снятьПеред = ctx.on('tools/pre-execute', async (exec, next) => {
    // Ворота карточки согласования: без показанного проекта заметки согласовывать
    // нечего (ADR «Показ проекта заметки до карточки согласования»).
    if (exec?.name === ИНСТРУМЕНТ_КАРТОЧКИ && карточкаСогласования(exec?.arguments)) {
      if (!показ.показан(последняяСессия)) {
        отметить('ЗАПРЕТ (карточка): проект заметки в чате не показан');
        return {
          kind: 'deny',
          reason: ТЕКСТ_ОТКАЗА,
          info: { name: 'ReglamentError', code: 'REGLEMENT_BLOCKED' },
        };
      }
      отметить('карточка согласования: проект заметки показан — пропуск');
    }

    const список = хукиПередВызовом(exec?.name);
    if (!список.length) return next();

    // Перевод команды нашего коммита — строкой в журнал: без неё «ворота
    // промолчали» неотличимо от «перевода не было» (та же причина, что у строк
    // о прогоне хуков ниже).
    const командаОболочки = String(exec?.arguments?.command ?? '');
    if (командаОболочки && перевестиКомандуКоммита(командаОболочки) !== командаОболочки) {
      отметить('команда нашего коммита переведена для правил: git_commit.py → git commit');
    }

    const payload = собратьPayload({
      инструмент: exec?.name,
      аргументы: exec?.arguments,
      корень,
      вызов: String(exec?.callId ?? ''),
    });
    const решение = прогнатьХуки(список, payload);
    if (решение.блок) {
      return {
        kind: 'deny',
        reason: решение.причина,
        info: { name: 'ReglamentError', code: 'REGLEMENT_BLOCKED' },
      };
    }
    return next();
  });

  // ── после вызова инструмента ──────────────────────────────────────────────
  const снятьПосле = ctx.on('tools/post-execute', async (exec, result, next) => {
    const список = хукиПослеВызова(exec?.name, exec?.arguments);
    if (!список.length) return next();

    const payload = собратьPayload({
      инструмент: exec?.name,
      аргументы: exec?.arguments,
      корень,
      вызов: String(exec?.callId ?? ''),
      событие: СОБЫТИЕ_ПОСЛЕ,
    });
    const решение = прогнатьХуки(список, payload);
    if (решение.блок) {
      return { kind: 'block', feedback: [{ type: 'text', text: решение.причина }] };
    }
    return next();
  });

  // ── согласование: ответ карточки вопроса пишем в табло ────────────────────
  const снятьРезультат = ctx.on('tools/result', (exec, result) => {
    if (exec?.name !== ИНСТРУМЕНТ_КАРТОЧКИ) return;
    const табло = прочитатьТабло(корень);
    const задача = табло?.задача;
    if (!задача) return;

    const ответы = разобратьОтвет(result?.value, result?.content);
    const запись = найтиСогласие({ вопросы: exec?.arguments?.questions, ответы, задача });
    if (!запись) return;

    try {
      записатьТабло(корень, штампСогласования(табло, запись));
      отметить(`согласование задачи «${задача}» записано в табло`);
    } catch (ошибка) {
      отметить(`не удалось записать согласование: ${ошибка}`);
    }
  });

  // ── конец хода: не даём закончить ход молча ──────────────────────────────
  //
  // Событие ДСХ «ход вот-вот закроется». Правило живёт в
  // `.claude/hooks/check_turn_end.py`: в фазе «заметка», пока согласования нет,
  // ход не заканчивается молча. Слушатель, который возражает, зовёт
  // `agent.steer(...)` — и машина запускает ещё один шаг вместо закрытия хода.
  const снятьКонецХода = ctx.on('agent/turn-stopping', async ({ agent, turn }) => {
    const сессия = agent?.session;
    if (!сессия) return;
    const id = String(сессия.id ?? '');

    if (!возвраты.можноВозвращать(id, turn)) {
      отметить(
        `предохранитель сработал: в ходу ${turn} уже ${возвраты.повтор(id, turn)} возвратов — ход закрывается`,
      );
      return;
    }

    const повтор = возвраты.повтор(id, turn);
    const реплика = реплики.get(id);
    const текст = реплика && реплика.ход === turn ? реплика.текст : '';
    const [хук] = хукиОстановки();
    const итог = запуститьХук({
      ...настройки,
      ...хук,
      payload: собратьPayloadОстановки({
        корень,
        сессия: id,
        активен: повтор > 0, // как stop_hook_active у Claude: ход уже разворачивали
        последняяРеплика: текст,
      }),
    });
    const решение = решениеПоОстановке(итог);

    if (!решение.возврат) {
      отметить(текст.endsWith('?') ? 'ход законен: вопрос' : 'конец хода: правило молчит');
      return;
    }

    const стал = возвраты.записатьВозврат(id, turn);
    try {
      agent.steer(сообщениеСторожа(решение.причина));
      отметить(
        `ход возвращён: повтор ${стал} из ${возвраты.потолок} — ${решение.причина.split('\n')[0]}`,
      );
    } catch (ошибка) {
      отметить(`не удалось вернуть ход: ${ошибка}`);
    }
  });

  // ── память о реплике ассистента: чем закончился ход ───────────────────────
  const снятьСобытия = ctx.on('session/event', (сессия, событие) => {
    if (событие?.type !== 'assistant/message') return;
    const id = String(сессия?.id ?? '');
    const текст = текстРеплики(событие.data?.message?.content);
    реплики.set(id, { ход: событие.data?.turn, текст });
    // Ворота карточки смотрят те же реплики: показан ли в них проект заметки.
    показ.запомнить(id, событие.data?.turn, текст);
    последняяСессия = id;
  });

  // ── сессия закрыта: её записи больше не нужны ────────────────────────────
  const снятьЗакрытие = ctx.on('session/disposed', (сессия) => {
    const id = String(сессия?.id ?? '');
    реплики.delete(id);
    показ.забыть(id);
    возвраты.забытьСессию(id);
  });

  отметить('сторож регламента подключён (хуки Claude Code)');
  if (настройки.канарейка) {
    try {
      проверитьВорота();
    } catch (ошибка) {
      отметить(`канарейка не отработала: ${ошибка}`);
    }
  }

  return () => {
    снятьПеред?.();
    снятьПосле?.();
    снятьРезультат?.();
    снятьКонецХода?.();
    снятьСобытия?.();
    снятьЗакрытие?.();
  };
}
