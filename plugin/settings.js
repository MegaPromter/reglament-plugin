// Настройки проекта — то, что проект говорит о себе сторожу.
//
// Зачем. Механизм один на все проекты, а правила и настройки у каждого свои
// (решение пользователя 11.10.2026): чем запускать python и bash, куда писать
// журнал, какие ворота включены, какую версию сторожа проект ждёт. Лежат они в
// самом проекте — `<корень>/.reglament/settings.json`, раздел `сторож` — и
// версионируются вместе с проектом: видно, какая версия сторожа его обслуживает.
//
// Файл читается только у проекта, где регламент есть: сторож чужой проект не
// обслуживает (решение О9).

import { readFileSync } from 'node:fs';
import путь from 'node:path';

/** Раздел настроек сторожа в файле проекта. */
export const РАЗДЕЛ = 'сторож';

const СТРОКИ = ['python', 'bash', 'журнал', 'версия'];
const ФЛАГИ = ['канарейка'];
const ЧИСЛА = ['повторов'];

/**
 * Настройки сторожа из файла проекта.
 *
 * Файла нет или раздел пуст — пустые настройки и молчание: это норма, проект
 * может ничего не настраивать. Файл испорчен — настройки пустые, но сказано
 * вслух, чтобы порча не выглядела как «настроек нет».
 *
 * @param {string} корень — корень проекта
 * @param {(путь: string, кодировка: string) => string} [прочитать] — чтение файла
 * @returns {{настройки: object, файл: string, сказано: string}}
 */
export function настройкиПроекта(корень, прочитать = (п, к) => readFileSync(п, к)) {
  const файл = путь.join(корень, '.reglament', 'settings.json');
  let данные;
  try {
    данные = JSON.parse(прочитать(файл, 'utf8'));
  } catch (ошибка) {
    const нетФайла = ошибка?.code === 'ENOENT';
    return {
      настройки: {},
      файл,
      сказано: нетФайла ? '' : `настройки проекта не разобраны (${файл}): ${ошибка.message}`,
    };
  }

  const раздел = данные?.[РАЗДЕЛ];
  if (раздел === undefined) return { настройки: {}, файл, сказано: '' };
  if (раздел === null || typeof раздел !== 'object' || Array.isArray(раздел)) {
    return { настройки: {}, файл, сказано: `раздел «${РАЗДЕЛ}» в ${файл} — не объект, пропущен` };
  }

  const собранные = {};
  const беды = [];
  for (const имя of СТРОКИ) {
    if (раздел[имя] === undefined) continue;
    if (typeof раздел[имя] === 'string' && раздел[имя].trim()) собранные[имя] = раздел[имя];
    else беды.push(имя);
  }
  for (const имя of ФЛАГИ) {
    if (раздел[имя] === undefined) continue;
    if (typeof раздел[имя] === 'boolean') собранные[имя] = раздел[имя];
    else беды.push(имя);
  }
  for (const имя of ЧИСЛА) {
    if (раздел[имя] === undefined) continue;
    if (Number.isInteger(раздел[имя]) && раздел[имя] >= 0) собранные[имя] = раздел[имя];
    else беды.push(имя);
  }
  const выключены = раздел.ворота_выключены;
  if (Array.isArray(выключены)) {
    собранные.ворота_выключены = выключены.filter((имя) => typeof имя === 'string');
  } else if (выключены !== undefined) {
    беды.push('ворота_выключены');
  }

  return {
    настройки: собранные,
    файл,
    сказано: беды.length ? `в настройках проекта (${файл}) пропущены поля: ${беды.join(', ')}` : '',
  };
}

/** Путь журнала из настроек: относительный считается от корня проекта. */
export function путьЖурнала(корень, настроенный) {
  if (!настроенный) return '';
  return путь.isAbsolute(настроенный) ? настроенный : путь.join(корень, настроенный);
}

/** Выключены ли настройками проекта ворота с таким скриптом. */
export function воротаВыключены(настройки, скрипт) {
  const список = настройки?.ворота_выключены ?? [];
  return список.includes(скрипт) || список.includes(путь.basename(String(скрипт)));
}
