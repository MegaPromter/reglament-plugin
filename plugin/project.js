// Проект сеанса — где на самом деле идёт работа.
//
// Зачем. Сторож настраивался на один проект (`корень` в строке плагина), а работа
// идёт в той папке, где открыт сеанс. 11.10.2026 это дало живой случай: коммит в
// проекте «плагин» отклонили ворота ПРИЗМЫ (правило 5), потому что сторож считал
// своей папкой ПРИЗМУ и другого проекта не знал (дефект D2, решение О9).
//
// Откуда берётся рабочая папка. ДСХ хранит её в шапке сеанса (`session.header.cwd`,
// он задаётся при создании: `ctx.sessions.create(id, { meta: { cwd } })`) и кладёт
// сам сеанс в события плагина (`exec.agent.session`, `agent.session` в конце хода) —
// читать внутренние файлы ДСХ не нужно.
//
// Проект ищется вверх от рабочей папки: сначала папка с регламентом
// (`.reglament/hooks`), иначе ближайший корень git. Нет ни того, ни другого —
// регламента в проекте нет: сторож об этом говорит, а не судит чужой проект
// правилами первого (решение О9).

import { existsSync } from 'node:fs';
import путь from 'node:path';

/** Рабочая папка сеанса из события ДСХ; нет её — пустая строка. */
export function рабочаяПапкаСеанса(agent) {
  const cwd = agent?.session?.header?.cwd ?? agent?.session?.cwd;
  return typeof cwd === 'string' && путь.isAbsolute(cwd) ? cwd : '';
}

/** Есть ли в папке регламент — тот самый признак, по которому сторож работает. */
export function естьРегламент(папка, естьФайл = existsSync) {
  return естьФайл(путь.join(папка, '.reglament', 'hooks'));
}

/**
 * Проект от рабочей папки вверх: папка с регламентом, иначе корень git.
 *
 * @param {string} рабочая — рабочая папка сеанса
 * @param {(путь: string) => boolean} [естьФайл] — проверка пути (в самопроверке — своя)
 * @returns {{корень: string, регламент: boolean, рабочая: string}}
 */
export function папкаПроекта(рабочая, естьФайл = existsSync) {
  const старт = путь.resolve(рабочая);
  let текущая = старт;
  let кореньГита = '';
  for (;;) {
    if (естьРегламент(текущая, естьФайл)) {
      return { корень: текущая, регламент: true, рабочая: старт };
    }
    if (!кореньГита && естьФайл(путь.join(текущая, '.git'))) кореньГита = текущая;
    const выше = путь.dirname(текущая);
    if (выше === текущая) break;
    текущая = выше;
  }
  return { корень: кореньГита || старт, регламент: false, рабочая: старт };
}

/**
 * Проект для вызова: рабочая папка из события, иначе запасной корень настроек
 * (канарейка и первые вызовы, когда сеанса ещё нет).
 *
 * @param {object|undefined} agent — агент из события ДСХ (`exec.agent`, `agent`)
 * @param {string} запасной — корень из строки плагина
 * @param {(путь: string) => boolean} [естьФайл] — проверка пути
 */
export function проектВызова(agent, запасной, естьФайл = existsSync) {
  const рабочая = рабочаяПапкаСеанса(agent);
  if (!рабочая) {
    // Сеанса нет или ДСХ не назвал рабочую папку — работаем как раньше: настройка.
    return { корень: запасной, регламент: true, рабочая: '', источник: 'настройка' };
  }
  return { ...папкаПроекта(рабочая, естьФайл), источник: 'сеанс' };
}
