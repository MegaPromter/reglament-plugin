// Предохранитель от петли для возврата ассистента (событие `agent/turn-stopping`).
//
// Зачем отдельный файл. В прежней среде признак «ход уже разворачивали хуком»
// (`stop_hook_active`) выставляет сам харнесс, и правило на второй попытке
// отступает. В ДСХ признак выставляем мы, а этот счётчик — вторая страховка:
// если правило когда-нибудь перестанет смотреть на признак, потолок не даст
// ходу зациклиться. Логика чистая и без ДСХ — поэтому проверяется самопроверкой
// рядом (`self-test.mjs`).
//
// Ключ счёта — пара «сессия + ход»: у каждой сессии свой запас, у нового хода
// он снова полный.

/** Сколько раз за один ход разрешено возвращать ассистента по умолчанию. */
export const ПОТОЛОК_ПО_УМОЛЧАНИЮ = 2;

/**
 * Счётчик возвратов на пару «сессия + ход».
 *
 * @param {object} [настройки]
 * @param {number} [настройки.потолок] — сколько возвратов разрешено в одном ходу
 */
export function учётВозвратов({ потолок = ПОТОЛОК_ПО_УМОЛЧАНИЮ } = {}) {
  const предел = Number.isInteger(потолок) && потолок > 0 ? потолок : ПОТОЛОК_ПО_УМОЛЧАНИЮ;
  const счёт = new Map();

  function ключ(сессия, ход) {
    return `${String(сессия ?? '')}:${String(ход ?? '')}`;
  }

  return {
    потолок: предел,

    /** Сколько раз ассистента уже возвращали в этом ходу. */
    повтор(сессия, ход) {
      return счёт.get(ключ(сессия, ход)) ?? 0;
    },

    /** Есть ли запас: false — ход надо отпустить, возврат больше не делаем. */
    можноВозвращать(сессия, ход) {
      return (счёт.get(ключ(сессия, ход)) ?? 0) < предел;
    },

    /** Записать возврат; возвращает счётчик после записи. */
    записатьВозврат(сессия, ход) {
      const к = ключ(сессия, ход);
      const стал = (счёт.get(к) ?? 0) + 1;
      счёт.set(к, стал);
      return стал;
    },

    /** Сессия закрыта — счётчики её ходов больше не нужны. */
    забытьСессию(сессия) {
      const начало = `${String(сессия ?? '')}:`;
      for (const к of [...счёт.keys()]) {
        if (к.startsWith(начало)) счёт.delete(к);
      }
    },
  };
}
