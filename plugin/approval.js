// Запись согласования в табло задачи.
//
// Зачем этот модуль. Полная форма регламента считается согласованной, если в
// табло стоит ШТАМП или ответ «Согласовано» найден в стенограмме сессии.
// Стенограммы в формате прежней среды у ДСХ нет, поэтому остаётся штамп — и его надо
// поставить самим: карточка вопроса в ДСХ своя (`ask_user_question`), и ответ
// пользователя приходит результатом инструмента.
//
// Поля штампа — ровно те же, что пишет `.reglament/hooks/gate_edit.py`
// (`отметить_в_табло`), иначе `отметка_верна` его не признает и правки кода
// останутся заблокированными навсегда.

import { readFileSync, writeFileSync } from 'node:fs';
import путь from 'node:path';

/** Вариант карточки, который считается согласованием (как в gate_edit.py). */
export const ВАРИАНТ_СОГЛАСИЯ = 'Согласовано';

/** Путь к табло задачи внутри проекта. */
export function путьТабло(корень) {
  return путь.join(корень, '.reglament', 'task-state.json');
}

/** Табло задачи; нет файла или он испорчен — пустое (как `прочитать_табло`). */
export function прочитатьТабло(корень) {
  try {
    const текст = readFileSync(путьТабло(корень), 'utf8');
    const данные = JSON.parse(текст);
    return данные && typeof данные === 'object' ? данные : {};
  } catch {
    return {};
  }
}

/** Записать табло, сохранив форматирование как у хука (отступ 2). */
export function записатьТабло(корень, табло) {
  writeFileSync(путьТабло(корень), `${JSON.stringify(табло, null, 2)}\n`, 'utf8');
}

/**
 * Значение ответа карточки: структура `{answers:[{id, selected, custom}]}`.
 * Модель видит его как компактный JSON, поэтому умеем разобрать и строку.
 */
export function разобратьОтвет(значение, содержание) {
  if (значение && typeof значение === 'object' && Array.isArray(значение.answers)) {
    return значение.answers;
  }
  const тексты = [];
  if (typeof значение === 'string') тексты.push(значение);
  if (Array.isArray(содержание)) {
    for (const блок of содержание) {
      if (блок && typeof блок === 'object' && typeof блок.text === 'string') тексты.push(блок.text);
    }
  }
  for (const текст of тексты) {
    try {
      const данные = JSON.parse(текст);
      if (данные && Array.isArray(данные.answers)) return данные.answers;
    } catch {
      // не JSON — пропускаем
    }
  }
  return [];
}

/**
 * Найти согласие в ответе карточки.
 *
 * Правило то же, что у `найти_согласование` в gate_edit.py: вопрос называет
 * задачу, а выбранный вариант — ровно «Согласовано».
 *
 * @returns {string|null} идентификатор ответа (он же ссылка записи) или null
 */
export function найтиСогласие({ вопросы, ответы, задача }) {
  if (!задача) return null;
  const список = Array.isArray(вопросы) ? вопросы : [];
  const ответыСписок = Array.isArray(ответы) ? ответы : [];
  for (const ответ of ответыСписок) {
    const вопрос = список.find((в) => в && в.id === ответ?.id);
    const текст = String(вопрос?.question ?? вопрос?.prompt ?? '');
    if (!текст.includes(задача)) continue;
    const выбранные = Array.isArray(ответ?.selected) ? ответ.selected : [];
    if (выбранные.includes(ВАРИАНТ_СОГЛАСИЯ)) {
      return String(ответ?.id ?? 'согласовано');
    }
  }
  return null;
}

/**
 * Штамп согласования — поля и формат времени как у `отметить_в_табло`.
 *
 * `отпечаток` — отпечаток текста заметки, которую человек согласовал (пустая
 * строка, если файла ещё нет: заметку в регламенте сохраняют после согласования).
 * По нему видно, что согласовали одну версию, а делают другую.
 */
export function штампСогласования(табло, запись, момент = new Date(), отпечаток = '') {
  const дд = String(момент.getDate()).padStart(2, '0');
  const мм = String(момент.getMonth() + 1).padStart(2, '0');
  const чч = String(момент.getHours()).padStart(2, '0');
  const мин = String(момент.getMinutes()).padStart(2, '0');
  return {
    ...табло,
    одобрено: true,
    одобрено_в: `${момент.getFullYear()}-${мм}-${дд} ${чч}:${мин}`,
    одобрено_записью: запись,
    одобрено_задача: табло?.задача,
    одобрено_заметкой: отпечаток,
  };
}
