// Канарейка: проверка, что ворота регламента ещё КУСАЮТ.
//
// Зачем. Хуки регламента — код прежней среды, а мы кормим их сочинённым нами
// входом. Если формат входа разойдётся (прежняя среда его изменит, мы ошибёмся в
// переводе), хук не поймёт данные и вернёт «пропуск» — ворота откажут МОЛЧА.
// Это ровно тот тихий отказ, который опаснее громкого.
//
// Как проверяем. Каждому хуку даём заведомо плохой вход и требуем «запрет».
// Прогон идёт во ВРЕМЕННОМ проекте, поэтому результат не зависит от настоящего
// табло задачи: канарейка не мешает работе и не зависит от неё.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import путь from 'node:path';

/** Табло временного проекта: задача есть, согласования НЕТ. */
const ТАБЛО_НЕСОГЛАСОВАННО = {
  задача: 'Канарейка регламента',
  заметка: 'docs/vault/задачи/Канарейка регламента.md',
  фаза: 'проект',
  форма: 'полная',
};

/** Табло пустое: барьеры, которым нужна задача, молчат — так и задумано. */
const ТАБЛО_ПУСТОЕ = {};

/** Собрать временный проект для канарейки. */
export function сделатьВременныйПроект() {
  const папка = путь.join(tmpdir(), `dsh-canary-${Date.now()}`);
  mkdirSync(путь.join(папка, '.reglament'), { recursive: true });
  mkdirSync(путь.join(папка, 'apps'), { recursive: true });
  writeFileSync(путь.join(папка, 'apps', 'canary.py'), 'x = 1\n', 'utf8');
  return папка;
}

export function убратьВременныйПроект(папка) {
  try {
    rmSync(папка, { recursive: true, force: true });
  } catch {
    // не убрали — не беда: папка во временном каталоге системы
  }
}

/**
 * Канарейки: имя, хук, вход и чего ждём.
 *
 * `табло` кладётся во временный проект перед прогоном этой канарейки.
 */
export function канарейки(папка) {
  return [
    {
      имя: 'gate_edit кусает несогласованную правку',
      скрипт: '.reglament/hooks/gate_edit.py',
      тип: 'py',
      табло: ТАБЛО_НЕСОГЛАСОВАННО,
      ожидаемыйКод: 2,
      payload: {
        hook_event_name: 'PreToolUse',
        tool_name: 'Write',
        tool_input: { file_path: путь.join(папка, 'apps', 'canary.py'), content: 'x = 2\n' },
      },
    },
    {
      имя: 'check_commit кусает коммит без ссылки',
      скрипт: '.reglament/hooks/check_commit.py',
      тип: 'py',
      табло: ТАБЛО_ПУСТОЕ,
      ожидаемыйКод: 2,
      payload: {
        hook_event_name: 'PreToolUse',
        tool_name: 'PowerShell',
        tool_input: { command: 'git commit -m канарейка' },
      },
    },
    {
      имя: 'gate_shell разбирает свой вход',
      скрипт: '.reglament/hooks/gate_shell.py',
      тип: 'py',
      табло: ТАБЛО_НЕСОГЛАСОВАННО,
      ожидаемыйКод: 0, // «до команды» только снимает отпечаток — запрета тут нет
      payload: {
        hook_event_name: 'PreToolUse',
        tool_name: 'PowerShell',
        tool_input: { command: 'echo канарейка' },
      },
    },
  ];
}

/**
 * Отдельная проверка: жив ли bash, которым запускаются `.sh`-хуки.
 *
 * Ловушка этой машины: `bash` из PATH — это WSL без установленного
 * дистрибутива, он не работает и на любой вызов отвечает сообщением об ошибке.
 * Если бы хуки брали bash оттуда, `pre-commit-tests.sh` и `post-edit-*.sh`
 * не запускались бы вовсе — и ворота молчали бы.
 */
export function проверитьBash({ запуститьBash }) {
  const итог = запуститьBash('echo canary');
  const жив = итог.код === 0 && String(итог.stdout).includes('canary');
  const хвост = `${итог.stdout ?? ''}${итог.stderr ?? ''}`
    .trim()
    .replace(/\s+/g, ' ')
    .slice(0, 140);
  return {
    жив,
    строка: `${жив ? 'ок' : 'СЛЕПО'} — bash отвечает: код ${итог.код}${жив ? '' : ` (${хвост})`}`,
  };
}

/**
 * Прогнать канарейки.
 *
 * @param {object} параметры
 * @param {string} параметры.корень — настоящая папка проекта (для путей хуков)
 * @param {(описание: object) => {код: number, stdout: string, stderr: string}} параметры.запустить
 * @returns {{ всего: number, слепых: string[], строки: string[] }}
 */
export function прогнатьКанарейку({ корень, запустить }) {
  const папка = сделатьВременныйПроект();
  const строки = [];
  const слепых = [];
  try {
    for (const канарейка of канарейки(папка)) {
      writeFileSync(
        путь.join(папка, '.reglament', 'task-state.json'),
        `${JSON.stringify(канарейка.табло, null, 2)}\n`,
        'utf8',
      );
      const итог = запустить({
        скрипт: канарейка.скрипт,
        тип: канарейка.тип,
        корень,
        рабочаяПапка: папка,
        payload: канарейка.payload,
      });
      const кусает = итог.код === канарейка.ожидаемыйКод;
      строки.push(
        `${кусает ? 'ок' : 'СЛЕПО'} — ${канарейка.имя}: код ${итог.код}, ожидали ${канарейка.ожидаемыйКод}`,
      );
      if (!кусает) слепых.push(канарейка.имя);
    }
  } finally {
    убратьВременныйПроект(папка);
  }
  return { всего: строки.length, слепых, строки };
}
