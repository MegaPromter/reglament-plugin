// Канарейка: проверка, что ворота регламента ещё КУСАЮТ.
//
// Зачем. Хуки регламента — код прежней среды, а мы кормим их сочинённым нами
// входом. Если формат входа разойдётся (прежняя среда его изменит, мы ошибёмся в
// переводе), хук не поймёт данные и вернёт «пропуск» — ворота откажут МОЛЧА.
// Это ровно тот тихий отказ, который опаснее громкого.
//
// Как проверяем. Каждому хуку даём заведомо плохой вход и требуем «запрет».
// Прогон идёт во ВРЕМЕННОМ проекте, поэтому результат не зависит от настоящего
// табло задачи: канарейка не мешает работе и не зависит от неё.

import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
