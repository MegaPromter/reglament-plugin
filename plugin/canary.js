/**
 * Отдельная проверка: жив ли bash, которым запускаются `.sh`-хуки.
 *
 * Ловушка этой машины: `bash` из PATH — это WSL без установленного
 * дистрибутива, он не работает и на любой вызов отвечает сообщением об ошибке.
 * Если бы хуки брали bash оттуда, `pre-commit-tests.sh` и `post-edit-*.sh`
 * не запускались бы вовсе — и ворота молчали бы.
 */
export function проверитьBash({ запуститьBash }) {
  const итог = запуститьBash('echo canary');
  const жив = итог.код === 0 && String(итог.stdout).includes('canary');
  const хвост = `${итог.stdout ?? ''}${итог.stderr ?? ''}`
    .trim()
    .replace(/\s+/g, ' ')
    .slice(0, 140);
  return {
    жив,
    строка: `${жив ? 'ок' : 'СЛЕПО'} — bash отвечает: код ${итог.код}${жив ? '' : ` (${хвост})`}`,
  };
}

/**
 * Проверить, что инструмент вообще запускается.
 *
 * Зачем отдельно от bash. 11.10.2026 полсессии ушло на то, что оболочка не
 * запускалась вовсе (падение 0xC0000142, пустой вывод): «ворота не сработали» и
 * «команд не было» выглядят одинаково. Проверка на старте называет это вслух.
 *
 * @param {object} параметры
 * @param {string} параметры.имя — как называть инструмент в журнале
 * @param {string} параметры.команда — чем запускать
 * @param {string[]} параметры.аргументы — что запускать
 * @param {string} [параметры.ожидаемое] — что обязано быть в выводе
 * @param {(о: object) => {код: number, stdout: string, stderr: string}} параметры.запустить
 */
export function проверитьИнструмент({ имя, команда, аргументы, ожидаемое = '', запустить }) {
  const итог = запустить({ команда, аргументы });
  const весь = `${итог.stdout ?? ''}${итог.stderr ?? ''}`;
  const жив = итог.код === 0 && (!ожидаемое || весь.includes(ожидаемое));
  const хвост = весь.trim().replace(/\s+/g, ' ').slice(0, 140);
  return {
    имя,
    жив,
    строка: `${жив ? 'ок' : 'СЛЕПО'} — ${имя}: код ${итог.код}${жив ? '' : ` (${хвост})`}`,
  };
}

/**
 * Что проверяем при старте: чем запускаются правила и проверки после правки.
 *
 * Инструмент проверок (ruff, node) — не роскошь: без него проверка после правки
 * молчит, а молчание неотличимо от «всё чисто» (дефект: хуки читали вход через
 * `jq`, которого в системе нет, и всегда выходили с кодом 0).
 */
