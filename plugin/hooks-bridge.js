// Слой совместимости: вызов хуков регламента прежней среды из ДСХ.
//
// Правила НЕ переписываются. Тот же самый скрипт `.reglament/hooks/*`, тот же вход
// (JSON на стандартный ввод), тот же выход (код 2 — запрет, объяснение в потоке
// ошибок). Разница платформ — только в четырёх местах, и все здесь:
//   1. имена инструментов: у ДСХ строчные (`write`, `pwsh`), у прежней среды с большой
//      буквы (`Write`, `PowerShell`);
//   2. `transcript_path`: у ДСХ стенограммы в формате прежней среды нет, поэтому путь
//      пустой, а согласование живёт в табло (штамп ставит модуль approval.js);
//   3. конец хода: у прежней среды это событие `Stop`, у ДСХ — `agent/turn-stopping`
//      (слушателя зовёт index.js, возврат ассистента делает `agent.steer`);
//   4. команда коммита: у прежней среды это `git commit`, у ДСХ — свой инструмент
//      (`python .dsh/tools/git_commit.py …`), и её надо перевести в понятный
//      правилам вид — иначе ворота тестов и проверка ссылки на заметку молчат
//      (`перевестиКомандуКоммита` ниже).
//
// Здесь только чистые функции: ничего не запускается, ничего не пишется.

import { randomUUID } from 'node:crypto';

import { воротаОстановки, воротаПеред, воротаПосле } from './hooks-map.js';

/** Соответствие имён инструментов ДСХ именам прежней среды. */
export const ИМЯ_ИНСТРУМЕНТА = {
  write: 'Write',
  edit: 'Edit',
  pwsh: 'PowerShell',
  bash: 'Bash',
};

/** События, на которые gate_shell ждёт отпечаток «после». */
export const СОБЫТИЕ_ПОСЛЕ = 'PostToolUse';

/**
 * Вызов нашего инструмента коммита в начале отрезка команды: необязательный
 * интерпретатор (питон проекта или системный), путь инструмента и аргументы как
 * есть. Упоминание имени файла внутри другой команды
 * (`echo .dsh/tools/git_commit.py`) под образец не подходит — перевода не будет.
 */
const ВЫЗОВ_КОММИТА =
  /^(\s*)(?:["']?(?:\S*[\\/])?(?:python[0-9.]*|py)(?:\.exe)?["']?\s+)?["']?(?:\S*[\\/])?\.dsh[\\/]tools[\\/]git_commit\.py["']?(\s[\s\S]*)?$/i;

/**
 * Разделители отрезков команды. Перенос строки — тоже разделитель: ассистент
 * пишет коммит двумя строками (`git add …`, затем команда инструмента), и без
 * этого живая проверка 04.10.2026 показала дыру — такой коммит уходил мимо ворот
 * (в журнале ни строки перевода, ни прогона тестов).
 */
const РАЗДЕЛИТЕЛЬ = /(&&|\|\||;|\||\r?\n)/;

/**
 * Перевести команду нашего коммита в вид, понятный правилам регламента.
 *
 * Это ещё одна разница сред, которую знает только слой ДСХ (к трём, названным
 * выше): в прежней среде коммит идёт командой `git commit`, а у нас — своим
 * инструментом (`python .dsh/tools/git_commit.py …`, `DSH_REPORT.md`, раздел
 * 20.7). Хуки ищут в тексте команды `git commit` и на нашу команду молчали:
 * ворота тестов и проверка ссылки на заметку не срабатывали (найдено
 * 04.10.2026, заметка vault «Ворота коммита видят команду нашего инструмента»).
 * Правила при этом остаются в одном месте — плагин ничего не решает, он
 * переводит вызов, а аргументы переносит как есть.
 *
 * @param {string} команда — текст команды оболочки
 * @returns {string} тот же текст, где вызов нашего инструмента заменён на `git commit`
 */
export function перевестиКомандуКоммита(команда) {
  if (typeof команда !== 'string' || !команда) return команда;
  return команда
    .split(РАЗДЕЛИТЕЛЬ)
    .map((отрезок) => {
      const найден = ВЫЗОВ_КОММИТА.exec(отрезок);
      if (!найден) return отрезок;
      const [, отступ, аргументы = ''] = найден;
      return `${отступ}git commit${аргументы}`;
    })
    .join('');
}

/** Вход инструмента для хука: у команды оболочки — с переводом нашего коммита. */
function входИнструмента(имя, аргументы) {
  const исходный = аргументы ?? {};
  if ((имя !== 'Bash' && имя !== 'PowerShell') || typeof исходный.command !== 'string') {
    return исходный;
  }
  const команда = перевестиКомандуКоммита(исходный.command);
  return команда === исходный.command ? исходный : { ...исходный, command: команда };
}

/**
 * Вход хука в том виде, в каком его ждут скрипты регламента.
 *
 * @param {object} параметры
 * @param {string} параметры.инструмент — имя инструмента ДСХ (`write`, `pwsh`, …)
 * @param {object} параметры.аргументы — аргументы вызова
 * @param {string} параметры.корень — папка проекта (идёт в `cwd`)
 * @param {string} параметры.вызов — номер вызова (`tool_use_id`); по нему
 *   gate_shell сшивает отпечатки «до» и «после»
 * @param {string} [параметры.событие] — `PreToolUse` (по умолчанию) или `PostToolUse`
 * @returns {object} полезная нагрузка хука
 */
export function собратьPayload({
  инструмент,
  аргументы,
  корень,
  вызов = '',
  сессия = '',
  событие = 'PreToolUse',
}) {
  return {
    session_id: сессия,
    transcript_path: '', // у ДСХ стенограмм прежней среды нет — согласование в табло
    cwd: корень,
    hook_event_name: событие,
    tool_name: ИМЯ_ИНСТРУМЕНТА[инструмент] ?? инструмент,
    tool_input: входИнструмента(ИМЯ_ИНСТРУМЕНТА[инструмент] ?? инструмент, аргументы),
    tool_use_id: вызов,
  };
}

/** Имя инструмента прежней среды — по нему карта ворот (`hooks-map.js`). */
function имяПрежнейСреды(инструмент) {
  return ИМЯ_ИНСТРУМЕНТА[инструмент] ?? инструмент;
}

/**
 * Хуки, которые прежняя среда зовёт ПЕРЕД вызовом. Состав и порядок — в
 * `hooks-map.js`, одном месте на весь комплект (порядок важен: тесты и ссылка
 * на vault идут до проверки оболочки).
 */
export function хукиПередВызовом(инструмент) {
  return воротаПеред(имяПрежнейСреды(инструмент));
}

/** Хуки, которые прежняя среда зовёт ПОСЛЕ вызова. Состав — в `hooks-map.js`. */
export function хукиПослеВызова(инструмент, аргументы) {
  return воротаПосле(имяПрежнейСреды(инструмент), аргументы);
}

/**
 * Решение по итогу хука. У регламента принято: код 2 — запрет, объяснение в
 * потоке ошибок. Всё остальное (в том числе сбой самого хука) работе не мешает —
 * кроме проверок необратимых действий (`строго`): там сбой значит «неизвестно»,
 * а «неизвестно» разрешением не считается (решение М2.4).
 */
export function решениеПоХуку({ код, stderr = '', stdout = '', строго = false, имя = 'правило' }) {
  if (код === 2) {
    const объяснение = String(stderr || stdout || '').trim();
    return {
      блок: true,
      причина: объяснение || 'Действие заблокировано правилом регламента.',
      сбой: false,
    };
  }
  if (код !== 0 && строго) {
    const хвост = String(stderr || stdout || '')
      .trim()
      .slice(0, 300);
    return {
      блок: true,
      сбой: true,
      причина:
        `Проверка «${имя}» не смогла отработать (код ${код}): ` +
        `${хвост || 'без объяснения'}.\n` +
        'Действие необратимое — без проверки оно не считается сделанным. ' +
        'Почини проверку и повтори.',
    };
  }
  return { блок: false, сбой: false };
}

// ── конец хода (у прежней среды — Stop, у ДСХ — agent/turn-stopping) ────────────────

/** Имя события прежней среды «ассистент закончил ход». */
export const СОБЫТИЕ_ОСТАНОВКИ = 'Stop';

/** Пометка сторожа: по ней в переписке видно, что это не слова пользователя. */
export const ПОМЕТКА_СТОРОЖА = '[сторож регламента]';

/** Вид источника сообщения сторожа (у ДСХ незнакомые виды сохраняются как есть). */
export const ИСТОЧНИК_СТОРОЖА = { kind: 'reglament' };

/**
 * Хуки конца хода — состав в `hooks-map.js` (одно место на весь комплект).
 */
export function хукиОстановки() {
  return воротаОстановки();
}

/**
 * Вход хука «ассистент закончил ход» — те поля, которые читает
 * `check_turn_end.py`.
 *
 * @param {object} параметры
 * @param {string} параметры.корень — папка проекта (идёт в `cwd`)
 * @param {string} [параметры.сессия] — идентификатор сессии ДСХ
 * @param {boolean} [параметры.активен] — ход уже разворачивали в этом ходу
 *   (`stop_hook_active` у прежней среды): правило на это смотрит и второй раз отступает
 * @param {string} [параметры.последняяРеплика] — чем закончил ассистент
 *   (нужен для исключения «ход закончился вопросом»)
 * @returns {object} полезная нагрузка хука
 */
export function собратьPayloadОстановки({
  корень,
  сессия = '',
  активен = false,
  последняяРеплика = '',
}) {
  return {
    session_id: сессия,
    transcript_path: '', // стенограмм прежней среды у ДСХ нет — согласование в табло
    cwd: корень,
    hook_event_name: СОБЫТИЕ_ОСТАНОВКИ,
    stop_hook_active: активен === true,
    last_assistant_message: последняяРеплика ?? '',
  };
}

/**
 * Ответ хука конца хода: возвращать ли ассистента и с каким текстом.
 *
 * У этого хука свой словарь ответа, не как у ворот инструментов: «вернуть
 * ассистента» он пишет в стандартный вывод строкой `{"decision": "block",
 * "reason": "…"}` и выходит с кодом 0. Код 2 (общий запрет регламента) тоже
 * считаем возвратом — на случай, если правило начнёт отвечать им.
 *
 * @returns {{возврат: boolean, причина: string}}
 */
export function решениеПоОстановке({ код, stdout = '', stderr = '' }) {
  if (код === 2) {
    const объяснение = String(stderr || stdout || '').trim();
    return {
      возврат: true,
      причина: объяснение || 'Ход возвращён правилом регламента.',
    };
  }
  // Сбой самого хука (код 1) работе не мешает — как и у прочих ворот.
  if (код !== 0) return { возврат: false, причина: '' };

  const текст = String(stdout ?? '').trim();
  if (!текст) return { возврат: false, причина: '' };
  let разобрано;
  try {
    разобрано = JSON.parse(текст);
  } catch {
    return { возврат: false, причина: '' }; // напоминание или мусор — не запрет
  }
  if (!разобрано || разобрано.decision !== 'block') {
    return { возврат: false, причина: '' };
  }
  const причина = String(разобрано.reason ?? '').trim();
  return {
    возврат: true,
    причина: причина || 'Ход возвращён правилом регламента.',
  };
}

/** Текст реплики ассистента: только текстовые блоки, по порядку. */
export function текстРеплики(содержание) {
  if (!Array.isArray(содержание)) return '';
  return содержание
    .filter((блок) => блок && блок.type === 'text' && typeof блок.text === 'string')
    .map((блок) => блок.text)
    .join('\n')
    .trim();
}

/** Заморозить значение наглухо: у ДСХ опубликованное сообщение неизменно. */
function заморозить(значение) {
  if (значение && typeof значение === 'object' && !Object.isFrozen(значение)) {
    Object.freeze(значение);
    for (const вложенное of Object.values(значение)) заморозить(вложенное);
  }
  return значение;
}

/**
 * Сообщение сторожа, которым ассистента возвращают к работе.
 *
 * У ДСХ это обычное сообщение пользователя в очереди агента: роль `user`,
 * содержимое — текст причины. Поэтому текст начинается пометкой сторожа, а
 * вид источника свой (`reglament`) — по ним видно, что писал не пользователь.
 *
 * @param {string} текст — причина возврата (текст правила)
 * @param {string} [id] — идентификатор сообщения (в самопроверке задаётся свой)
 */
export function сообщениеСторожа(текст, id = randomUUID()) {
  return заморозить({
    id,
    role: 'user',
    content: [{ type: 'text', text: `${ПОМЕТКА_СТОРОЖА} ${String(текст ?? '').trim()}` }],
    source: { ...ИСТОЧНИК_СТОРОЖА },
  });
}
