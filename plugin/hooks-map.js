// Единственное место, где записано, какие правила-проверки стоят на каком событии.
//
// Зачем отдельный файл. Список ворот знали трое — слой совместимости
// (`hooks-bridge.js`), самопроверка (`self-test.mjs`) и текст навыка, — и
// расхождение между ними было ТИХИМ: правило живёт в хуке, второй раз в мосте,
// третий раз в навыке (дефект D13). Теперь состав здесь, один раз; мост берёт его
// отсюда, а самопроверка следит, чтобы ни один файл в папке хуков не остался
// забытым: каждый обязан быть либо в карте, либо в списке «зовут не ворота».
//
// Здесь только данные и чистые функции: ничего не запускается, ничего не пишется.

/** Папка хуков в развёрнутом проекте — одна на все правила. */
export const ПАПКА_ХУКОВ = '.reglament/hooks';

/**
 * Хуки, которые прежняя среда зовёт ПЕРЕД вызовом инструмента, по именам
 * инструментов ПРЕЖНЕЙ среды (`Write`, `PowerShell`, …). Порядок важен: тесты и
 * ссылка на vault идут до проверки оболочки.
 */
export const ВОРОТА_ПЕРЕД = {
  Bash: ['pre-commit-tests.sh', 'check_commit.py', 'gate_shell.py'],
  PowerShell: ['pre-commit-tests.sh', 'check_commit.py', 'gate_shell.py'],
  Write: ['gate_edit.py'],
  Edit: ['gate_edit.py'],
};

/**
 * Хуки ПОСЛЕ вызова: постоянные (для инструмента) и те, что зависят от того,
 * какой файл правили (`.py` — проверка питона, `.js` — синтаксис JS).
 */
export const ВОРОТА_ПОСЛЕ = {
  Bash: { постоянные: ['gate_shell.py'] },
  PowerShell: { постоянные: ['gate_shell.py'] },
  Write: {
    по_суффиксу: {
      '.py': ['post-edit-python.sh'],
      '.js': ['post-edit-js.sh'],
    },
  },
  Edit: {
    по_суффиксу: {
      '.py': ['post-edit-python.sh'],
      '.js': ['post-edit-js.sh'],
    },
  },
};

/** Хуки конца хода (у прежней среды — событие `Stop`). */
export const ВОРОТА_ОСТАНОВКИ = ['check_turn_end.py'];

/**
 * Файлы в папке хуков, которых ворота НЕ зовут, — и почему.
 *
 * Это не «забыли», а решение: закрытие задачи зовёт ассистент по навыку, а
 * валидатор vault зовут контролёр коммита и автозакрытие. Появится в папке новый
 * файл — самопроверка потребует назвать его здесь или внести в карту.
 */
export const ЗОВУТ_НЕ_ВОРОТА = {
  'close_task.py': 'зовёт ассистент по навыку (шаг закрытия)',
  'validate_vault.py': 'зовут check_commit.py и close_task.py',
};

/**
 * Проверки необратимых действий: их сбой — не «пропустить».
 *
 * Коммит без проверки не считается сделанным, а «неизвестно» (проверка упала)
 * разрешением там не считается — решение М2.4.
 */
export const СТРОГИЕ = ['pre-commit-tests.sh', 'check_commit.py'];

/** Описание одного хука в том виде, в каком его ждёт запускающий. */
export function описаниеХука(файл) {
  return {
    скрипт: `${ПАПКА_ХУКОВ}/${файл}`,
    тип: файл.endsWith('.sh') ? 'sh' : 'py',
    строго: СТРОГИЕ.includes(файл),
  };
}

/** Хуки перед вызовом по имени инструмента прежней среды. */
export function воротаПеред(имя) {
  return (ВОРОТА_ПЕРЕД[имя] ?? []).map(описаниеХука);
}

/** Хуки после вызова по имени инструмента прежней среды и аргументам вызова. */
export function воротаПосле(имя, аргументы) {
  const описание = ВОРОТА_ПОСЛЕ[имя];
  if (!описание) return [];
  const файлы = [...(описание.постоянные ?? [])];
  const путь = String(аргументы?.file_path ?? '').toLowerCase();
  for (const [суффикс, список] of Object.entries(описание.по_суффиксу ?? {})) {
    if (путь.endsWith(суффикс)) файлы.push(...список);
  }
  return файлы.map(описаниеХука);
}

/** Хуки конца хода. */
export function воротаОстановки() {
  return ВОРОТА_ОСТАНОВКИ.map(описаниеХука);
}
