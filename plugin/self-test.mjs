// Самопроверка слоя совместимости — без запуска ДСХ.
//
// Запуск:  node .dsh/plugin-reglament/self-test.mjs
// Проверяются чистые части: перевод вызова ДСХ во вход хука, состав и порядок
// хуков, перевод ответа хука в решение, разбор ответа карточки, штамп табло,
// конец хода (вход «Stop», ответ хука, сообщение сторожа), предохранитель от
// петли и ворота карточки согласования (проект заметки показывается первым).
// Сами правила живут в `.reglament/hooks/*` и здесь не дублируются.

import assert from 'node:assert/strict';

import {
  ИМЯ_ИНСТРУМЕНТА,
  ПОМЕТКА_СТОРОЖА,
  перевестиКомандуКоммита,
  решениеПоОстановке,
  решениеПоХуку,
  собратьPayload,
  собратьPayloadОстановки,
  сообщениеСторожа,
  текстРеплики,
  хукиОстановки,
  хукиПередВызовом,
  хукиПослеВызова,
} from './hooks-bridge.js';
import { ВАРИАНТ_СОГЛАСИЯ, найтиСогласие, разобратьОтвет, штампСогласования } from './approval.js';
import { ТЕКСТ_ОТКАЗА, карточкаСогласования, проектПоказан, учётПоказа } from './card-guard.js';
import { учётВозвратов } from './stop-guard.js';
import { проверитьBash, прогнатьКанарейку } from './canary.js';

let пройдено = 0;
const провалы = [];

function случай(имя, проверка) {
  try {
    проверка();
    пройдено++;
  } catch (ошибка) {
    провалы.push(`${имя}: ${ошибка.message}`);
  }
}

// ── перевод вызова во вход хука ─────────────────────────────────────────────
случай('write переводится в Write', () => {
  assert.equal(ИМЯ_ИНСТРУМЕНТА.write, 'Write');
});
случай('pwsh переводится в PowerShell', () => {
  assert.equal(ИМЯ_ИНСТРУМЕНТА.pwsh, 'PowerShell');
});
