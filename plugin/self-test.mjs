// ── предохранитель от петли ─────────────────────────────────────────────────
случай('предохранитель считает возвраты на ход', () => {
  const учёт = учётВозвратов({ потолок: 2 });
  assert.equal(учёт.можноВозвращать('с1', 1), true);
  assert.equal(учёт.записатьВозврат('с1', 1), 1);
  assert.equal(учёт.записатьВозврат('с1', 1), 2);
  assert.equal(учёт.можноВозвращать('с1', 1), false);
  assert.equal(учёт.повтор('с1', 1), 2);
});
случай('новый ход — запас снова полный', () => {
  const учёт = учётВозвратов({ потолок: 1 });
  учёт.записатьВозврат('с1', 1);
  assert.equal(учёт.можноВозвращать('с1', 1), false);
  assert.equal(учёт.можноВозвращать('с1', 2), true);
  assert.equal(учёт.можноВозвращать('с2', 1), true);
});
случай('сессия закрыта — её счётчики забыты', () => {
  const учёт = учётВозвратов({ потолок: 1 });
  учёт.записатьВозврат('с1', 1);
  учёт.записатьВозврат('с2', 1);
  учёт.забытьСессию('с1');
  assert.equal(учёт.можноВозвращать('с1', 1), true);
  assert.equal(учёт.можноВозвращать('с2', 1), false);
});
случай('негодный потолок — берём общий', () => {
  assert.equal(учётВозвратов({ потолок: 0 }).потолок, 2);
  assert.equal(учётВозвратов({ потолок: -1 }).потолок, 2);
  assert.equal(учётВозвратов().потолок, 2);
});

