// ── команда нашего коммита: правила должны видеть git commit ────────────────
случай('команда нашего коммита переводится в git commit', () => {
  assert.equal(
    перевестиКомандуКоммита(
      'venv\\Scripts\\python.exe .dsh\\tools\\git_commit.py -m "правка (vault: «Заметка»)"',
    ),
    'git commit -m "правка (vault: «Заметка»)"',
  );
});
случай('перевод идёт по отрезкам: git add остаётся как был', () => {
  assert.equal(
    перевестиКомандуКоммита(
      'git add docs/x.md ; venv\\Scripts\\python.exe .dsh/tools/git_commit.py -m "x"',
    ),
    'git add docs/x.md ; git commit -m "x"',
  );
});
случай('вызов без интерпретатора тоже переводится', () => {
  assert.equal(перевестиКомандуКоммита('.dsh/tools/git_commit.py --amend'), 'git commit --amend');
});
случай('команда двумя строками тоже переводится (живая находка 04.10.2026)', () => {
  assert.equal(
    перевестиКомандуКоммита(
      'git add docs/x.md\nvenv\\Scripts\\python.exe .dsh/tools/git_commit.py -m "x"',
    ),
    'git add docs/x.md\ngit commit -m "x"',
  );
  assert.equal(
    перевестиКомандуКоммита('git add docs/x.md\r\npython .dsh/tools/git_commit.py -m "x"'),
    'git add docs/x.md\r\ngit commit -m "x"',
  );
});
случай('упоминание имени файла командой не считается', () => {
  assert.equal(
    перевестиКомандуКоммита('echo .dsh/tools/git_commit.py'),
    'echo .dsh/tools/git_commit.py',
  );
});
случай('чужой инструмент и обычный git commit не переводятся', () => {
  assert.equal(
    перевестиКомандуКоммита('python .dsh/tools/close_task.py --desc "x"'),
    'python .dsh/tools/close_task.py --desc "x"',
  );
  assert.equal(перевестиКомандуКоммита('git commit -m "x"'), 'git commit -m "x"');
});
случай('вход команды несёт переведённый коммит, исходные аргументы целы', () => {
  const аргументы = { command: 'python .dsh/tools/git_commit.py -m "x"', description: 'коммит' };
  const payload = собратьPayload({ инструмент: 'pwsh', аргументы, корень: 'D:/п' });
  assert.equal(payload.tool_input.command, 'git commit -m "x"');
  assert.equal(payload.tool_input.description, 'коммит');
  assert.equal(аргументы.command, 'python .dsh/tools/git_commit.py -m "x"');
});
случай('вход правки файла перевода не знает', () => {
  const payload = собратьPayload({
    инструмент: 'write',
    аргументы: { file_path: 'a.py', content: 'путь .dsh/tools/git_commit.py в тексте' },
    корень: 'D:/п',
  });
  assert.equal(payload.tool_input.content, 'путь .dsh/tools/git_commit.py в тексте');
});

