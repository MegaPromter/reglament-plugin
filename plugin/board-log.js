// Порядок в табло задачи: метка времени фазы и отпечаток согласованной заметки.
//
// Зачем. Табло знает фазу, но не знает, С КОГДА она стоит, — «задача висит»
// измерить нечем (дефект D11). И оно не помнит, какую версию заметки человек
// согласовал, — «согласовали одно, делают другое» не видно (дефект D8).
//
// Табло правит сам сторож: тогда отметка появляется и когда табло писали руками
// через инструмент правки, и ассистенту не нужно помнить про отметки.
//
// Здесь только чистые функции: файлы читает и пишет вызывающий.

import { createHash } from 'node:crypto';

/** Сколько переходов фаз помним: табло — не летопись, старая история живёт в vault. */
export const ПРЕДЕЛ_ИСТОРИИ = 20;

/** Момент времени в виде «2026-10-11T10:55:00+03:00». */
export function моментСейчас(дата = new Date()) {
  const смещение = -дата.getTimezoneOffset();
  const знак = смещение >= 0 ? '+' : '-';
  const часы = String(Math.floor(Math.abs(смещение) / 60)).padStart(2, '0');
  const минуты = String(Math.abs(смещение) % 60).padStart(2, '0');
  const местное = new Date(дата.getTime() - дата.getTimezoneOffset() * 60000);
  return `${местное.toISOString().slice(0, 19)}${знак}${часы}:${минуты}`;
}

/** Отпечаток текста: по нему видно, менялся ли он после согласования. */
export function отпечатокТекста(текст) {
  return createHash('sha1')
    .update(String(текст ?? ''), 'utf8')
    .digest('hex');
}

/**
 * Табло с меткой времени фазы.
 *
 * Фаза та же — табло не трогаем: иначе каждая правка табло выглядела бы
 * переходом. Возвращает `{ табло, изменено, переход }`: `переход` — фаза
 * действительно сменилась, и об этом стоит оставить строку в истории.
 */
export function сОтметкойФазы(табло, момент = моментСейчас()) {
  const фаза = String(табло?.фаза ?? '');
  if (!фаза) return { табло, изменено: false, переход: false };
  const история = Array.isArray(табло?.история_фаз) ? табло.история_фаз : [];
  const последняя = история[история.length - 1];
  if (последняя && последняя.фаза === фаза && табло?.фаза_с) {
    return { табло, изменено: false, переход: false };
  }
  const новая = [...история, { фаза, с: момент }].slice(-ПРЕДЕЛ_ИСТОРИИ);
  return {
    табло: { ...табло, фаза_с: момент, история_фаз: новая },
    изменено: true,
    переход: true,
  };
}

/**
 * Строка версионируемой истории переходов — одна запись, одна строка JSON.
 *
 * Состояние петли живёт вне git (табло — рабочее), а след остаётся в файле,
 * который коммитится: по нему видно, когда и в какой фазе встала задача
 * (решение О2).
 */
export function строкаИстории(табло, момент) {
  return JSON.stringify({
    задача: табло?.задача ?? '',
    фаза: табло?.фаза ?? '',
    форма: табло?.форма ?? 'полная',
    с: момент,
  });
}

/**
 * Табло с отпечатком заметки, которую согласовали.
 *
 * Пустой отпечаток — «ещё не поставлен»: заметку в регламенте сохраняют ПОСЛЕ
 * согласования, поэтому в момент штампа файла может ещё не быть. Ставим отпечаток
 * при первой же записи заметки и потом не трогаем: он и должен устареть, если
 * заметку правят.
 */
export function сОтпечаткомЗаметки(табло, текст) {
  if (табло?.одобрено !== true) return { табло, изменено: false };
  if (String(табло?.одобрено_заметкой ?? '')) return { табло, изменено: false };
  if (!String(текст ?? '')) return { табло, изменено: false };
  return {
    табло: { ...табло, одобрено_заметкой: отпечатокТекста(текст) },
    изменено: true,
  };
}
