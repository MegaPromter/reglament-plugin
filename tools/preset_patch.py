"""Слой пакета сторожа: свой пресет агента для рабочего профиля.

Зачем. Строку плагина в существующий пресет ДСХ вставить нельзя: пресет — не группа
(опыт отвечает `patch insert: entry "preset-standard" is not a group`), а его плагины
патчу не адресуются. Значит строка добавляется только переносом определения пресета
целиком. Чтобы это не писалось руками и не отставало от обновлений ДСХ, слой собирает
этот скрипт из свежего слепка сборки.

Что получается (`DSH_REPORT.md`, раздел 26; ADR «Пресет сторожа в слое пакета»):

- новый пресет `reglament` — копия пресета `standard` плюс строка нашего плагина;
- `agent-preset-registry` переключается на `reglament` (пресет по умолчанию);
- пресет `standard` НЕ переписывается: чужое имя не занимаем.

Запуск (слепок снимается командой оболочки, скрипт его только читает):

    dsh preset-refresh --from-default-profile web --dump-config > слепок.yml
    python .dsh/tools/preset_patch.py --слепок слепок.yml

**Цена, названная заранее:** список плагинов пресета замирает в слое. После обновления
ДСХ прогонять скрипт заново и сверять слепки — иначе новый инструмент появится у ДСХ,
но не у нас, и это будет тихой потерей.
"""

import argparse
import re
import sys
from pathlib import Path

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЛОЙ = КОРЕНЬ / ".dsh" / "plugin-reglament" / "cordis.patch.yml"

# Строка плагина: имя пакета и его идентификатор в дереве.
ИМЯ_ПЛАГИНА = "@local/dsh-plugin-reglament"
ИД_ПЛАГИНА = "plugin-reglament"

ПРЕСЕТ_ОСНОВА = "standard"
ПРЕСЕТ_СВОЙ = "reglament"
ПОРЯДОК = 9  # свой пресет — в конце списка, чтобы не переставлять чужие

ШАПКА = """# Слой пакета сторожа регламента: свой пресет агента для рабочего профиля.
#
# Файл СОБИРАЕТСЯ скриптом — руками не править:
#   python .dsh/tools/preset_patch.py --слепок <слепок сборки ДСХ>
#
# Вставить строку плагина в существующий пресет нельзя (пресет — не группа, его
# плагины патчу не адресуются), поэтому определение пресета {основа} перенесено сюда
# целиком и дополнено строкой плагина. После обновления ДСХ слой пересобрать и
# сверить слепки: иначе новый инструмент появится у ДСХ, но не у нас.
"""


def блок_пресета(строки: list[str], основа: str = ПРЕСЕТ_ОСНОВА) -> list[str]:
    """Строки определения пресета из слепка сборки (без строки с его id)."""
    начало = next(
        (
            номер
            for номер, строка in enumerate(строки)
            if строка.startswith(f"- id: preset-{основа}")
        ),
        None,
    )
    if начало is None:
        raise SystemExit(f"в слепке нет пресета preset-{основа} — сборка не та")
    конец = next(
        (
            номер
            for номер in range(начало + 1, len(строки))
            if строки[номер].startswith("- ")
        ),
        len(строки),
    )
    return строки[начало + 1 : конец]


# Выражение ДСХ в слепке выглядит тегом `!!js <выражение>`. В слое пакета тег писать
# нельзя: проверка YAML в репозитории (`check-yaml` хука коммита) его не разбирает.
# Инертная форма того же выражения — `{__jsExpr: <выражение>}`: смысл тот же
# (проверено сравнением слепков — они совпадают полностью), а разбирает её любой
# разборщик YAML.
ВЫРАЖЕНИЕ_ДСХ = re.compile(r"^(\s*)([A-Za-z_][\w-]*):\s*!!js\s+(.+)$")


def развернуть_выражения(строка: str) -> list[str]:
    """Тег `!!js` → инертная форма `__jsExpr` (смысл не меняется)."""
    найдено = ВЫРАЖЕНИЕ_ДСХ.match(строка)
    if not найдено:
        return [строка]
    отступ, ключ, выражение = найдено.groups()
    безопасное = выражение.replace("'", "''")
    return [f"{отступ}{ключ}:", f"{отступ}  __jsExpr: '{безопасное}'"]


def собрать_слой(
    строки: list[str],
    свой: str = ПРЕСЕТ_СВОЙ,
    основа: str = ПРЕСЕТ_ОСНОВА,
    порядок: int = ПОРЯДОК,
) -> list[str]:
    """Слой наложения: свой пресет со строкой плагина и переключение умолчания."""
    тело: list[str] = []
    for строка in блок_пресета(строки, основа):
        if not строка.strip():
            тело.append(строка)
            continue
        тело += ["    " + часть for часть in развернуть_выражения(строка)]
    тело = [
        f"        id: {свой}" if строка == f"        id: {основа}" else строка
        for строка in тело
    ]
    тело = [
        f"        order: {порядок}" if строка.startswith("        order: ") else строка
        for строка in тело
    ]
    return [
        ШАПКА.format(основа=основа).rstrip("\n"),
        "- insert:",
        f"    - id: preset-{свой}",
        *тело,
        f"          - id: {ИД_ПЛАГИНА}",
        f"            name: '{ИМЯ_ПЛАГИНА}'",
        "- id: agent-preset-registry",
        "  config:",
        f"    default: {свой}",
    ]


def main() -> int:
    разбор = argparse.ArgumentParser(description="собрать слой пакета сторожа")
    разбор.add_argument("--слепок", required=True, help="файл слепка сборки ДСХ")
    разбор.add_argument("--выход", default=str(СЛОЙ), help="куда положить слой")
    разбор.add_argument("--пресет", default=ПРЕСЕТ_СВОЙ, help="имя своего пресета")
    разбор.add_argument("--основа", default=ПРЕСЕТ_ОСНОВА, help="пресет-основа")
    разбор.add_argument("--порядок", type=int, default=ПОРЯДОК, help="порядок в списке")
    аргументы = разбор.parse_args()

    слепок = Path(аргументы.слепок)
    if not слепок.is_file():
        print(f"нет файла слепка: {слепок}")
        return 1

    строки = слепок.read_text(encoding="utf-8").splitlines()
    слой = собрать_слой(строки, аргументы.пресет, аргументы.основа, аргументы.порядок)
    выход = Path(аргументы.выход)
    выход.write_text("\n".join(слой) + "\n", encoding="utf-8", newline="\n")
    print(f"слой собран: {выход} — строк {len(слой)}")
    print(f"пресет {аргументы.пресет}: копия {аргументы.основа} плюс {ИМЯ_ПЛАГИНА}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
