"""Проверка табло задачи против реальности — числа, а не «на глаз».

Зачем. Табло (`.reglament/task-state.json`) — ярлык: в нём написано, в какой фазе
задача и какой заметке она соответствует. Разошлось с диском — и всё принуждение
начинает верить ярлыку (дефект D12): фаза «код», а заметки нет; фаза «тесты», а
статус заметки «запланировано». Заметить это глазами можно, но только если
вспомнить; измеритель считает.

Что проверяется:
  1. заметка из табло существует — для фаз от «согласовано» и дальше (в фазе
     «заметка» её ещё не сохраняют: сначала согласование);
  2. статус заметки соответствует фазе;
  3. сколько стоит текущая фаза (по отметке сторожа `фаза_с`) — число, а не
     «давно»;
  4. менялась ли заметка после согласования (отпечаток `одобрено_заметкой`);
  5. не закоммиченные правки кода — списком (это сигнал, а не нарушение).

Запуск:  python .dsh/tools/board_check.py
Код выхода: 0 — расхождений нет; 1 — табло и реальность разошлись.

Фазы от «согласовано»: заметка обязана быть и стоять «в работе».
"""

import json
import os
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pre_commit_cache import КОРЕНЬ as КОРЕНЬ_ПО_РАСКЛАДКЕ  # noqa: E402
import phase_rules  # noqa: E402 — лежит рядом, в той же папке инструментов

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

# Корень — как у хуков: сначала переменная среды, потом место инструмента.
# Переменная нужна самопроверке и запуску по чужому проекту.
КОРЕНЬ = Path(os.environ.get("REGLAMENT_PROJECT_DIR") or КОРЕНЬ_ПО_РАСКЛАДКЕ)
ТАБЛО = КОРЕНЬ / ".reglament" / "task-state.json"

# Фазы, в которых заметка уже обязана лежать в vault со статусом «в работе».
ФАЗЫ_С_ЗАМЕТКОЙ = ("согласовано", "код", "тесты", "коммит")
# Фазы, где заметки может ещё не быть: её сохраняют после согласования.
ФАЗЫ_БЕЗ_ЗАМЕТКИ = ("vault", "заметка")

# Сколько часов в одной фазе считаем нормой, а больше — поводом сказать вслух.
ПОРОГ_ЧАСОВ_ФАЗЫ = 24

СТАТУС = re.compile(r"^статус:\s*(.+?)\s*$", re.M)
ОТПЕЧАТОК = re.compile(r"^одобрено_заметкой:\s*(\S*)\s*$", re.M)


def табло() -> dict:
    """Табло задачи; нет файла или испорчено — пустое."""
    if not ТАБЛО.exists():
        return {}
    try:
        return json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return {}


def статус_заметки(путь: Path) -> str:
    """Статус из шапки заметки; нет файла — пусто."""
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError:
        return ""
    найдено = СТАТУС.search(текст)
    return найдено.group(1).strip() if найдено else ""


def отпечаток_текста(текст: str) -> str:
    """Отпечаток текста — тот же, что ставит сторож (`board-log.js`)."""
    import hashlib

    return hashlib.sha1(текст.encode("utf-8")).hexdigest()


def часов_в_фазе(табло_задачи: dict) -> float | None:
    """Сколько часов стоит текущая фаза; отметки нет — None."""
    отметка = str(табло_задачи.get("фаза_с") or "")
    if not отметка:
        return None
    try:
        момент = datetime.fromisoformat(отметка)
    except ValueError:
        return None
    if момент.tzinfo is None:
        момент = момент.astimezone()
    разница = datetime.now().astimezone() - момент
    return round(разница.total_seconds() / 3600, 1)


def грязный_код() -> list[str]:
    """Файлы кода, отличающиеся от последнего коммита (документация не в счёт)."""
    try:
        итог = subprocess.run(
            ["git", "--no-optional-locks", "-C", str(КОРЕНЬ), "status", "--porcelain"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=20,
        )
    except Exception:
        return []
    if итог.returncode != 0:
        return []
    файлы = []
    for строка in итог.stdout.splitlines():
        if len(строка) < 4:
            continue
        путь_файла = строка[3:].strip().strip('"').replace("\\", "/")
        нижний = путь_файла.lower()
        if нижний.startswith(("docs/", ".reglament/")):
            continue
        файлы.append(путь_файла)
    return файлы


def main() -> int:
    борт = табло()
    задача = борт.get("задача")
    if not задача:
        print("Активной задачи в табло нет — сверять нечего.")
        return 0

    фаза = str(борт.get("фаза") or "")
    форма = str(борт.get("форма") or "полная")
    нарушения: list[str] = []
    предупреждения: list[str] = []

    print(f"Задача «{задача}»: форма {форма}, фаза «{фаза or '—'}»")
    if борт.get("ждёт"):
        print(f"  ждёт: {борт['ждёт']}")

    заметка = КОРЕНЬ / str(борт.get("заметка") or "")
    if фаза in ФАЗЫ_С_ЗАМЕТКОЙ:
        if not борт.get("заметка"):
            нарушения.append("в табло не названа заметка, а фаза уже после согласования")
        elif not заметка.is_file():
            нарушения.append(f"заметки нет на диске: {заметка}")
        else:
            статус = статус_заметки(заметка)
            if статус != "в работе":
                нарушения.append(
                    f"фаза «{фаза}», а статус заметки «{статус or 'не найден'}» "
                    "(ожидается «в работе»)"
                )
    elif фаза in ФАЗЫ_БЕЗ_ЗАМЕТКИ:
        print("  заметку в этой фазе ещё не сохраняют — так и задумано")
    elif фаза:
        предупреждения.append(f"фаза «{фаза}» не из словаря фаз")

    # Шаг фазы — смешанный предикат (решение О1): факт где есть, отметка где нет.
    # Здесь это ОТЧЁТ, а не запрет: фаза называет текущий шаг, и «коммита ещё нет»
    # в фазе «коммит» — норма. Запрет живёт в автозакрытии.
    состояния = phase_rules.состояния_задачи(
        борт, заметка.is_file(), статус_заметки(заметка)
    )
    вердикт = phase_rules.вердикт(фаза, состояния)
    if вердикт["сделан"] is None:
        print("  шаг фазы: правил для этой фазы нет")
    else:
        print(f"  шаг фазы: {'сделан' if вердикт['сделан'] else 'не сделан'}")
        for имя in вердикт["не_сделано"]:
            print(f"    ✗ не сделано: {phase_rules.ОПИСАНИЕ.get(имя, имя)}")
        for имя in вердикт["неизвестно"]:
            print(f"    ? не проверить: {phase_rules.ОПИСАНИЕ.get(имя, имя)}")

    часов = часов_в_фазе(борт)
    if часов is None:
        print("  метки времени фазы нет: поставить её может только сторож нового слоя")
    else:
        print(f"  фаза стоит {часов} ч (отметка {борт.get('фаза_с')})")
        if часов > ПОРОГ_ЧАСОВ_ФАЗЫ:
            предупреждения.append(
                f"фаза «{фаза}» стоит {часов} ч при пороге {ПОРОГ_ЧАСОВ_ФАЗЫ}"
            )

    история = борт.get("история_фаз")
    if isinstance(история, list) and история:
        путь_фаз = " → ".join(str(звено.get("фаза", "?")) for звено in история)
        print(f"  путь фаз: {путь_фаз}")

    if заметка.is_file():
        отпечаток_в_табло = str(борт.get("одобрено_заметкой") or "")
        if отпечаток_в_табло:
            сейчас = отпечаток_текста(заметка.read_text(encoding="utf-8"))
            if сейчас != отпечаток_в_табло:
                предупреждения.append(
                    "заметка изменилась после согласования: человек согласовал "
                    f"версию {отпечаток_в_табло[:8]}, на диске {сейчас[:8]} — покажи "
                    "изменения и спроси заново"
                )
        elif борт.get("одобрено") is True:
            print("  отпечатка согласованной заметки нет: штамп поставлен до этой проверки")

    файлы = грязный_код()
    if файлы:
        перечень = ", ".join(файлы[:10]) + (" …" if len(файлы) > 10 else "")
        print(f"  не закоммичено файлов кода: {len(файлы)} ({перечень})")

    for предупреждение in предупреждения:
        print(f"⚠ {предупреждение}")
    for нарушение in нарушения:
        print(f"✗ {нарушение}")

    if нарушения:
        print(f"\nТабло расходится с реальностью: {len(нарушения)} нарушение(й).")
        return 1
    if предупреждения:
        print(f"\nТабло сходится; предупреждений: {len(предупреждения)}.")
        return 0
    print("\nТабло сходится с реальностью.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
