"""Склад проверяльщика pre-commit для ДСХ — свой, чужого не используем.

Зачем он вообще нужен. Перед коммитом git зовёт проверяльщика `pre-commit`,
а тот держит свои окружения хуков в «складе». По умолчанию склад лежит в
`~/.cache/pre-commit` — вне рабочей папки, а ДСХ не даёт дочерним процессам
писать за её пределы: проверяльщик падает, коммит не создаётся (разбор —
`DSH_REPORT.md`, раздел 20).

Решение: склад живёт **внутри рабочей папки** проекта — `.pre-commit-home/`
(в репозиторий не попадает, строка в `.gitignore`). Установка окружений в ДСХ
зависает, поэтому склад не собирается заново, а **копируется** из готового.

Источники — только свои, дээсэхашные. Решение пользователя 04.10.2026: на
прежнюю среду не рассчитываем, его склад не используем.

1. **Мастер-склад в доме ДСХ** — `<дом ДСХ>/pre-commit-cache`. Наполняется один
   раз вне ДСХ: внутри ДСХ писать в дом нельзя.
2. **Склады соседних проектов ДСХ** — у каждого проекта своя папка
   `.pre-commit-home`; годится любой пригодный.

Из пригодных берётся **самый свежий** (по времени правки базы): так меньше
шансов взять устаревшие окружения, из-за которых проверяльщик захочет
доустановить их и зависнет.

Файл — и библиотека, и команда:

    python .dsh/tools/pre_commit_cache.py        # подготовить склад в этом проекте
"""

import os
import shutil
import sys
from pathlib import Path

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

ИМЯ_СКЛАДА = ".pre-commit-home"


def корень_проекта() -> Path:
    """Корень проекта по месту инструмента.

    Раскладок две, и они различаются на один уровень: в развёрнутом проекте
    инструмент лежит в `<проект>/.dsh/tools/`, в исходниках комплекта —
    в `<комплект>/tools/`. Без этой развилки запущенный из исходников инструмент
    искал бы корень на уровень выше (найдено 11.10.2026: отчёт по журналу искал
    журнал в `D:\\Program\\.dsh`, а не в проекте регламента).
    """
    здесь = Path(__file__).resolve()
    if здесь.parents[1].name == ".dsh":
        return здесь.parents[2]
    return здесь.parents[1]


КОРЕНЬ = корень_проекта()

# Дом ДСХ: там же лежит его мастер-склад (наполняется вне ДСХ).
ДОМ_ДСХ = Path(os.environ.get("DSH_HOME") or (Path.home() / ".dsh"))
МАСТЕР_СКЛАД = ДОМ_ДСХ / "pre-commit-cache"


def _пригоден(склад: Path) -> bool:
    """В складе есть база и хотя бы одно окружение — значит им можно пользоваться."""
    return (склад / "db.db").is_file() and any(склад.glob("repo*"))


def _свежесть(склад: Path) -> float:
    """Время правки базы склада — по нему выбираем самый свежий источник."""
    return (склад / "db.db").stat().st_mtime


def _кандидаты(корень: Path) -> list[Path]:
    """Свои склады ДСХ: мастер-склад в доме и склады соседних проектов."""
    свои = [МАСТЕР_СКЛАД]
    try:
        свои += [
            папка / ИМЯ_СКЛАДА for папка in корень.parent.iterdir() if папка.is_dir()
        ]
    except OSError:
        pass  # соседние папки недоступны — обойдёмся мастер-складом
    return [склад for склад in свои if склад != корень / ИМЯ_СКЛАДА]


def _источник(корень: Path) -> Path | None:
    """Самый свежий пригодный склад ДСХ или None, если своих складов нет."""
    пригодные = [склад for склад in _кандидаты(корень) if _пригоден(склад)]
    if not пригодные:
        return None
    return max(пригодные, key=_свежесть)


def обеспечить_склад(корень: Path = КОРЕНЬ, сказать=print) -> Path:
    """Склад в рабочей папке: есть — вернуть, нет — скопировать готовый.

    Копирование занимает секунды (сотни мегабайт локально) и заменяет
    установку окружений, которая в ДСХ зависает.
    """
    склад = корень / ИМЯ_СКЛАДА
    if _пригоден(склад):
        return склад

    источник = _источник(корень)
    if источник is None:
        raise SystemExit(
            "Своего склада проверяльщика нет — копировать неоткуда. "
            "Подготовьте мастер-склад один раз ВНЕ ДСХ (внутри ДСХ установка "
            "окружений зависает, а писать в дом ДСХ нельзя):\n"
            f'  $env:PRE_COMMIT_HOME = "{МАСТЕР_СКЛАД}"\n'
            "  pre-commit install-hooks\n"
            "После этого любой проект ДСХ будет копировать склад из дома "
            "(DSH_REPORT.md, раздел 20)."
        )

    сказать(f"Склада нет — копирую готовый: {источник} → {склад}")
    склад.mkdir(parents=True, exist_ok=True)
    for репозиторий in источник.glob("repo*"):
        shutil.copytree(репозиторий, склад / репозиторий.name, dirs_exist_ok=True)
    shutil.copy2(источник / "db.db", склад / "db.db")
    сказать(f"Склад проверяльщика готов: {склад}")
    return склад


def среда_со_складом(корень: Path = КОРЕНЬ) -> dict[str, str]:
    """Окружение процесса с указанием склада — его наследует проверяльщик."""
    среда = os.environ.copy()
    среда["PRE_COMMIT_HOME"] = str(обеспечить_склад(корень))
    return среда


def main() -> int:
    склад = обеспечить_склад()
    print(f"PRE_COMMIT_HOME={склад}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
