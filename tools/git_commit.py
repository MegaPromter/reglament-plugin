"""Коммит из ДСХ: свой путь, проверяльщик работает, обходов нет.

Отличие от обычного `git commit` ровно одно: перед вызовом git готовится
склад проверяльщика внутри рабочей папки и подставляется переменной
`PRE_COMMIT_HOME` (см. `.dsh/tools/pre_commit_cache.py` и `DSH_REPORT.md`,
раздел 20). Всё остальное делает сам git — хуки, проверки, отказ при
красном.

Запуск (аргументы передаются `git commit` как есть):

    python .dsh/tools/git_commit.py -m "сообщение"

Обход проверок (`--no-verify`) запрещён решением пользователя: коммит без
проверок не считается сделанным. Если проверяльщик не сможет работать, скрипт
скажет об этом и коммита не будет.
"""

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pre_commit_cache import КОРЕНЬ, обеспечить_склад, среда_со_складом  # noqa: E402

ПОДСКАЗКА = 'нужно сообщение коммита: python .dsh/tools/git_commit.py -m "..."'


def main() -> int:
    аргументы = sys.argv[1:]
    if not аргументы:
        print(ПОДСКАЗКА)
        return 1

    обеспечить_склад(КОРЕНЬ)  # нет склада — скопируем готовый, а не будем ставить
    среда = среда_со_складом(КОРЕНЬ)

    # Потоки наследуются: вывод git и хуков виден как есть, без перекодировки.
    итог = subprocess.run(["git", "-C", str(КОРЕНЬ), "commit", *аргументы], env=среда)
    return итог.returncode


if __name__ == "__main__":
    sys.exit(main())
