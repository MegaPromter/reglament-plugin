"""Правила фаз: что обязано сойтись, чтобы шаг задачи считался сделанным.

Решение О1 — смешанный предикат: где факт есть, требуем факт; где факта нет —
отметку из «Как проверим». Так самая дорогая часть работы не закрывается одними
словами, а там, где команды нет, слова и остаются.

Читают правило двое: измеритель `board_check.py` (показывает состояние) и
автозакрытие `close_task.py` (отказывает, пока шаг не сделан). Таблица живёт здесь
одним местом — иначе она разъедется между потребителями (дефект D13).

Что сознательно НЕ требуется: зелёный прогон тестов как факт. Сторож не видит
результата чужой команды (канал вывода команды — отдельная незакрытая мера M0.6),
поэтому «тесты зелёные» пока остаётся словом ассистента, а не фактом.
"""

# Что требуется от фазы. Значения — имена требований, ключи `ОПИСАНИЕ`.
ТРЕБОВАНИЯ_ФАЗ = {
    "согласовано": ("заметка",),
    "код": ("заметка",),
    "тесты": ("заметка", "проверки"),
    "коммит": ("заметка", "проверки"),
}

ОПИСАНИЕ = {
    "заметка": "заметка существует и стоит «в работе»",
    "проверки": "пункты «Как проверим» отмечены в табло",
}

# Состояния требования.
ЕСТЬ = "есть"
НЕТ = "нет"
НЕИЗВЕСТНО = "неизвестно"


def состояние_проверок(табло: dict) -> str:
    """Отмечены ли пункты «Как проверим».

    Списка `проверки` в табло нет — «неизвестно»: интерфейс молодой, и требовать
    его у задач, начатых до него, значит валить закрытие на ровном месте.
    """
    проверки = табло.get("проверки")
    if not isinstance(проверки, list) or not проверки:
        return НЕИЗВЕСТНО
    return НЕТ if any(not пункт.get("сделано") for пункт in проверки) else ЕСТЬ


def состояние_заметки(заметка_есть: bool, статус: str) -> str:
    """Заметка на месте и в работе — этого достаточно для «есть»."""
    return ЕСТЬ if заметка_есть and статус == "в работе" else НЕТ


def вердикт(фаза: str, состояния: dict) -> dict:
    """Что с шагом фазы: `сделан`, чего не хватает и что не проверить.

    `сделан` = None — для фазы правил нет (vault, заметка, неизвестная фаза):
    судить не о чем.
    """
    требования = ТРЕБОВАНИЯ_ФАЗ.get(фаза)
    if not требования:
        return {"сделан": None, "не_сделано": [], "неизвестно": []}
    не_сделано = [т for т in требования if состояния.get(т) == НЕТ]
    неизвестно = [т for т in требования if состояния.get(т) == НЕИЗВЕСТНО]
    return {
        "сделан": not не_сделано,
        "не_сделано": не_сделано,
        "неизвестно": неизвестно,
    }


def словами(имена: list) -> str:
    """Имена требований — человеческим текстом, через запятую."""
    return ", ".join(ОПИСАНИЕ.get(имя, имя) for имя in имена)
