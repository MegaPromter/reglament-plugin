"""Отчёт по журналу сторожа — что сработало, а что промолчало.

Зачем. Журнал (`.dsh/plugin-reglament.log`) пишется на каждом решении сторожа, но
читают его глазами и редко. Сводка превращает журнал в числа: сколько ворот
сработало, сколько запретов, возвратов хода, согласований, предупреждений и —
главное — сколько ворот оказалось СЛЕПЫМИ. Без этого нечем управлять: не видно ни
цены ворот, ни их пользы.

Файл — и библиотека, и команда:

    python .dsh/tools/journal_report.py                 # весь журнал
    python .dsh/tools/journal_report.py --строк 200     # только последние 200 строк

Код выхода: 0 — слепых ворот и предупреждений нет; 1 — есть, на них и смотреть.

Ложные срабатывания машинно не считаются: «ложное» — суждение человека о том, что
запрет был не по делу. Сводка называет только то, что можно посчитать.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pre_commit_cache import КОРЕНЬ  # noqa: E402

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

ЖУРНАЛ_ПО_УМОЛЧАНИЮ = КОРЕНЬ / ".dsh" / "plugin-reglament.log"

# Бюджет шума (мера M3.2): сколько отказов и эскалаций на окно журнала считаем
# нормой. Превышение — повод ПЕРЕДЕЛАТЬ ворота, а не отключить: молча отключённые
# ворота дороже шумных. Числа названы и пересматриваются решением.
ПОРОГ_ОТКАЗОВ_НА_100_ПРОГОНОВ = 20
ПОРОГ_ЭСКАЛАЦИЙ = 3

# Классы строк журнала: имя → образец. Порядок — от тревожного к обычному.
ОБРАЗЦЫ = (
    ("ворот ослепли", r"ОСЛЕПЛИ"),
    ("команды не запускаются", r"команды в этой среде не запускаются"),
    ("инструмент слеп", r"СЛЕПО —"),
    ("канарейка ок", r"ок — "),
    ("предупреждения", r"ВНИМАНИЕ"),
    ("эскалации", r"эскалация:"),
    ("запреты", r"ЗАПРЕТ"),
    ("возвраты хода", r"ход возвращён"),
    ("предохранитель от петли", r"предохранитель сработал"),
    ("согласования", r"согласование задачи"),
    ("правки вне корня сторожа", r"правка вне корня сторожа"),
    ("прогоны хуков", r"хук \S+: код"),
    ("подключения сторожа", r"сторож регламента подключён"),
)

# Классы, из-за которых отчёт заканчивается тревогой: защиты нет или она слепа.
ТРЕВОЖНЫЕ = (
    "ворот ослепли",
    "команды не запускаются",
    "инструмент слеп",
    "правки вне корня сторожа",
)


def сводка(текст: str) -> dict[str, int]:
    """Числа по классам строк журнала — только то, что считается машинно."""
    строки = текст.splitlines()
    итог = {"всего строк": len(строки)}
    for имя, образец in ОБРАЗЦЫ:
        проверка = re.compile(образец)
        итог[имя] = sum(1 for строка in строки if проверка.search(строка))
    return итог


def тревожные(числа: dict[str, int]) -> list[str]:
    """Что требует внимания: слепые ворота, неработающие команды, чужие правки."""
    return [f"{имя}: {числа[имя]}" for имя in ТРЕВОЖНЫЕ if числа.get(имя)]


def шум_выше_бюджета(числа: dict[str, int]) -> list[str]:
    """Где шум перевалил бюджет: доля отказов и число эскалаций на окно журнала."""
    беды = []
    прогоны = числа.get("прогоны хуков", 0)
    отказы = числа.get("запреты", 0)
    if прогоны and отказы * 100 > ПОРОГ_ОТКАЗОВ_НА_100_ПРОГОНОВ * прогоны:
        доля = round(отказы * 100 / прогоны)
        беды.append(
            f"отказов {отказы} на {прогоны} прогонов ({доля}% при пороге "
            f"{ПОРОГ_ОТКАЗОВ_НА_100_ПРОГОНОВ}%)"
        )
    эскалации = числа.get("эскалации", 0)
    if эскалации > ПОРОГ_ЭСКАЛАЦИЙ:
        беды.append(f"эскалаций {эскалации} при пороге {ПОРОГ_ЭСКАЛАЦИЙ}")
    return беды


def main() -> int:
    разбор = argparse.ArgumentParser(description="отчёт по журналу сторожа")
    разбор.add_argument("--журнал", default=str(ЖУРНАЛ_ПО_УМОЛЧАНИЮ), help="файл журнала")
    разбор.add_argument(
        "--строк", type=int, default=0, help="смотреть только последние N строк"
    )
    аргументы = разбор.parse_args()

    путь = Path(аргументы.журнал)
    if not путь.is_file():
        print(f"Журнала нет: {путь} — сторож в этом проекте ничего не писал.")
        return 1
    текст = путь.read_text(encoding="utf-8", errors="replace")
    if аргументы.строк > 0:
        текст = "\n".join(текст.splitlines()[-аргументы.строк :])

    числа = сводка(текст)
    print(f"Журнал: {путь}")
    for имя, число in числа.items():
        print(f"  {имя}: {число}")

    беды_шума = шум_выше_бюджета(числа)
    if беды_шума:
        print("Шум выше бюджета: " + "; ".join(беды_шума))
        print(
            "  Это повод ПЕРЕДЕЛАТЬ ворота, а не отключить их: молча отключённые "
            "дороже шумных."
        )

    беды = тревожные(числа)
    if беды:
        print("ИТОГ: есть тревожное — " + "; ".join(беды))
        return 1
    print("ИТОГ: слепых ворот, чужих правок и предупреждений нет.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
