"""Проверка признаков «пора убрать память» — измеритель для навыка уборки.

Память проекта (`.dsh/memory/`) — быстрая рабочая копия знаний: оригинал лежит в
vault (`docs/vault/`). Память стареет незаметно: статус разрастается, один факт
появляется в двух файлах, числа расходятся с фактом, ссылки «Индекса» ведут в
никуда. Правило и признаки — ADR «Подсказка об уборке памяти».

Скрипт **только измеряет**: ничего не правит и не удаляет. Считать, а не
вспоминать, — его работа; решать и убирать — дело навыка `memory-cleanup`
(`.dsh/skills/memory-cleanup/SKILL.md`) и слова пользователя.

Файл — и библиотека, и команда:

    python .dsh/tools/memory_check.py            # отчёт по признакам
    python .dsh/tools/memory_check.py --числа    # ещё и список количеств для сверки
    python .dsh/tools/memory_check.py --копия    # отчёт и копия памяти перед уборкой

Код выхода: 0 — причин нет, 1 — причины есть (на них и надо смотреть).
"""

import re
import shutil
import sys
from datetime import date
from pathlib import Path

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПАМЯТЬ = КОРЕНЬ / ".dsh" / "memory"
ИНДЕКС = ПАМЯТЬ / "Индекс.md"
СТАТУС = ПАМЯТЬ / "Текущий статус.md"
КОПИИ = КОРЕНЬ / ".dsh"

# Пороги «пора убирать» живут ЗДЕСЬ, одним местом: решение и Регламент ссылаются
# на измеритель, а числа не повторяют (ADR «Подсказка об уборке памяти»:
# «часть порогов переедет в навык»).
ПОРОГ_СТРОК_СТАТУСА = 100
ПОРОГ_ДНЕЙ_С_УБОРКИ = 30

# Что считать кандидатом в дубли: короткая строка — обычные слова, а не факт.
ДЛИНА_СТРОКИ_ДУБЛЯ = 40

# Мелочи разбора текста. Дату уборки ищем без оглядки на регистр: в статусе она
# стоит с заглавной буквы («**Уборка памяти:** 04.10.2026»).
ДАТА_УБОРКИ = re.compile(
    r"уборка памяти[^\d]{0,20}(\d{2})\.(\d{2})\.(\d{4})", re.IGNORECASE
)
ССЫЛКА = re.compile(r"\]\(([^)#]+\.md)\)")
ПОМЕТКА_ДСХ = "в ДСХ этого нет"

# «Число-количество» — цифра вместе с единицей измерения: тесты, строки, файлы,
# размеры, проценты, минуты. Ищем не вообще числа (их в тексте сотни, и они
# безобидны: номера долгов, порты, коды ответов, хэши), а количества, которые
# обязаны сходиться с фактом. Одна единица с разными числами в двух файлах —
# верный признак устаревшего числа.
КОЛИЧЕСТВО = re.compile(
    r"(\d[\d\s]*(?:[.,]\d+)?)\s*"
    r"(тест\w*|строк\w*|файл\w*|мб|кб|гб|%|процент\w*|минут\w*)",
    re.IGNORECASE,
)
# Слова-оценки перед числом: «~500», «около 500». Приблизительное число не обязано
# сходиться с фактом, и совпадение двух оценок в разных файлах ничего не доказывает
# (ложное срабатывание 2026-10-04: «~500 строк» в цитате фантомного долга и в
# оценке объёма зачистки тестов). Такие числа в сверку не идут.
ПРИБЛИЗИТЕЛЬНО = ("~", "≈", "около", "примерно", "порядка")
СЛУЖЕБНОЕ = ("#", ">", "|", "```", "---", "тип:", "статус:", "создано:", "обновлено:")


def файлы_памяти() -> list[Path]:
    """Файлы памяти по алфавиту; папки нет — пустой список (о ней скажет отчёт)."""
    return sorted(ПАМЯТЬ.glob("*.md")) if ПАМЯТЬ.is_dir() else []


def текст(путь: Path) -> str:
    """Текст файла; файла нет — пустая строка, а не падение."""
    return путь.read_text(encoding="utf-8") if путь.is_file() else ""


def строк_в_статусе() -> int:
    """Сколько строк в «Текущем статусе» — по ним видно, переехала ли туда подробность."""
    return len(текст(СТАТУС).splitlines())


def дата_уборки() -> date | None:
    """Дата последней уборки из строки «уборка памяти: дата»; нет строки — None."""
    найдено = ДАТА_УБОРКИ.search(текст(СТАТУС))
    if not найдено:
        return None
    день, месяц, год = (int(часть) for часть in найдено.groups())
    try:
        return date(год, месяц, день)
    except ValueError:
        return None


def дней_с_уборки(сегодня: date | None = None) -> int | None:
    """Сколько дней прошло с последней уборки; даты нет — None."""
    была = дата_уборки()
    if была is None:
        return None
    return ((сегодня or date.today()) - была).days


def битые_ссылки() -> list[str]:
    """Ссылки «Индекса», ведущие на несуществующие файлы памяти."""
    return [
        цель for цель in ССЫЛКА.findall(текст(ИНДЕКС)) if not (ПАМЯТЬ / цель).is_file()
    ]


def файлы_вне_индекса() -> list[str]:
    """Файлы памяти, о которых «Индекс» не упоминает: знание есть, входа к нему нет.

    Сам «Индекс» себя не упоминает — это вход, а не знание, и в список не идёт.
    """
    указатель = текст(ИНДЕКС)
    return [
        файл.name
        for файл in файлы_памяти()
        if файл != ИНДЕКС and файл.name not in указатель
    ]


def пустые_файлы() -> list[str]:
    """Пустой файл в памяти — потерянное знание, а не «пока ничего»."""
    return [файл.name for файл in файлы_памяти() if not текст(файл).strip()]


def пометки_дсх() -> dict[str, int]:
    """Пометки «в ДСХ этого нет» по файлам: устареют — их надо снять."""
    return {
        файл.name: текст(файл).count(ПОМЕТКА_ДСХ)
        for файл in файлы_памяти()
        if ПОМЕТКА_ДСХ in текст(файл)
    }


def приблизительное(текст_файла: str, начало: int) -> bool:
    """Число записано как оценка («~500», «около 500») — в сверку не идёт."""
    перед = текст_файла[max(0, начало - 12) : начало].rstrip()
    return перед.endswith(ПРИБЛИЗИТЕЛЬНО)


def количества() -> list[tuple[str, str, str]]:
    """Количества памяти: (число, единица, файл) — материал для сверки с фактом."""
    найдено: list[tuple[str, str, str]] = []
    for файл in файлы_памяти():
        содержимое = текст(файл)
        for совпадение in КОЛИЧЕСТВО.finditer(содержимое):
            if приблизительное(содержимое, совпадение.start()):
                continue
            число, единица = совпадение.groups()
            найдено.append(
                (" ".join(число.split()), " ".join(единица.lower().split()), файл.name)
            )
    return найдено


def количества_в_двух_местах() -> dict[str, list[str]]:
    """Одинаковые количества («1887 тестов») в разных файлах — верный дубль.

    Разошедшиеся числа скрипт НЕ судит: одно и то же это количество или разные,
    видно только по смыслу («36 тестов» в одном файле и «1887 тестов» в другом —
    разные факты). Поэтому полный список количеств даёт ключ `--числа`, а навык
    сверяет их с фактом: прогон, размер файла, слепок зависимостей.
    """
    места: dict[str, set[str]] = {}
    for число, единица, файл in количества():
        места.setdefault(f"{число} {единица}", set()).add(файл)
    return {
        фраза: sorted(имена) for фраза, имена in sorted(места.items()) if len(имена) > 1
    }


def количества_по_файлам() -> dict[str, list[str]]:
    """Количества по файлам — для сверки с фактом (ключ `--числа`)."""
    по_файлам: dict[str, list[str]] = {}
    for число, единица, файл in количества():
        по_файлам.setdefault(файл, []).append(f"{число} {единица}")
    return по_файлам


def _норма(строка: str) -> str:
    """Строка без разметки и лишних пробелов — по ней и сравниваем."""
    return " ".join(строка.split()).strip("-* \t")


def дубли_строк() -> dict[str, list[str]]:
    """Одинаковые содержательные строки в разных файлах: кандидаты в дубли.

    Свести дубль — значит оставить факт в одном месте, а в остальных поставить
    ссылку (правило памяти). Спорный факт не трогаем: сначала вопрос.
    """
    места: dict[str, set[str]] = {}
    for файл in файлы_памяти():
        for строка in текст(файл).splitlines():
            норма = _норма(строка)
            if len(норма) < ДЛИНА_СТРОКИ_ДУБЛЯ or норма.startswith(СЛУЖЕБНОЕ):
                continue
            места.setdefault(норма, set()).add(файл.name)
    return {строка: sorted(имена) for строка, имена in места.items() if len(имена) > 1}


def отчёт(сегодня: date | None = None) -> dict[str, object]:
    """Все признаки одной записью — из неё и печать, и решение «пора»."""
    дней = дней_с_уборки(сегодня)
    return {
        "файлов памяти": len(файлы_памяти()),
        "строк в статусе": строк_в_статусе(),
        "дней с уборки": дней,
        "дата уборки": дата_уборки(),
        "битые ссылки": битые_ссылки(),
        "файлы вне индекса": файлы_вне_индекса(),
        "пустые файлы": пустые_файлы(),
        "пометки в ДСХ": пометки_дсх(),
        "числа в двух местах": количества_в_двух_местах(),
        "дубли строк": дубли_строк(),
    }


def причины(данные: dict[str, object]) -> list[str]:
    """Причины «пора убирать» — словами и с числами, по признакам ADR."""
    найдено: list[str] = []
    строк = данные["строк в статусе"]
    if isinstance(строк, int) and строк > ПОРОГ_СТРОК_СТАТУСА:
        найдено.append(f"статус {строк} строк при пороге {ПОРОГ_СТРОК_СТАТУСА}")
    дней = данные["дней с уборки"]
    if дней is None:
        найдено.append("в «Текущем статусе» нет строки «уборка памяти: дата»")
    elif дней > ПОРОГ_ДНЕЙ_С_УБОРКИ:
        найдено.append(
            f"с уборки {дней} дней при пороге {ПОРОГ_ДНЕЙ_С_УБОРКИ} ({данные['дата уборки']})"
        )
    if данные["битые ссылки"]:
        найдено.append(f"ссылки «Индекса» в никуда: {данные['битые ссылки']}")
    if данные["файлы вне индекса"]:
        найдено.append(f"файлы вне «Индекса»: {данные['файлы вне индекса']}")
    if данные["пустые файлы"]:
        найдено.append(f"пустые файлы: {данные['пустые файлы']}")
    if данные["дубли строк"]:
        найдено.append(f"кандидатов в дубли: {len(данные['дубли строк'])}")
    for фраза, имена in данные["числа в двух местах"].items():  # type: ignore[union-attr]
        найдено.append(f"число в двух местах: «{фраза}» — {', '.join(имена)}")
    return найдено


def копия_памяти(сказать=print) -> Path:
    """Копия папки памяти рядом с ней: память не в git, откатываться больше нечем.

    Имя — с датой; копия с таким именем уже есть — кладём рядом следующую, а не
    затираем и не берём старую: перед каждой уборкой копия должна быть свежей.
    """
    основа = f"memory-backup-{date.today():%Y-%m-%d}"
    копия = КОПИИ / основа
    номер = 2
    while копия.exists():
        копия = КОПИИ / f"{основа}-{номер}"
        номер += 1
    shutil.copytree(ПАМЯТЬ, копия)
    сказать(f"Копия памяти сделана: {копия}")
    return копия


def печать(данные: dict[str, object]) -> None:
    """Отчёт человеку: сперва числа, потом вывод — без «на глаз»."""
    print(f"Память: {ПАМЯТЬ} — файлов {данные['файлов памяти']}")
    print(
        f"Строк в «Текущем статусе»: {данные['строк в статусе']} (порог {ПОРОГ_СТРОК_СТАТУСА})"
    )
    дней = данные["дней с уборки"]
    if дней is None:
        print("Уборка памяти: строки «уборка памяти: дата» в статусе нет")
    else:
        print(
            f"Уборка памяти: {данные['дата уборки']} — {дней} дней назад (порог {ПОРОГ_ДНЕЙ_С_УБОРКИ})"
        )
    print(f"Ссылки «Индекса» в никуда: {данные['битые ссылки'] or 'нет'}")
    print(f"Файлы вне «Индекса»: {данные['файлы вне индекса'] or 'нет'}")
    print(f"Пустые файлы: {данные['пустые файлы'] or 'нет'}")
    пометки = данные["пометки в ДСХ"]
    print(f"Пометки «в ДСХ этого нет»: {пометки or 'нет'}")
    числа = данные["числа в двух местах"]
    print(f"Числа-количества в двух местах: {len(числа)}")
    for фраза, имена in list(числа.items())[:5]:  # type: ignore[union-attr]
        print(f"  «{фраза}» — {', '.join(имена)}")
    дубли = данные["дубли строк"]
    print(f"Кандидаты в дубли: {len(дубли)}")
    for строка, имена in list(дубли.items())[:10]:
        print(f"  «{строка[:70]}» — {', '.join(имена)}")
    найдено = причины(данные)
    if найдено:
        print(f"ИТОГ: причин {len(найдено)} — пора убирать")
        for причина in найдено:
            print(f"  - {причина}")
    else:
        print("ИТОГ: причин нет — уборка не нужна")


def main(аргументы: list[str] | None = None) -> int:
    """Отчёт по признакам; `--числа` — список количеств, `--копия` — копия памяти."""
    аргументы = list(sys.argv[1:] if аргументы is None else аргументы)
    if not ПАМЯТЬ.is_dir():
        print(f"Нет папки памяти: {ПАМЯТЬ}")
        return 1
    данные = отчёт()
    печать(данные)
    if "--числа" in аргументы:
        print("Количества по файлам (сверять с фактом: прогон, размер, слепок версий):")
        for файл, собранные in количества_по_файлам().items():
            print(f"  {файл}: {', '.join(собранные)}")
    if "--копия" in аргументы:
        копия_памяти()
    return 1 if причины(данные) else 0


if __name__ == "__main__":
    sys.exit(main())
