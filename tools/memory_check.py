"""Проверка признаков «пора убрать память» — измеритель для навыка уборки.

Память проекта (`.dsh/memory/`) — быстрая рабочая копия знаний: оригинал лежит в
vault (`docs/vault/`). Память стареет незаметно: статус разрастается, один факт
появляется в двух файлах, числа расходятся с фактом, ссылки «Индекса» ведут в
никуда, пометки «в ДСХ этого нет» перестают быть верными.

Скрипт **только измеряет**: ничего не правит и не удаляет. Считать, а не
вспоминать, — его работа; решать и убирать — дело навыка `memory-cleanup`
(`.dsh/skills/memory-cleanup/SKILL.md`) и слова пользователя.

**Два вердикта** (ADR «Подсказка об уборке памяти», пересмотр 11.10.2026):

- **«Пора убирать»** — только порча содержимого: дубли, числа в двух местах,
  битые ссылки, пустые файлы, файлы вне индекса. Это код возврата 1.
- **«Повод посмотреть»** — размер и возраст: история в статусе (абзац или пункт с
  датой либо хэшем коммита — подробностям место в «Ходе работ»), больше
  `ПОТОЛОК_ПУНКТОВ` пунктов в разделах работы, больше месяца с уборки, нет строки
  с датой уборки. Код возврата это не меняет: повод — не порча.

Почему размер меряется содержанием, а не строками. 11.10.2026 подсказка
срабатывала почти каждую сессию: порог в 100 строк считал переносы строк (файлы
памяти набраны по ~80 знаков), а сверка дублей сравнивала живой файл с АРХИВНЫМ
журналом «Ход работ — до переноса» — и находила вечный дубль у любого факта,
пережившего переезд. Формат на вердикт влиять не должен: считаем пункты и
«переехавшую историю», а архивные файлы (пометка `архив: да` в шапке) в сверку не
берём вовсе.

Файл — и библиотека, и команда:

    python .dsh/tools/memory_check.py            # отчёт по признакам
    python .dsh/tools/memory_check.py --числа    # ещё и список количеств для сверки
    python .dsh/tools/memory_check.py --копия    # отчёт и копия памяти перед уборкой

Код выхода: 0 — порчи нет (поводы могут быть); 1 — есть порча содержимого.
"""

import os
import re
import shutil
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pre_commit_cache import корень_проекта  # noqa: E402

for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

# Корень — как у соседних инструментов: сначала переменная среды (по ней измеритель
# гоняют по чужой памяти, например по копии), потом место файла.
КОРЕНЬ = Path(os.environ.get("REGLAMENT_PROJECT_DIR") or корень_проекта())
ПАМЯТЬ = КОРЕНЬ / ".dsh" / "memory"
ИНДЕКС = ПАМЯТЬ / "Индекс.md"
СТАТУС = ПАМЯТЬ / "Текущий статус.md"
КОПИИ = КОРЕНЬ / ".dsh"

# Пороги «повод посмотреть» живут ЗДЕСЬ, одним местом: решение, Регламент и навык
# ссылаются на измеритель, а числа не повторяют.
#
# Сколько пунктов в разделах работы считаем нормой. Это ПОТОЛОК, а не рабочий
# сигнал: сегодня в статусе 11 пунктов, и 50 сработает только на разрастании.
# Рабочий сигнал размера — «история в статусе» (см. ниже).
ПОТОЛОК_ПУНКТОВ = 50
ПОРОГ_ДНЕЙ_С_УБОРКИ = 30

# Разделы «Текущего статуса», по которым считаем пункты: что можно продолжить и
# куда идём дальше. Подробности — в «Ходе работ», долги — в своём реестре.
РАЗДЕЛЫ_ПУНКТОВ = ("Незакрытые работы, которые можно продолжить", "Следующий шаг")

# Что считать кандидатом в дубли: короткая строка — обычные слова, а не факт.
ДЛИНА_СТРОКИ_ДУБЛЯ = 40

# Мелочи разбора текста. Дату уборки ищем без оглядки на регистр: в статусе она
# стоит с заглавной буквы («**Уборка памяти:** 04.10.2026»).
ДАТА_УБОРКИ = re.compile(
    r"уборка памяти[^\d]{0,20}(\d{2})\.(\d{2})\.(\d{4})", re.IGNORECASE
)
ССЫЛКА = re.compile(r"\]\(([^)#]+\.md)\)")
ПОМЕТКА_ДСХ = "в ДСХ этого нет"

# Пометка архива в шапке файла памяти: «архив: да». Такой файл описывает состояние
# на прошлую дату — сверять с ним живое знание нельзя, иначе у любого факта,
# пережившего переезд, находится вечный «дубль» (случай 11.10.2026).
АРХИВ_В_ШАПКЕ = re.compile(r"^архив:\s*(да|yes|true)\s*$", re.M | re.IGNORECASE)

# Дата «дд.мм.гггг» и хэш коммита в тексте статуса: это событие, а не состояние.
ДАТА_СОБЫТИЯ = re.compile(r"\b\d{2}\.\d{2}\.\d{4}\b")
ХЭШ_КОММИТА = re.compile(r"\b(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b")

# «Число-количество» — цифра вместе с единицей измерения: тесты, строки, файлы,
# размеры, проценты, минуты. Ищем не вообще числа (их в тексте сотни, и они
# безобидны: номера долгов, порты, коды ответов, хэши), а количества, которые
# обязаны сходиться с фактом. Одна единица с разными числами в двух файлах —
# верный признак устаревшего числа.
КОЛИЧЕСТВО = re.compile(
    r"(\d[\d\s]*(?:[.,]\d+)?)\s*"
    r"(тест\w*|строк\w*|файл\w*|мб|кб|гб|%|процент\w*|минут\w*)",
    re.IGNORECASE,
)
# Слова-оценки перед числом: «~500», «около 500». Приблизительное число не обязано
# сходиться с фактом, и совпадение двух оценок в разных файлах ничего не доказывает
# (ложное срабатывание 2026-10-04: «~500 строк» в цитате фантомного долга и в
# оценке объёма зачистки тестов). Такие числа в сверку не идут.
ПРИБЛИЗИТЕЛЬНО = ("~", "≈", "около", "примерно", "порядка")
СЛУЖЕБНОЕ = ("#", ">", "|", "```", "---", "тип:", "статус:", "создано:", "обновлено:")


def файлы_памяти() -> list[Path]:
    """Файлы памяти по алфавиту; папки нет — пустой список (о ней скажет отчёт)."""
    return sorted(ПАМЯТЬ.glob("*.md")) if ПАМЯТЬ.is_dir() else []


def текст(путь: Path) -> str:
    """Текст файла; файла нет — пустая строка, а не падение."""
    return путь.read_text(encoding="utf-8") if путь.is_file() else ""


def шапка(путь: Path) -> str:
    """Текст YAML-шапки файла (между первой и второй линией «---»); нет — пусто."""
    строки = текст(путь).splitlines()
    if not строки or строки[0].strip() != "---":
        return ""
    собранные: list[str] = []
    for строка in строки[1:]:
        if строка.strip() == "---":
            break
        собранные.append(строка)
    return "\n".join(собранные)


def архивный(путь: Path) -> bool:
    """Файл помечен архивом В ШАПКЕ — сверять с ним живое знание нельзя.

    Именно в шапке: упоминание «архив: да» в тексте заметки пометкой не считается —
    иначе служебная строка посреди файла молча выключила бы его из сверки.
    """
    return bool(АРХИВ_В_ШАПКЕ.search(шапка(путь)))


def файлы_сверки() -> list[Path]:
    """Файлы памяти без архивных: только по ним ищем дубли и числа."""
    return [файл for файл in файлы_памяти() if not архивный(файл)]


def архивные() -> list[str]:
    """Имена архивных файлов — их называют в отчёте, чтобы это не было тайной."""
    return [файл.name for файл in файлы_памяти() if архивный(файл)]


def строк_в_статусе() -> int:
    """Сколько физических строк в «Текущем статусе» — число для справки.

    Признаком размера это больше НЕ является: переносы строк зависят от набора
    текста, а не от количества знания (пересмотр 11.10.2026).
    """
    return len(текст(СТАТУС).splitlines())


def дата_уборки() -> date | None:
    """Дата последней уборки из строки «уборка памяти: дата»; нет строки — None."""
    найдено = ДАТА_УБОРКИ.search(текст(СТАТУС))
    if not найдено:
        return None
    день, месяц, год = (int(часть) for часть in найдено.groups())
    try:
        return date(год, месяц, день)
    except ValueError:
        return None


def дней_с_уборки(сегодня: date | None = None) -> int | None:
    """Сколько дней прошло с последней уборки; даты нет — None."""
    была = дата_уборки()
    if была is None:
        return None
    return ((сегодня or date.today()) - была).days


def битые_ссылки() -> list[str]:
    """Ссылки «Индекса», ведущие на несуществующие файлы памяти."""
    return [
        цель for цель in ССЫЛКА.findall(текст(ИНДЕКС)) if not (ПАМЯТЬ / цель).is_file()
    ]


def файлы_вне_индекса() -> list[str]:
    """Файлы памяти, о которых «Индекс» не упоминает: знание есть, входа к нему нет.

    Сам «Индекс» себя не упоминает — это вход, а не знание, и в список не идёт.
    """
    указатель = текст(ИНДЕКС)
    return [
        файл.name
        for файл in файлы_памяти()
        if файл != ИНДЕКС and файл.name not in указатель
    ]


def пустые_файлы() -> list[str]:
    """Пустой файл в памяти — потерянное знание, а не «пока ничего»."""
    return [файл.name for файл in файлы_памяти() if not текст(файл).strip()]


def пометки_дсх() -> dict[str, int]:
    """Пометки «в ДСХ этого нет» по файлам: устареют — их надо снять.

    Вердикта эти пометки не двигают: отличить свежую пометку от устаревшей
    измеритель не может (решение 11.10.2026) — он их только называет.
    """
    return {
        файл.name: текст(файл).count(ПОМЕТКА_ДСХ)
        for файл in файлы_памяти()
        if ПОМЕТКА_ДСХ in текст(файл)
    }


def приблизительное(текст_файла: str, начало: int) -> bool:
    """Число записано как оценка («~500», «около 500») — в сверку не идёт."""
    перед = текст_файла[max(0, начало - 12) : начало].rstrip()
    return перед.endswith(ПРИБЛИЗИТЕЛЬНО)


def количества() -> list[tuple[str, str, str]]:
    """Количества памяти: (число, единица, файл) — материал для сверки с фактом."""
    найдено: list[tuple[str, str, str]] = []
    for файл in файлы_сверки():
        содержимое = текст(файл)
        for совпадение in КОЛИЧЕСТВО.finditer(содержимое):
            if приблизительное(содержимое, совпадение.start()):
                continue
            число, единица = совпадение.groups()
            найдено.append(
                (" ".join(число.split()), " ".join(единица.lower().split()), файл.name)
            )
    return найдено


def количества_в_двух_местах() -> dict[str, list[str]]:
    """Одинаковые количества («1887 тестов») в разных файлах — верный дубль.

    Разошедшиеся числа скрипт НЕ судит: одно и то же это количество или разные,
    видно только по смыслу («36 тестов» в одном файле и «1887 тестов» в другом —
    разные факты). Поэтому полный список количеств даёт ключ `--числа`, а навык
    сверяет их с фактом: прогон, размер файла, слепок зависимостей.
    """
    места: dict[str, set[str]] = {}
    for число, единица, файл in количества():
        места.setdefault(f"{число} {единица}", set()).add(файл)
    return {
        фраза: sorted(имена) for фраза, имена in sorted(места.items()) if len(имена) > 1
    }


def количества_по_файлам() -> dict[str, list[str]]:
    """Количества по файлам — для сверки с фактом (ключ `--числа`)."""
    по_файлам: dict[str, list[str]] = {}
    for число, единица, файл in количества():
        по_файлам.setdefault(файл, []).append(f"{число} {единица}")
    return по_файлам


def _норма(строка: str) -> str:
    """Строка без разметки и лишних пробелов — по ней и сравниваем."""
    return " ".join(строка.split()).strip("-* \t")


def дубли_строк() -> dict[str, list[str]]:
    """Одинаковые содержательные строки в разных файлах: кандидаты в дубли.

    Свести дубль — значит оставить факт в одном месте, а в остальных поставить
    ссылку (правило памяти). Спорный факт не трогаем: сначала вопрос. Архивные
    файлы в сверке не участвуют: они описывают состояние на прошлую дату.
    """
    места: dict[str, set[str]] = {}
    for файл in файлы_сверки():
        for строка in текст(файл).splitlines():
            норма = _норма(строка)
            if len(норма) < ДЛИНА_СТРОКИ_ДУБЛЯ or норма.startswith(СЛУЖЕБНОЕ):
                continue
            места.setdefault(норма, set()).add(файл.name)
    return {строка: sorted(имена) for строка, имена in места.items() if len(имена) > 1}


def разделы_статуса() -> dict[str, str]:
    """Текст разделов «Текущего статуса», названных в `РАЗДЕЛЫ_ПУНКТОВ`."""
    содержимое = текст(СТАТУС)
    найдено: dict[str, str] = {}
    for имя in РАЗДЕЛЫ_ПУНКТОВ:
        образец = re.compile(rf"^##\s+{re.escape(имя)}\s*$(.*?)(?=^##\s|\Z)", re.M | re.S)
        совпадение = образец.search(содержимое)
        if совпадение:
            найдено[имя] = совпадение.group(1)
    return найдено


def пунктов_в_статусе() -> tuple[int, bool]:
    """(сколько пунктов в разделах работы, нашлись ли все разделы).

    Разделы не нашлись — это не «ноль пунктов», а «считать нечего»: о таком
    измеритель говорит вслух (переименовали заголовок — признак ослеп, и это
    должно быть видно, а не молчать).
    """
    разделы = разделы_статуса()
    пункт = re.compile(r"^\s*(?:[-*]|\d+[.)])\s+\S")
    всего = sum(
        1
        for содержимое in разделы.values()
        for строка in содержимое.splitlines()
        if пункт.match(строка)
    )
    return всего, len(разделы) == len(РАЗДЕЛЫ_ПУНКТОВ)


def истории_в_статусе() -> list[str]:
    """Абзацы и пункты статуса с датой события или хэшем коммита.

    Это и есть «переехавшая подробность»: событиям и коммитам место в «Ходе
    работ», а статус отвечает на вопрос «что сейчас». Шапка файла и блок
    «Уборка памяти» не в счёт — там дата стоит по делу.
    """
    строки = текст(СТАТУС).splitlines()
    начало = 0
    if строки and строки[0].strip() == "---":
        for номер, строка in enumerate(строки[1:], start=1):
            if строка.strip() == "---":
                начало = номер + 1
                break

    находки: list[str] = []
    пункт_списка = re.compile(r"^\s*(?:[-*]|\d+[.)])\s+\S")

    def проверить(строки_блока: list[str]) -> None:
        собранный = " ".join(строки_блока)
        if not собранный.strip():
            return
        if ДАТА_УБОРКИ.search(собранный):
            return  # блок про уборку: дата там по делу
        if ДАТА_СОБЫТИЯ.search(собранный) or ХЭШ_КОММИТА.search(собранный):
            первая = next((строка for строка in строки_блока if строка.strip()), "")
            находки.append(первая.strip()[:70])

    # Блок — абзац или ОДИН пункт списка: пункты часто идут подряд без пустой
    # строки, и склеивать их нельзя — иначе находка называет не виновника.
    блок: list[str] = []
    for строка in строки[начало:]:
        if not строка.strip():
            проверить(блок)
            блок = []
            continue
        if пункт_списка.match(строка) and блок:
            проверить(блок)
            блок = []
        блок.append(строка)
    проверить(блок)
    return находки


def отчёт(сегодня: date | None = None) -> dict[str, object]:
    """Все признаки одной записью — из неё и печать, и вердикты."""
    дней = дней_с_уборки(сегодня)
    пунктов, разделы_найдены = пунктов_в_статусе()
    return {
        "файлов памяти": len(файлы_памяти()),
        "архивных файлов": архивные(),
        "строк в статусе": строк_в_статусе(),
        "пунктов в статусе": пунктов,
        "разделы найдены": разделы_найдены,
        "историй в статусе": истории_в_статусе(),
        "дней с уборки": дней,
        "дата уборки": дата_уборки(),
        "битые ссылки": битые_ссылки(),
        "файлы вне индекса": файлы_вне_индекса(),
        "пустые файлы": пустые_файлы(),
        "пометки в ДСХ": пометки_дсх(),
        "числа в двух местах": количества_в_двух_местах(),
        "дубли строк": дубли_строк(),
    }


def причины(данные: dict[str, object]) -> list[str]:
    """«Пора убирать»: только порча содержимого — словами и с числами."""
    найдено: list[str] = []
    if данные["битые ссылки"]:
        найдено.append(f"ссылки «Индекса» в никуда: {данные['битые ссылки']}")
    if данные["файлы вне индекса"]:
        найдено.append(f"файлы вне «Индекса»: {данные['файлы вне индекса']}")
    if данные["пустые файлы"]:
        найдено.append(f"пустые файлы: {данные['пустые файлы']}")
    if данные["дубли строк"]:
        найдено.append(f"кандидатов в дубли: {len(данные['дубли строк'])}")
    for фраза, имена in данные["числа в двух местах"].items():  # type: ignore[union-attr]
        найдено.append(f"число в двух местах: «{фраза}» — {', '.join(имена)}")
    return найдено


def поводы(данные: dict[str, object]) -> list[str]:
    """«Повод посмотреть»: размер и возраст — не порча, но и не молчание."""
    найдено: list[str] = []
    истории = данные["историй в статусе"]
    if истории:
        найдено.append(
            f"история в статусе: {len(истории)} мест — подробностям место в «Ходе работ»"
        )
    пунктов = данные["пунктов в статусе"]
    if isinstance(пунктов, int) and пунктов > ПОТОЛОК_ПУНКТОВ:
        найдено.append(
            f"пунктов в разделах работы: {пунктов} при потолке {ПОТОЛОК_ПУНКТОВ}"
        )
    if not данные["разделы найдены"]:
        найдено.append(
            "разделы работы в статусе не найдены — признак пунктов не работал "
            f"(ждали: {', '.join(РАЗДЕЛЫ_ПУНКТОВ)})"
        )
    дней = данные["дней с уборки"]
    if дней is None:
        найдено.append("нет строки «уборка памяти: дата» — признак возраста не работает")
    elif дней > ПОРОГ_ДНЕЙ_С_УБОРКИ:
        найдено.append(
            f"с уборки {дней} дней при пороге {ПОРОГ_ДНЕЙ_С_УБОРКИ} ({данные['дата уборки']})"
        )
    return найдено


def копия_памяти(сказать=print) -> Path:
    """Копия папки памяти рядом с ней: память не в git, откатываться больше нечем.

    Имя — с датой; копия с таким именем уже есть — кладём рядом следующую, а не
    затираем и не берём старую: перед каждой уборкой копия должна быть свежей.
    """
    основа = f"memory-backup-{date.today():%Y-%m-%d}"
    копия = КОПИИ / основа
    номер = 2
    while копия.exists():
        копия = КОПИИ / f"{основа}-{номер}"
        номер += 1
    shutil.copytree(ПАМЯТЬ, копия)
    сказать(f"Копия памяти сделана: {копия}")
    return копия


def печать(данные: dict[str, object]) -> None:
    """Отчёт человеку: сперва числа, потом два вердикта — без «на глаз»."""
    print(f"Память: {ПАМЯТЬ} — файлов {данные['файлов памяти']}")
    if данные["архивных файлов"]:
        print(f"Архивные (в сверке не участвуют): {', '.join(данные['архивных файлов'])}")
    print(
        f"«Текущий статус»: {данные['строк в статусе']} строк, "
        f"{данные['пунктов в статусе']} пунктов в разделах работы (потолок {ПОТОЛОК_ПУНКТОВ})"
    )
    истории = данные["историй в статусе"]
    print(f"История в статусе: {len(истории)} мест")
    for место in list(истории)[:5]:
        print(f"  «{место}…»")
    дней = данные["дней с уборки"]
    if дней is None:
        print("Уборка памяти: строки «уборка памяти: дата» в статусе нет")
    else:
        print(
            f"Уборка памяти: {данные['дата уборки']} — {дней} дней назад (порог {ПОРОГ_ДНЕЙ_С_УБОРКИ})"
        )
    print(f"Ссылки «Индекса» в никуда: {данные['битые ссылки'] or 'нет'}")
    print(f"Файлы вне «Индекса»: {данные['файлы вне индекса'] or 'нет'}")
    print(f"Пустые файлы: {данные['пустые файлы'] or 'нет'}")
    пометки = данные["пометки в ДСХ"]
    print(f"Пометки «в ДСХ этого нет» (вердикта не двигают): {пометки or 'нет'}")
    числа = данные["числа в двух местах"]
    print(f"Числа-количества в двух местах: {len(числа)}")
    for фраза, имена in list(числа.items())[:5]:  # type: ignore[union-attr]
        print(f"  «{фраза}» — {', '.join(имена)}")
    дубли = данные["дубли строк"]
    print(f"Кандидаты в дубли: {len(дубли)}")
    for строка, имена in list(дубли.items())[:10]:
        print(f"  «{строка[:70]}» — {', '.join(имена)}")

    порча = причины(данные)
    if порча:
        print(f"ПОРА УБИРАТЬ: причин {len(порча)}")
        for причина in порча:
            print(f"  - {причина}")
    поводы_найдены = поводы(данные)
    if поводы_найдены:
        print(f"ПОВОД ПОСМОТРЕТЬ: {len(поводы_найдены)}")
        for повод in поводы_найдены:
            print(f"  - {повод}")
    if not порча and not поводы_найдены:
        print("ИТОГ: ни порчи, ни поводов — память в порядке")


def main(аргументы: list[str] | None = None) -> int:
    """Отчёт по признакам; `--числа` — список количеств, `--копия` — копия памяти."""
    аргументы = list(sys.argv[1:] if аргументы is None else аргументы)
    if not ПАМЯТЬ.is_dir():
        print(f"Нет папки памяти: {ПАМЯТЬ}")
        return 1
    данные = отчёт()
    печать(данные)
    if "--числа" in аргументы:
        print("Количества по файлам (сверять с фактом: прогон, размер, слепок версий):")
        for файл, собранные in количества_по_файлам().items():
            print(f"  {файл}: {', '.join(собранные)}")
    if "--копия" in аргументы:
        копия_памяти()
    return 1 if причины(данные) else 0


if __name__ == "__main__":
    sys.exit(main())
