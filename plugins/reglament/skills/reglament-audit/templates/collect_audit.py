def шаг_окружение(корень, отчёт):
    """Шаг 0. Чем запускается проект и совпадает ли со слепком.

    Сверка со слепком — до всех измерений: расхождение означает,
    что мерили не тот код, который поедет в продакшен.
    """
    строки = []
    интерпретатор = питон(корень)
    своё = интерпретатор != sys.executable
    строки.append(f"Интерпретатор: `{интерпретатор}`")
    строки.append(
        "Виртуальное окружение проекта: "
        + ("найдено" if своё else "НЕ найдено — измерения идут "
           "системным Python, это может быть не тот набор пакетов")
    )
    _, версия = выполнить([интерпретатор, "--version"], корень)
    строки.append(f"Версия: {версия or 'не определилась'}")

    файлы_зависимостей = [
        и.name for и in корень.iterdir()
        if и.is_file() and и.name in (
            "requirements.txt", "requirements.lock", "requirements-dev.txt",
            "pyproject.toml", "poetry.lock", "Pipfile", "Pipfile.lock",
            "uv.lock", "package.json",
        )
    ]
    строки.append(
        "Файлы зависимостей: "
        + (", ".join(f"`{и}`" for и in файлы_зависимостей) or "не найдены")
    )

    получилось, заморожено = выполнить(
        [интерпретатор, "-m", "pip", "freeze"], корень
    )
    if получилось:
        установлено = {}
        for строка in заморожено.splitlines():
            if "==" in строка:
                имя, _, версия_пакета = строка.partition("==")
                установлено[имя.strip().lower()] = версия_пакета.strip()
        строки.append(f"Установлено пакетов: {len(установлено)}")

        слепок = None
        for имя in ("requirements.lock", "requirements.txt"):
            кандидат = корень / имя
            if кандидат.exists():
                слепок = кандидат
                break
        if слепок:
            расхождения = []
            текст = слепок.read_text(encoding="utf-8", errors="replace")
            for строка in текст.splitlines():
                строка = строка.strip()
                if not строка or строка.startswith("#") or "==" not in строка:
                    continue
                имя, _, ожидается = строка.partition("==")
                имя = имя.strip().lower()
                ожидается = ожидается.strip().split(";")[0].strip()
                факт = установлено.get(имя)
                if факт is None:
                    расхождения.append(f"{имя}: в слепке {ожидается}, НЕ установлен")
                elif факт != ожидается:
                    расхождения.append(f"{имя}: слепок {ожидается}, установлено {факт}")
            строки.append("")
            строки.append(f"Сверка с `{слепок.name}`:")
            if расхождения:
                строки.append("")
                строки.append(блок("\n".join(расхождения)))
                строки.append(
                    "РАСХОЖДЕНИЕ. Дальнейшие измерения относятся к "
                    "установленным версиям, а не к зафиксированным."
                )
            else:
                строки.append("совпадает")
        else:
            строки.append("Слепок версий не найден — сверять не с чем.")
    else:
        строки.append(f"Список пакетов не получен: {заморожено}")

    отчёт.добавить("Окружение", "\n".join(строки))
    return интерпретатор


def шаг_состав(корень, отчёт):
    """Шаг 1. Из чего состоит проект — и чего инструменты не увидят."""
    по_языкам = {}
    for путь in корень.rglob("*"):
        if not путь.is_file() or not свой_файл(путь):
            continue
        язык = ЯЗЫКИ.get(путь.suffix.lower())
        if not язык:
            continue
        try:
            строк = sum(1 for _ in путь.open(encoding="utf-8", errors="replace"))
        except OSError:
            строк = 0
        файлов, всего = по_языкам.get(язык, (0, 0))
        по_языкам[язык] = (файлов + 1, всего + строк)

    if не_пусто := sorted(по_языкам.items(), key=lambda и: -и[1][1]):
        таблица = ["| Язык | Файлов | Строк |", "|---|---|---|"]
        for язык, (файлов, строк) in не_пусто:
            таблица.append(f"| {язык} | {файлов} | {строк} |")
        тело = "\n".join(таблица)
    else:
        тело = "Файлов с кодом не найдено."

    # Слепые зоны объявляем сразу: инструменты ниже — только Python.
    прочие = [я for я, _ in не_пусто if я != "Python"]
    if прочие:
        отчёт.слепая_зона(
            ", ".join(прочие),
            "radon, vulture и ruff проверяют только Python. Мёртвый "
            "код, сложность и ошибки в этих файлах не проверял никто",
        )
    отчёт.добавить("Состав проекта", тело)
    return {я for я, _ in не_пусто}


def шаг_ruff(корень, отчёт, интерпретатор):
    """Шаг 2-3. Ruff со СВОИМ набором правил, мимо конфига проекта."""
    база = [интерпретатор, "-m", "ruff", "check", ".", "--isolated",
            "--exit-zero", "--no-cache"]

    получилось, вывод = выполнить(
        база + ["--select", НАБОР_ПРАВИЛ, "--statistics"], корень
    )
    if получилось:
        отчёт.добавить(
            "Ruff — сводка по правилам",
            блок(вывод or "нарушений не найдено"),
            "Конфиг проекта проигнорирован (--isolated). Группы: "
            "F и B — настоящие ошибки, S — безопасность, "
            "DJ — Django, ERA и ARG — следы правок.",
        )
    else:
        отчёт.добавить("Ruff — сводка по правилам", f"_Не выполнено: {вывод}_")
        отчёт.слепая_зона("Проверка кода (ruff)", вывод)
        return

    # Безопасность отдельным прогоном: на первом аудите именно её
    # спрятал конфиг проекта, поэтому она не тонет в общей сводке.
    _, безопасность = выполнить(
        база + ["--select", "S", "--output-format", "concise"], корень
    )
    отчёт.добавить(
        "Ruff — безопасность (группа S), подробно",
        блок(безопасность or "нарушений не найдено"),
        "Отдельный прогон намеренно: на первом аудите эту группу "
        "отключал конфиг проекта, и сводка выглядела чистой.",
    )

    получилось, чинится = выполнить(
        база + ["--select", НАБОР_ПРАВИЛ, "--fix", "--diff"], корень
    )
    if получилось:
        сколько = len([с for с in чинится.splitlines() if с.startswith("+++")])
        тело = (f"Файлов, которые изменил бы автофикс: {сколько}\n\n"
                "Ничего не применено: сборщик не правит код.")
    else:
        тело = f"_Не выполнено: {чинится}_"
    отчёт.добавить("Ruff — что чинится автоматически", тело)


def шаг_django(корень, отчёт, интерпретатор):
    """Шаг 4. Встроенная проверка боевых настроек."""
    if not (корень / "manage.py").exists():
        отчёт.слепая_зона("Настройки Django", "manage.py не найден — не Django")
        return False
    получилось, вывод = выполнить(
        [интерпретатор, "manage.py", "check", "--deploy"], корень
    )
    отчёт.добавить(
        "Django — проверка боевых настроек",
        блок(вывод) if получилось else f"_Не выполнено: {вывод}_",
        "Встроенная проверка Django. Каждый пункт — риск на живом "
        "сайте, навык переводит их на человеческий язык.",
    )
    return True


