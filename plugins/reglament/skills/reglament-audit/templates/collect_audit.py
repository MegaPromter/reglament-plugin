#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сборщик аудита — прогон измерительных инструментов.

Запуск: python collect_audit.py [--вывод ПУТЬ] [--корень ПУТЬ]
Выход: всегда 0. Сборщик не судит и не падает — он записывает.

Собирает сырой вывод инструментов в один markdown-файл, который
затем разбирает навык reglament-audit. Ничего не чинит, не ставит
и не решает: отделить находку от шума — работа навыка.

ПОЧЕМУ СКРИПТ, А НЕ ИНСТРУКЦИЯ АССИСТЕНТУ

На первом прогоне (planapp_django, 2026-08-20) ассистент взял ruff
с конфигом проекта, а тот отключал группу безопасности S.
Статистика показала «чисто» не потому что чисто, а потому что не
смотрела. Инструкция «не забудь про S» такую осечку не исключает —
скрипт с явным набором правил исключает.

Отсюда главное правило сборщика: КОНФИГИ ПРОЕКТА ИГНОРИРУЮТСЯ.
Набор правил задаётся здесь. Конфиг проекта — это компромиссы для
повседневной работы; аудит существует затем, чтобы посмотреть мимо
них.

ЧАСТИЧНЫЙ РЕЗУЛЬТАТ ПОЛЕЗНЕЕ ПУСТОГО

Каждый шаг переживает отсутствие инструмента, чужой стек и
отсутствие git: пишет «не выполнено» с причиной и идёт дальше.
Единственный способ не получить отчёт — прервать скрипт руками.

СЛЕПЫЕ ЗОНЫ ОБЪЯВЛЯЮТСЯ

Что не проверено — записывается явно. Необъявленная слепая зона
хуже объявленной: она даёт ложное спокойствие. radon и vulture
видят только Python; если в проекте есть другой язык, об этом
будет сказано в отчёте.

[МАСТЕР: при записи в проект перевести на язык проекта заголовки
разделов и сообщения. Имена инструментов, ключи и флаги команд НЕ
переводить. Набор правил ruff (НАБОР_ПРАВИЛ) — не трогать без
причины: он подобран шире повседневного.]
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

# Консоль Windows по умолчанию не UTF-8 — переключаем потоки явно.
for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

# Набор правил ruff для АУДИТА — шире повседневного (в хуке F, B, S).
#   F   — настоящие ошибки: код может упасть
#   B   — конструкции-ловушки, почти всегда баг
#   S   — безопасность
#   DJ  — специфичные для Django
#   ERA — закомментированный код: на проектах, писанных с ИИ,
#         это след отброшенных подходов
#   ARG — неиспользуемые аргументы: признак недоделанной правки
НАБОР_ПРАВИЛ = "F,B,S,DJ,ERA,ARG"

# Сколько строк сырого вывода класть в отчёт по одному шагу.
# Больше — навыку тяжело читать, меньше — теряется картина.
ПРЕДЕЛ_СТРОК = 200

# Пути, которые не считаются кодом проекта.
МУСОРНЫЕ_ПАПКИ = (
    ".git", ".venv", "venv", "env", "node_modules", "__pycache__",
    ".mypy_cache", ".ruff_cache", ".pytest_cache", "migrations",
    "staticfiles", "dist", "build", ".tox", "site-packages",
)

# Расширения по языкам — для карты «из чего состоит проект».
ЯЗЫКИ = {
    ".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript",
    ".ts": "TypeScript", ".tsx": "TypeScript", ".html": "HTML",
    ".htm": "HTML", ".css": "CSS", ".scss": "CSS", ".vue": "Vue",
    ".sql": "SQL", ".sh": "Shell",
}

# Что ищем в истории git как возможные секреты. Не «найти всё», а
# «поднять флаг»: полноценный поиск — gitleaks, он предлагается
# отдельно.
ПРИЗНАКИ_СЕКРЕТОВ = (
    "password", "passwd", "secret", "token", "api_key", "apikey",
    "private_key", "AWS_", "пароль",
)


class Отчёт:
    """Накопитель разделов. Пишется один раз, в конце."""

    def __init__(self):
        self.разделы = []
        self.слепые_зоны = []

    def добавить(self, заголовок, тело, примечание=None):
        self.разделы.append((заголовок, тело, примечание))

    def слепая_зона(self, что, почему):
        self.слепые_зоны.append((что, почему))

    def собрать(self, корень):
        строки = [
            "# Сырой сбор аудита",
            "",
            f"Проект: `{корень}`",
            "",
            "Это машинный вывод инструментов, а НЕ отчёт об аудите.",
            "Разбирает его навык `reglament-audit`: отделяет находки",
            "от шума, проверяет по чек-листу, объясняет пользователю.",
            "",
            "Набор правил задан сборщиком, конфиги проекта",
            f"проигнорированы намеренно. Правила: `{НАБОР_ПРАВИЛ}`.",
            "",
        ]
        if self.слепые_зоны:
            строки += ["## Слепые зоны", "",
                       "Что НЕ проверено. Отсутствие находок здесь",
                       "не означает отсутствия проблем.", ""]
            for что, почему in self.слепые_зоны:
                строки.append(f"- **{что}** — {почему}")
            строки.append("")
        for заголовок, тело, примечание in self.разделы:
            строки += [f"## {заголовок}", ""]
            if примечание:
                строки += [f"> {примечание}", ""]
            строки += [тело.rstrip() or "_(пусто)_", ""]
        return "\n".join(строки)


def выполнить(команда, корень, таймаут=300):
    """Запуск инструмента. Возвращает (получилось, текст).

    Отсутствие инструмента — не ошибка сборщика, а факт о проекте:
    возвращаем False с внятной причиной, отчёт продолжается.

    Отдельно ловим «модуль не установлен» для запусков вида
    `python -m ruff`: without этой проверки shutil.which видит
    python, шаг рапортует успех и записывает сообщение об ошибке
    как результат — то есть проверка не смотрела, но промолчала.
    Это ровно тот класс осечки, ради которого писался сборщик.
    """
    if not shutil.which(команда[0]):
        return False, f"инструмент `{команда[0]}` не установлен"
    try:
        готово = subprocess.run(
            команда, cwd=str(корень), capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=таймаут,
            # Дочерний Python пишет кириллицу в UTF-8, а не в кодировке
            # консоли Windows: иначе русские пути в выводе — мусор.
            env={**os.environ, "PYTHONIOENCODING": "utf-8",
                 "PYTHONUTF8": "1"},
        )
    except subprocess.TimeoutExpired:
        return False, f"превышено время ожидания ({таймаут} с)"
    except OSError as ошибка:
        return False, f"не удалось запустить: {ошибка}"
    вывод = ((готово.stdout or "") + (готово.stderr or "")).strip()
    if готово.returncode and "No module named" in вывод:
        модуль = вывод.rsplit("No module named", 1)[-1].strip().strip("'\"")
        return False, f"модуль `{модуль}` не установлен"
    return True, вывод


def обрезать(текст, предел=ПРЕДЕЛ_СТРОК):
    строки = текст.splitlines()
    if len(строки) <= предел:
        return текст
    хвост = len(строки) - предел
    return "\n".join(строки[:предел] + [f"… ещё {хвост} строк опущено"])


def блок(текст):
    return f"```\n{обрезать(текст)}\n```"


def свой_файл(путь):
    return not any(часть in МУСОРНЫЕ_ПАПКИ for часть in путь.parts)


def питон(корень):
    """Python из окружения проекта, если оно есть.

    Ставить и мерить надо тем же интерпретатором, которым проект
    запускается, иначе измерения относятся не к тому коду.
    """
    for имя in (".venv", "venv", "env"):
        for подпуть in ("Scripts/python.exe", "bin/python"):
            кандидат = корень / имя / подпуть
            if кандидат.exists():
                return str(кандидат)
    return sys.executable


