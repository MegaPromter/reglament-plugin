#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Хук контроля незавершённых шагов (Stop — ассистент закончил ход).

Задача одна: не дать ассистенту молча замолчать, когда заметка
согласована по процедуре, но пользователю не сказано, что нужно
поставить штамп кнопкой Run. Забывчивость ассистента лечится не
формулировкой в регламенте, а этой проверкой (принцип 10).

Хук НЕ ждёт нажатия Run — это невозможно: пользователь нажимает
кнопку уже после того, как ассистент замолчал. Хук лишь один раз
возвращает ассистента дописать призыв к действию.

Защита от цикла — встроенная: Claude Code выставляет во входном
JSON `stop_hook_active: true`, если ход уже разворачивался хуком.
Свой флаг в табло не заводим: он застрянет выставленным, если
сессия оборвётся посреди хода.

Выходы: 0 — пропустить ход; stdout с {"decision": "block"} —
вернуть ассистента, текст `reason` уйдёт ему как инструкция.

[МАСТЕР: при записи в проект перевести сообщения на язык проекта;
значения фаз и ключи табло — те же, что в gate_edit.py,
approve_task.py и навыке.]
"""
import json
import os
import sys
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(
    os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
ТАБЛО = КОРЕНЬ / ".claude" / "task-state.json"
# Фазы, на которых заметка уже показана и ждёт штампа пользователя.
ФАЗЫ_ОЖИДАНИЯ_ШТАМПА = ("заметка", "согласование")


def пропустить():
    return 0


def вернуть(причина):
    """Блокировка завершения хода: `reason` уходит ассистенту."""
    print(json.dumps({"decision": "block", "reason": причина}, ensure_ascii=False))
    return 0


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return пропустить()

    # Встроенный страж цикла: ход уже разворачивался — не мешаем.
    if данные.get("stop_hook_active") is True:
        return пропустить()

    if not ТАБЛО.exists():
        return пропустить()
    try:
        табло = json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return пропустить()

    if not табло.get("задача"):
        return пропустить()
    # Малая форма идёт без штампа — там ждать нечего.
    if табло.get("форма") == "малая":
        return пропустить()
    if табло.get("одобрено") is True:
        return пропустить()
    if табло.get("фаза", "") not in ФАЗЫ_ОЖИДАНИЯ_ШТАМПА:
        return пропустить()

    # Если призыв уже прозвучал в последнем сообщении — не повторяем.
    последнее = данные.get("last_assistant_message") or ""
    if "approve_task.py" in последнее:
        return пропустить()

    return вернуть(
        f"Задача «{табло['задача']}» ждёт штампа одобрения, а ход "
        f"заканчивается без призыва к действию. Прежде чем замолчать, "
        f"выведи пользователю явную просьбу поставить штамп кнопкой "
        f"Run под командой:\n"
        f"  python .claude/hooks/approve_task.py\n"
        f"и предупреди, что до отметки «одобрено» в табло правки кода "
        f"заблокированы. Ничего больше в этом ходе не делай."
    )


if __name__ == "__main__":
    sys.exit(main())
