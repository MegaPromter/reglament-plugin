#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# reglament-plugin v{{ВЕРСИЯ_ПЛАГИНА}}
"""Хук контроля незавершённых шагов (Stop — ассистент закончил ход).

Ловит три вида забывчивости в фазе «заметка» (полная форма, штампа
ещё нет), прежде чем ассистент замолчит:

1. Ход закончился без действия для пользователя: нет ни вопроса по
   согласованию, ни блока с командой штампа.
2. Команда штампа упомянута, но не оформлена отдельным bash-блоком
   — кнопка Run появляется только у такого блока, упоминание в
   обычном тексте её не даёт, и пользователю некуда нажимать.
3. Блок штампа есть, но фоновый наблюдатель за табло не запущен —
   после нажатия Run сессию никто не разбудит, и пользователю
   придётся писать в чат.

Ход, оканчивающийся вопросом, пропускается: согласование заметки
ещё идёт, требовать штамп рано.

Наблюдатель ищется в поле background_tasks входного JSON
(Claude Code v2.1.145+): фоновая команда, упоминающая task-state.
Поля нет — проверка молча пропускается (старая версия или реестр
задач недоступен).

Защита от цикла — встроенная: stop_hook_active=true, когда ход уже
разворачивался хуком; после 8 блокировок подряд Claude Code
перебивает хук сам. Свой флаг в табло не заводим: он застрянет
выставленным, если сессия оборвётся посреди хода.

Выходы: 0 — пропустить ход; stdout с {"decision": "block"} —
вернуть ассистента, текст reason уйдёт ему как инструкция.

[МАСТЕР: при записи в проект перевести сообщения на язык проекта;
значение фазы и ключи табло — те же, что в gate_edit.py,
approve_task.py и навыке.]
"""
import json
import os
import sys
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(
    os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
ТАБЛО = КОРЕНЬ / ".claude" / "task-state.json"
# Единственная фаза, в которой ждём штампа (словарь фаз: vault →
# заметка → согласовано → код → тесты → коммит → закрыто).
ФАЗА_ОЖИДАНИЯ_ШТАМПА = "заметка"


def пропустить():
    return 0


def команда_в_блоке(текст):
    """Команда штампа внутри кодового блока (``` ... ```).

    Кнопку Run даёт только отдельный блок — инлайн-код в одинарных
    бэктиках не считается. При разрезании текста по ``` содержимое
    блоков оказывается в кусках с нечётными номерами.
    """
    куски = текст.split("```")
    return any("approve_task.py" in кусок for кусок in куски[1::2])


def вернуть(причина):
    """Блокировка завершения хода: reason уходит ассистенту."""
    print(json.dumps({"decision": "block", "reason": причина}, ensure_ascii=False))
    return 0


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return пропустить()

    # Встроенный страж цикла: ход уже разворачивался — не мешаем.
    if данные.get("stop_hook_active") is True:
        return пропустить()

    if not ТАБЛО.exists():
        return пропустить()
    try:
        табло = json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return пропустить()

    if not табло.get("задача"):
        return пропустить()
    # Малая форма идёт без штампа — там ждать нечего.
    if табло.get("форма") == "малая":
        return пропустить()
    if табло.get("одобрено") is True:
        return пропустить()
    if табло.get("фаза", "") != ФАЗА_ОЖИДАНИЯ_ШТАМПА:
        return пропустить()

    последнее = данные.get("last_assistant_message") or ""

    if команда_в_блоке(последнее):
        # Блок с кнопкой есть. Проверяем наблюдателя, если поле доступно.
        задачи = данные.get("background_tasks")
        if not isinstance(задачи, list):
            return пропустить()
        наблюдатель = any(
            isinstance(з, dict) and "task-state" in (з.get("command") or "")
            for з in задачи
        )
        if наблюдатель:
            return пропустить()
        return вернуть(
            f"Призыв к штампу по задаче «{табло['задача']}» прозвучал, "
            f"но фоновый наблюдатель за табло не запущен — после "
            f"нажатия Run сессию никто не разбудит, и пользователю "
            f"придётся писать в чат. Запусти наблюдателя (инструмент "
            f"Bash, run_in_background) по процедуре навыка и снова "
            f"заверши ход призывом нажать Run."
        )

    # Блока с командой нет. Ход-вопрос — согласование идёт, не мешаем.
    if "?" in последнее.rstrip()[-3:]:
        return пропустить()

    if "approve_task.py" in последнее:
        return вернуть(
            f"Команда штампа по задаче «{табло['задача']}» упомянута, "
            f"но не оформлена отдельным bash-блоком — кнопки Run у "
            f"пользователя не будет, нажимать некуда. Покажи команду "
            f"отдельным блоком:\n"
            f"```bash\npython .claude/hooks/approve_task.py\n```\n"
            f"проверь, что фоновый наблюдатель за табло запущен, и "
            f"заверши ход явным призывом нажать Run."
        )

    return вернуть(
        f"Задача «{табло['задача']}» в фазе «заметка», а ход закончился "
        f"без действия для пользователя. Если устное «согласовано» по "
        f"заметке уже получено — покажи команду штампа отдельным "
        f"bash-блоком (у пользователя появится кнопка Run):\n"
        f"```bash\npython .claude/hooks/approve_task.py\n```\n"
        f"запусти фонового наблюдателя за табло и заверши ход явным "
        f"призывом нажать Run. Если согласование ещё идёт — заверши "
        f"ход конкретным вопросом пользователю."
    )


if __name__ == "__main__":
    sys.exit(main())
