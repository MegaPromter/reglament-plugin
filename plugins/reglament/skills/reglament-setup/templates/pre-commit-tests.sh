#!/bin/bash
# reglament-plugin v{{ВЕРСИЯ_ПЛАГИНА}}
# Запуск тестов перед коммитом — блокирует коммит при падении.
# Разбор JSON — на Python: jq может отсутствовать в системе, а с
# отсутствующим jq хук молча пропускал бы всё.
# [МАСТЕР: {{КОМАНДА_ТЕСТОВ}} заменить командой тестов из анкеты
# проекта; сообщение перевести на язык проекта.]
INPUT=$(cat)
TOOL_INPUT=$(printf '%s' "$INPUT" | python -c "
import json, sys
try:
    print(json.load(sys.stdin).get('tool_input', {}).get('command', ''))
except Exception:
    pass
" 2>/dev/null)
if ! echo "$TOOL_INPUT" | grep -q "git commit"; then
  exit 0
fi

cd "$CLAUDE_PROJECT_DIR"

# [МАСТЕР: если на шаге 2 проверка типов не выбрана (или вопрос не
# задавался — в стеке нет Python) — удалить весь блок ниже, до
# строки с командой тестов.]
# Проверка типов — ПЕРЕД тестами: она укладывается в секунды, а
# тесты идут минутами; красные типы отсеиваются дёшево.
# Имена переменных латиницей: кириллические имена bash не берёт.
# Интерпретатор ищем в окружении проекта тем же перебором, что и
# сборщик аудита (mypy ставят в окружение, а не в систему).
PY=""
for ENV_DIR in .venv venv env; do
  for SUBPATH in "Scripts/python.exe" "bin/python"; do
    if [ -x "$ENV_DIR/$SUBPATH" ]; then
      PY="$ENV_DIR/$SUBPATH"
      break 2
    fi
  done
done
[ -z "$PY" ] && PY="python"

# Предохранитель: без установленного mypy шаг молчит. На новом
# проекте mypy появляется позже настройки, и без этой проверки
# хук заблокировал бы первый же коммит.
if "$PY" -m mypy --version >/dev/null 2>&1; then
  "$PY" -m mypy 2>&1
  MYPY_STATUS=$?
  # 1 — найдены ошибки типов, это блок. 2 — mypy не смог
  # запуститься (не задана цель проверки, битый конфиг): не про
  # код проекта, коммит не трогаем. 0 — чисто.
  if [ $MYPY_STATUS -eq 1 ]; then
    echo "Проверка типов не прошла — коммит заблокирован" >&2
    exit 2
  fi
fi

{{КОМАНДА_ТЕСТОВ}} 2>&1
STATUS=$?
if [ $STATUS -ne 0 ]; then
  echo "Тесты не прошли — коммит заблокирован" >&2
  exit 2
fi
exit 0
