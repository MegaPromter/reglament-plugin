#!/usr/bin/env python3
# reglament-plugin v1.4.0
"""Валидатор vault — формальные проверки регламента.

Запуск: python .reglament/hooks/validate_vault.py
Выход: 0 — нарушений нет (предупреждения допустимы); 1 — есть нарушения.

Нарушения (валят коммит):
  1. Статус не из словаря (свой словарь для задачных и постоянных
     типов — Регламент, «Словарь статусов — строгий»).
  2. Заметка «сделано» без хэша коммита в теле (правило 6).
  3. У задачи, созданной после 2026-08-11, нет секции «Как проверим».
  4. Маркер «⚠️ уточнить» в заметке, которая уже не «запланировано»
     (согласована) — маркеры снимаются до согласования.
  5. В шапке нет поля «тип» или «статус».
  6. У задачи, закрытой с 2026-10-06, нет секции «Осталось после задачи»
     или её пункт без дома (ссылка, «долг №N», «не задача: причина») —
     остатки задачи обязаны получать дом при закрытии.
  7. У такой же задачи, чей раздел «Затрагивает» называет шаблоны,
     статику или панель Django, не заполнен «Вид интерфейса».

Предупреждения (не валят — honest-todo разрешён регламентом):
  - ссылка [[...]] на несуществующую заметку.

Пропускаются: файлы без YAML-шапки (README), шаблоны («Шаблон …»),
автоген (тип: автоген).
"""

import os
import re
import sys
from pathlib import Path

# Windows-консоль по умолчанию не UTF-8 — русские сообщения хуков
# превращаются в кашу; переключаем потоки явно.
for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

# Корень — как у соседних хуков (gate_edit, check_commit): сначала переменная
# среды, потом место файла. Иначе валидатор жёстко смотрел бы только в свой
# проект, и канарейка сторожа не смогла бы проверить, что он кусает: она гоняет
# хуки во временном проекте.
КОРЕНЬ = Path(
    os.environ.get("REGLAMENT_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
VAULT = КОРЕНЬ / "docs" / "vault"

ТИПЫ_ЗАДАЧ = {"задача", "баг", "техдолг"}
ТИПЫ_ПОСТОЯННЫЕ = {"модуль", "решение"}
# meta и справка бывают и постоянным документом («действует» —
# Регламент), и разовым событием («сделано» — Введение регламента);
# для них допустимы оба словаря.
ТИПЫ_СМЕШАННЫЕ = {"meta", "справка"}
СТАТУСЫ_ЗАДАЧ = {"запланировано", "в работе", "сделано", "заморожено"}
СТАТУСЫ_ПОСТОЯННЫХ = {"действует", "заменено"}

# Секция «Как проверим» обязательна для задач, созданных ПОСЛЕ этой
# даты (введена «второй очередью» улучшений; старые не переписываем).
ДАТА_КАК_ПРОВЕРИМ = "2026-08-11"

# Секции «Осталось после задачи» и «Вид интерфейса» обязательны для
# задач, ЗАКРЫТЫХ начиная с этой даты (ADR «Закрытие задачи — остатки и
# видимые изменения», 2026-10-05). Заметки, закрытые раньше, не
# переписываем — приём тот же, что у «Как проверим».
ДАТА_ОСТАТКОВ = "2026-10-06"

# Дом остатка: ссылка на заметку, строка реестра долгов или явный
# отказ «не задача: …».
ДОМ_ОСТАТКА = re.compile(r"\[\[|долг\s*№|не задача", re.I)

# Пункт списка: «- », «* » или «1. » в начале строки.
ПУНКТ_СПИСКА = re.compile(r"^\s*(?:[-*]|\d+[.)])\s+\S")

# Места, после правки которых вид интерфейса обязан быть назван.
ВИДИМЫЕ_МЕСТА = ("templates/", "static/", "панель Django")

# Ссылки не проверяем в файлах с примерами-ссылками (как в graphify).
БЕЗ_ПРОВЕРКИ_ССЫЛОК = ("Шаблон", "Регламент", "README")

# Ссылки-плейсхолдеры из примеров в заметках — не считаются битыми.
ПРИМЕРЫ_ССЫЛОК = {"...", "…", "имя", "имя новой заметки", "ссылки", "ссылка"}

# Хэш коммита: 7-40 hex-символов, хотя бы одна буква a-f
# (иначе совпадают чистые числа вроде дат).
ХЭШ = re.compile(r"\b(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b")


def шапка(текст):
    """Разбирает YAML-шапку. Возвращает (словарь | None, тело)."""
    if not текст.startswith("---"):
        return None, текст
    м = re.match(r"^---\s*\n(.*?)\n---\s*\n?", текст, re.S)
    if not м:
        return None, текст
    поля = {}
    for строка in м.group(1).splitlines():
        if ":" in строка:
            ключ, _, значение = строка.partition(":")
            поля[ключ.strip()] = значение.strip()
    return поля, текст[м.end() :]


def секция(тело, имя):
    """Текст секции «## имя» до следующего заголовка второго уровня."""
    м = re.search(rf"^##\s+{re.escape(имя)}\s*$(.*?)(?=^##\s|\Z)", тело, re.M | re.S)
    return м.group(1) if м else None


def main():
    нарушения = []
    предупреждения = []
    файлы = sorted(VAULT.rglob("*.md"))
    имена = {f.stem for f in файлы}

    for f in файлы:
        имя = f.stem
        отн = f.relative_to(VAULT)
        if имя.startswith("Шаблон"):
            continue
        текст = f.read_text(encoding="utf-8")
        поля, тело = шапка(текст)
        if поля is None:
            continue  # README и прочие файлы без шапки
        тип = поля.get("тип", "")
        статус = поля.get("статус", "")
        if тип == "автоген":
            continue

        if not тип:
            нарушения.append(f"{отн}: в шапке нет поля «тип»")
        if not статус:
            нарушения.append(f"{отн}: в шапке нет поля «статус»")

        if тип in ТИПЫ_ЗАДАЧ:
            словарь = СТАТУСЫ_ЗАДАЧ
        elif тип in ТИПЫ_ПОСТОЯННЫЕ:
            словарь = СТАТУСЫ_ПОСТОЯННЫХ
        elif тип in ТИПЫ_СМЕШАННЫЕ:
            словарь = СТАТУСЫ_ЗАДАЧ | СТАТУСЫ_ПОСТОЯННЫХ
        else:
            словарь = СТАТУСЫ_ЗАДАЧ | СТАТУСЫ_ПОСТОЯННЫХ
            if тип:
                предупреждения.append(
                    f"{отн}: неизвестный тип «{тип}» — статус проверен "
                    f"по объединённому словарю"
                )
        if статус and статус not in словарь:
            нарушения.append(
                f"{отн}: статус «{статус}» не из словаря ({', '.join(sorted(словарь))})"
            )

        if статус == "сделано" and not ХЭШ.search(тело):
            нарушения.append(
                f"{отн}: статус «сделано», но в теле нет хэша коммита (правило 6)"
            )

        if (
            тип in ТИПЫ_ЗАДАЧ
            and поля.get("создано", "") > ДАТА_КАК_ПРОВЕРИМ
            and "## Как проверим" not in тело
        ):
            нарушения.append(f"{отн}: нет секции «Как проверим»")

        # Остатки задачи и вид интерфейса — для задач, закрытых с
        # 2026-10-06 (ADR «Закрытие задачи — остатки и видимые
        # изменения»): знание обязано получить дом, а видимые
        # изменения — быть названными, иначе они теряются.
        if (
            тип in ТИПЫ_ЗАДАЧ
            and статус == "сделано"
            and поля.get("обновлено", "") >= ДАТА_ОСТАТКОВ
        ):
            остатки = секция(тело, "Осталось после задачи")
            if остатки is None:
                нарушения.append(
                    f"{отн}: нет секции «Осталось после задачи» — "
                    f"остатки задачи получают дом при закрытии"
                )
            else:
                for строка in остатки.splitlines():
                    if ПУНКТ_СПИСКА.match(строка) and not ДОМ_ОСТАТКА.search(строка):
                        нарушения.append(
                            f"{отн}: остаток без дома — «{строка.strip()[:60]}» "
                            f"(нужна ссылка [[…]], «долг №N» или «не задача: причина»)"
                        )
            затрагивает = секция(тело, "Затрагивает") or ""
            if any(место in затрагивает for место in ВИДИМЫЕ_МЕСТА):
                вид = секция(тело, "Вид интерфейса")
                if вид is None or вид.strip() in ("", "—", "-"):
                    нарушения.append(
                        f"{отн}: не назван «Вид интерфейса» — задача трогает "
                        f"шаблоны, статику или панель Django"
                    )

        # Маркер — отдельной строкой (в тексте-описании «⚠️ уточнить»
        # в кавычках внутри предложения маркером не считается).
        if re.search(r"^\s*(?:[-*>]\s*)*⚠️ уточнить", тело, re.M) and статус not in (
            "",
            "запланировано",
        ):
            нарушения.append(
                f"{отн}: неснятый маркер «⚠️ уточнить» при статусе "
                f"«{статус}» — маркеры снимаются до согласования"
            )

        if not имя.startswith(БЕЗ_ПРОВЕРКИ_ССЫЛОК):
            for ссылка in re.findall(r"\[\[([^\]]+)\]\]", тело):
                цель = ссылка.split("|")[0].split("#")[0]
                # Перенос строки внутри ссылки (заметки с wrap) и
                # цитатные «>» — нормализуем в один пробел.
                цель = " ".join(с for с in цель.split() if с != ">")
                if цель and цель not in ПРИМЕРЫ_ССЫЛОК and цель not in имена:
                    предупреждения.append(
                        f"{отн}: битая ссылка [[{цель}]] (допустимо как honest-todo)"
                    )

    for п in предупреждения:
        print(f"⚠ {п}")
    for н in нарушения:
        print(f"✗ {н}")
    if нарушения:
        print(f"\nВалидатор vault: {len(нарушения)} нарушение(й).")
        return 1
    print(
        f"Валидатор vault: чисто "
        f"({len(файлы)} файлов, предупреждений: {len(предупреждения)})."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
