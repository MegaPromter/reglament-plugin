#!/usr/bin/env python3
# reglament-plugin v1.4.0 + planapp 2026-09-27 (общее правило согласования;
# согласование — только выбранный в карточке вариант)
"""Хук-блокировка правок кода до согласования (PreToolUse на Edit|Write).

Правило 4 регламента в железной форме: пока заметка активной
задачи не согласована, файлы кода не правятся.
Всегда разрешены: docs/ (включая vault), .claude/ (табло, хуки,
навыки) и всё вне проекта (память ИИ, черновики-scratchpad).

Согласование — это КЛИК пользователя по варианту «Согласовано» в
карточке вопроса (AskUserQuestion). Хук ищет ответ в стенограмме
сессии: её путь Claude Code передаёт на вход (transcript_path).
Засчитывается только запись ответа на карточку — у неё есть поле
«ответы» (`toolUseResult.answers`: вопрос → выбранный вариант), его
пишет Claude Code, а не ассистент. Результаты остальных инструментов
(прочитанный файл, вывод команды) в стенограмме тоже записаны от
имени пользователя, но такого поля у них нет: слово «Согласовано»
рядом с названием задачи в их тексте согласованием не считается.
Название задачи в тексте вопроса привязывает согласование к текущей
задаче: «Согласовано» от прошлой задачи и на соседний вопрос той же
карточки не засчитывается.

Найдя согласование, хук сам ставит отметку в табло — чтобы задача,
продолженная в НОВОЙ сессии (другая стенограмма), не потребовала
согласовывать заново. Отметке верим только со ссылкой на запись
ответа (ключ «одобрено_записью») и для той задачи, к которой она
поставлена (ключ «одобрено_задача»): её проставляет этот хук.

Правило «задача согласована?» — функция `задача_согласована` здесь;
её же зовут хук оболочки (gate_shell.py — правки командами терминала)
и контролёр коммита (check_commit.py) — vault «Блокировка правок кода
через терминал до согласования».

Пустое табло — напоминание, не блок (косметика и опечатки по уставу
процедуры не требуют; на выходе их страхует контролёр коммита).

Выходы: 0 — пропустить; 2 — заблокировать (объяснение в stderr).

"""

import json
import os
import sys
from datetime import datetime
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(
    os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
ТАБЛО = КОРЕНЬ / ".claude" / "task-state.json"
ФАЗЫ_ПОСЛЕ_СОГЛАСОВАНИЯ = ("согласовано", "код", "тесты", "коммит")
# Вариант карточки, который считается согласованием.
ВАРИАНТ_СОГЛАСИЯ = "Согласовано"


def ответы_карточки(запись):
    """Пары «вопрос → выбранный вариант» из записи ответа на карточку
    вопроса: Claude Code кладёт их в поле `toolUseResult.answers`
    результата инструмента AskUserQuestion. У результатов других
    инструментов этого поля нет — пусто."""
    результат = запись.get("toolUseResult")
    if not isinstance(результат, dict):
        return {}
    ответы = результат.get("answers")
    return ответы if isinstance(ответы, dict) else {}


def найти_согласование(путь_стенограммы, задача):
    """UUID записи с ответом «Согласовано» по этой задаче или None.

    Засчитывается только выбранный в карточке вариант: вопрос называет
    задачу, ответ именно на этот вопрос — ровно «Согласовано». Раньше
    хватало, чтобы оба слова стояли в одной записи от имени пользователя,
    и 2026-09-27 чтение файла статуса (там «Согласовано» от прошлой задачи
    стояло рядом с названием следующей) поставило ложный штамп (журнал
    мелких правок)."""
    if not путь_стенограммы or not задача:
        return None
    файл = Path(путь_стенограммы)
    if not файл.exists():
        return None
    try:
        строки = файл.read_text(encoding="utf-8", errors="ignore").splitlines()
    except Exception:
        return None
    for строка in reversed(строки):
        # Грубый отсев по сырой строке: в стенограмме русский текст
        # лежит как есть, без \u-экранирования.
        if ВАРИАНТ_СОГЛАСИЯ not in строка or задача not in строка:
            continue
        try:
            запись = json.loads(строка)
        except Exception:
            continue
        if запись.get("type") != "user":
            continue
        for вопрос, ответ in ответы_карточки(запись).items():
            if задача in вопрос and ответ == ВАРИАНТ_СОГЛАСИЯ:
                return запись.get("uuid") or "без-uuid"
    return None


def отметить_в_табло(табло, запись_uuid):
    """Штамп в табло, чтобы согласование пережило конец сессии.
    Штамп помнит, к какой задаче он относится (`одобрено_задача`): табло
    новой задачи, записанное поверх старого без чистки, иначе унаследовало
    бы чужое согласование."""
    табло["одобрено"] = True
    табло["одобрено_в"] = datetime.now().strftime("%Y-%m-%d %H:%M")
    табло["одобрено_записью"] = запись_uuid
    табло["одобрено_задача"] = табло.get("задача")
    try:
        ТАБЛО.write_text(
            json.dumps(табло, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    except Exception:
        pass  # не смогли записать — согласование всё равно найдено


def отметка_верна(табло):
    """Штамп поставлен хуком (есть ссылка на запись ответа) и относится к
    текущей задаче. Штамп старого вида — без имени задачи — считается
    верным: так их ставили до 2026-09-27."""
    if табло.get("одобрено") is not True or not табло.get("одобрено_записью"):
        return False
    задача_штампа = табло.get("одобрено_задача")
    return задача_штампа is None or задача_штампа == табло.get("задача")


def задача_согласована(табло, путь_стенограммы):
    """Согласована ли активная задача табло — ОДНО правило для всех хуков
    (gate_edit, gate_shell, check_commit; vault «Блокировка правок кода
    через терминал до согласования»).

    Малая форма — фаза не раньше «согласовано» (словесное «да»). Полная —
    штамп этого хука для этой задачи или ответ «Согласовано» в стенограмме
    сессии (тогда штамп ставится). Штамп проверяется первым: поиск по
    стенограмме на большой сессии (80 МБ) стоит почти секунду, а хук
    оболочки зовут на каждую команду терминала. Задачи нет — False:
    согласовывать нечего, решают вызывающие."""
    задача = табло.get("задача")
    if not задача:
        return False
    if табло.get("форма", "полная") == "малая":
        return табло.get("фаза", "") in ФАЗЫ_ПОСЛЕ_СОГЛАСОВАНИЯ
    if отметка_верна(табло):
        return True
    запись = найти_согласование(путь_стенограммы, задача)
    if запись:
        отметить_в_табло(табло, запись)
        return True
    return False


def прочитать_табло():
    """Табло задачи; нет файла или он испорчен — пустое."""
    if not ТАБЛО.exists():
        return {}
    try:
        return json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return {}


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return 0
    путь = (данные.get("tool_input") or {}).get("file_path") or ""
    if not путь:
        return 0
    try:
        отн = Path(путь).resolve().relative_to(КОРЕНЬ.resolve())
    except ValueError:
        return 0  # вне проекта: память ИИ, черновики
    отн_с = str(отн).replace("\\", "/").lower()
    if отн_с.startswith("docs/") or отн_с.startswith(".claude/"):
        return 0

    табло = прочитать_табло()
    задача = табло.get("задача")
    if not задача:
        print(
            "Напоминание: активной задачи в табло нет. Если это "
            "задача по коду — начни с процедуры /reglament "
            "(заметка до кода). Косметика и опечатки — можно без "
            "процедуры."
        )
        return 0

    # Правило согласования — одно на все хуки (задача_согласована выше):
    # малая форма — фаза, полная — ответ пользователя в стенограмме или
    # штамп, поставленный хуком раньше для этой задачи
    if задача_согласована(табло, данные.get("transcript_path")):
        return 0

    if табло.get("форма", "полная") == "малая":
        print(
            f"Правка кода заблокирована: задача «{задача}» в фазе "
            f"«{табло.get('фаза', '')}» — подтверждения малой формы ещё "
            f"нет. Дождись «да» пользователя и переведи фазу в "
            f"«согласовано».",
            file=sys.stderr,
        )
        return 2

    print(
        f"Правка кода заблокирована: заметка задачи «{задача}» не "
        f"согласована. Покажи пользователю ПРОЕКТ заметки и задай "
        f"карточку вопроса (инструмент AskUserQuestion): в тексте "
        f"вопроса — название задачи «{задача}», среди вариантов — "
        f"«{ВАРИАНТ_СОГЛАСИЯ}» и вариант отказа. Клик пользователя "
        f"по «{ВАРИАНТ_СОГЛАСИЯ}» и есть согласование; ставить его "
        f"за пользователя нельзя.",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
