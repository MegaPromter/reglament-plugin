#!/usr/bin/env python3
# reglament-plugin v1.4.0
"""Хук контроля незавершённых шагов (Stop — ассистент закончил ход).

Принцип 10 регламента (забывчивость лечится скриптом, а не ужесточением текста).
Два правила:

1. Фаза «заметка», согласования нет — ход не заканчивается молча: ассистент либо
   задаёт карточку вопроса, либо заканчивает ход конкретным вопросом.
2. Любая другая незакрытая фаза: шаг фазы не сделан — ход не заканчивается молча
   (решения О1 и М2.2). Что считается сделанным, решает `phase_rules.py`: правило
   живёт одним местом, и то же самое спрашивает автозакрытие.

Остановка уже записана в табло (`ждёт`) — ход заканчивать законно: контур сам
сказал, чего ждёт от человека (решение О3). Малая форма идёт без карточки — там
ждать нечего.

Согласование ищется там же, где его ищет gate_edit.py: в стенограмме сессии.
Общая функция берётся импортом из gate_edit — чтобы правило было записано в одном
месте (оба файла лежат рядом, в .reglament/hooks/).

Защита от цикла: `stop_hook_active` (ход уже разворачивали), потолок возвратов на
ход у сторожа и бюджет возвратов на ЗАДАЧУ в табло (решение М2.3) — его считает
сторож, прежде чем вернуть ассистента ещё раз.

Выходы: 0 — пропустить ход; stdout с {"decision": "block"} — вернуть ассистента,
текст reason уйдёт ему как инструкция.
"""

import json
import os
import re
import sys
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

try:  # правило согласования живёт в gate_edit.py, дублировать нельзя
    from gate_edit import ВАРИАНТ_СОГЛАСИЯ, найти_согласование
except Exception:  # соседа нет — молчим, чтобы не блокировать зря
    ВАРИАНТ_СОГЛАСИЯ = None
    найти_согласование = None

КОРЕНЬ = Path(
    os.environ.get("REGLAMENT_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
ТАБЛО = КОРЕНЬ / ".reglament" / "task-state.json"

# Правила фаз живут в инструментах (`.dsh/tools/phase_rules.py`). Раскладок две —
# комплект и развёрнутый проект, — поэтому пробуем обе (дефект D21).
правила = None
for _кандидат in (КОРЕНЬ / ".dsh" / "tools", КОРЕНЬ / "tools"):
    if (_кандидат / "phase_rules.py").is_file():
        sys.path.insert(0, str(_кандидат))
        import phase_rules as правила  # noqa: E402

        break

СТАТУС_ЗАМЕТКИ = re.compile(r"^статус:\s*(.+?)\s*$", re.M)

# Единственная фаза, в которой ждём согласования (словарь фаз: vault →
# заметка → согласовано → код → тесты → коммит → закрыто).
ФАЗА_ОЖИДАНИЯ = "заметка"


def пропустить():
    return 0


def вернуть(причина):
    """Блокировка завершения хода: reason уходит ассистенту."""
    print(json.dumps({"decision": "block", "reason": причина}, ensure_ascii=False))
    return 0


def прочитать_табло():
    """Табло задачи; нет файла или он испорчен — пустое."""
    if not ТАБЛО.exists():
        return {}
    try:
        return json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return {}


def статус_заметки(путь):
    """Статус из шапки заметки; нет файла — пусто."""
    if путь is None:
        return ""
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError:
        return ""
    найдено = СТАТУС_ЗАМЕТКИ.search(текст)
    return найдено.group(1).strip() if найдено else ""


def шаг_фазы_не_сделан(табло):
    """Чего не хватает шагу фазы; пусто — шаг сделан или правил для фазы нет."""
    if правила is None:
        return ""
    заметка = КОРЕНЬ / str(табло["заметка"]) if табло.get("заметка") else None
    состояния = правила.состояния_задачи(
        табло,
        заметка is not None and заметка.is_file(),
        статус_заметки(заметка),
    )
    вердикт = правила.вердикт(str(табло.get("фаза") or ""), состояния)
    if вердикт["не_сделано"]:
        return правила.словами(вердикт["не_сделано"])
    return ""


def main():
    if найти_согласование is None:
        return пропустить()
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return пропустить()

    # Встроенный страж цикла: ход уже разворачивали — не мешаем.
    if данные.get("stop_hook_active") is True:
        return пропустить()

    табло = прочитать_табло()
    задача = табло.get("задача")
    if not задача:
        return пропустить()
    # Малая форма идёт без карточки — там ждать нечего.
    if табло.get("форма") == "малая":
        return пропустить()
    # Остановка уже записана: контур сказал, чего ждёт от человека (решение О3).
    if табло.get("ждёт"):
        return пропустить()

    последнее = (данные.get("last_assistant_message") or "").rstrip()
    фаза = str(табло.get("фаза") or "")

    согласовано = найти_согласование(данные.get("transcript_path"), задача) or (
        табло.get("одобрено") is True and табло.get("одобрено_записью")
    )

    if фаза == ФАЗА_ОЖИДАНИЯ and not согласовано:
        # Ход-вопрос: согласование ещё обсуждается, не мешаем.
        if последнее.endswith("?"):
            return пропустить()
        return вернуть(
            f"Задача «{задача}» в фазе «заметка», согласования нет, а ход "
            f"закончился без действия для пользователя. Если проект "
            f"заметки показан — задай карточку вопроса (инструмент "
            f"AskUserQuestion): в тексте вопроса название задачи "
            f"«{задача}», среди вариантов «{ВАРИАНТ_СОГЛАСИЯ}» и вариант "
            f"отказа. Клик по «{ВАРИАНТ_СОГЛАСИЯ}» и есть согласование — "
            f"работа продолжится тем же ходом, ждать и будить сессию не "
            f"нужно. Если заметка ещё не показана или обсуждается — "
            f"заверши ход конкретным вопросом пользователю."
        )

    # Остальные незакрытые фазы: шаг не сделан — сказать, чего именно не хватает.
    не_хватает = шаг_фазы_не_сделан(табло)
    if не_хватает and not последнее.endswith("?"):
        return вернуть(
            f"Задача «{задача}» в фазе «{фаза}», а шаг фазы не сделан: "
            f"{не_хватает}. Сделай шаг и отметь его (пункты «Как проверим» — "
            f"списком `проверки` в табло), либо запиши в табло `ждёт`: чего "
            f"контур ждёт от человека, — либо закончи ход конкретным "
            f"вопросом пользователю."
        )

    return пропустить()


if __name__ == "__main__":
    sys.exit(main())
