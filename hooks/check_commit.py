#!/usr/bin/env python3
# reglament-plugin v1.4.0 + planapp 2026-09-27 (барьер согласования)
"""Хук-контролёр коммита (PreToolUse на Bash) — правило 5 регламента.

Читает JSON вызова инструмента из stdin. Пропускает всё, кроме:
  1. git commit без ссылки на документацию — блок. Разрешают коммит:
     - все файлы коммита внутри docs/vault/ (сам vault);
     - «vault: «Имя заметки»» в сообщении (заметка должна существовать);
     - пометка «журнал мелких правок» (малая форма);
     - метка-исключение из устава: косметика / линтер / опечатка / откат;
     - revert.
  2. коммита с файлами vault, если валидатор vault находит нарушения;
  3. коммита с файлами кода, пока задача в табло не согласована (правило
     4, последний барьер для правок любым инструментом — vault
     «Блокировка правок кода через терминал до согласования»).

Коммит в ЧУЖОЙ репозиторий (соседний проект, репозиторий плагина)
пропускается: регламент этого проекта к нему не относится.

Выходы: 0 — пропустить; 2 — заблокировать (объяснение в stderr).
"""

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

# Windows-Python по умолчанию читает и пишет не в UTF-8 — русские
# сообщения превращаются в кашу, а кириллица из JSON на входе не
# распознаётся; переключаем ВСЕ потоки явно (stdin — обязательно:
# харнесс шлёт JSON в UTF-8).
for _поток in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(
    os.environ.get("REGLAMENT_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
VAULT = КОРЕНЬ / "docs" / "vault"
МЕТКИ_ИСКЛЮЧЕНИЯ = ("косметика", "линтер", "опечатка", "откат")

try:  # правило согласования живёт в gate_edit.py, дублировать нельзя
    from gate_edit import задача_согласована, прочитать_табло
except Exception:  # соседа нет — барьер согласования молчит
    задача_согласована = None
    прочитать_табло = None


def несогласованный_код(данные, файлы, известен):
    """Правило 4 — последний барьер: коммит с файлами кода, когда задача в
    табло не согласована, не проходит, чем бы код ни правили (Edit, Write
    или команды терминала — vault «Блокировка правок кода через терминал
    до согласования»). Возвращает текст отказа или None.

    Пустое табло — не барьер: косметика и опечатки идут без процедуры (их
    страхуют метки-исключения ниже). Состав коммита неизвестен заранее
    (`git add -A`, `git add .`) — считаем, что код в нём есть."""
    if задача_согласована is None:
        return None
    табло = прочитать_табло()
    задача = табло.get("задача")
    if not задача:
        return None
    код = [ф for ф in файлы if not ф.lower().startswith(("docs/", ".reglament/"))]
    if известен and not код:
        return None
    if задача_согласована(табло, данные.get("transcript_path")):
        return None
    перечень = ", ".join(код[:5]) or "состав коммита заранее не известен"
    return (
        f"Коммит заблокирован (правило 4 регламента): в нём файлы кода "
        f"({перечень}), а задача «{задача}» в табло не согласована. "
        f"Сначала согласование заметки — карточка вопроса (малая форма — "
        f"«да» пользователя и фаза «согласовано»). Если коммит к этой "
        f"задаче не относится — закрой или отложи её в табло."
    )


def файлы_коммита(команда):
    """Файлы будущего коммита: уже в индексе + аргументы git add
    из той же команды. Возвращает (список, точно_ли_известен)."""
    файлы = []
    известен = True
    # core.quotepath=false — пути как есть: по умолчанию git экранирует
    # кириллицу («"docs/vault/\320\267…"»), и заметка с русским именем не
    # узнавалась как файл vault — валидатор на таком коммите молча не
    # запускался (найдено 2026-09-27, vault «Блокировка правок кода через
    # терминал до согласования»)
    р = subprocess.run(
        [
            "git",
            "-c",
            "core.quotepath=false",
            "-C",
            str(КОРЕНЬ),
            "diff",
            "--cached",
            "--name-only",
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if р.returncode == 0:
        файлы += [с for с in р.stdout.splitlines() if с.strip()]
    for сегмент in re.split(r"&&|;|\|\|", команда):
        м = re.search(r"\bgit\s+add\s+(.*)$", сегмент.strip())
        if not м:
            continue
        try:
            токены = shlex.split(м.group(1))
        except ValueError:
            известен = False
            continue
        for т in токены:
            if т in (".", "-A", "--all", "-u", "--update") or т.startswith("-"):
                известен = False
            else:
                файлы.append(т)
    return файлы, известен


def есть_вызов_коммита(команда):
    """Настоящий вызов `git commit`, а не слово «commit» внутри имени
    файла (`pre-commit-tests.sh`), ветки или текста сообщения.

    Разбор по токенам: ищем токен «git», а следом —
    токен ровно «commit», пропуская между ними глобальные ключи git
    (`-C путь`, `-c ключ=значение`, `--git-dir=…`, `--no-pager`)."""
    for сегмент in re.split(r"&&|;|\|\||\|", команда):
        try:
            токены = shlex.split(сегмент)
        except ValueError:
            # Незакрытая кавычка — например, тело heredoc с сообщением.
            токены = сегмент.split()
        for i, т in enumerate(токены):
            if т.rsplit("/", 1)[-1] != "git":
                continue
            j = i + 1
            while j < len(токены):
                if токены[j] in ("-C", "-c", "--git-dir", "--work-tree"):
                    j += 2  # ключ, значение которого — отдельный токен
                elif токены[j].startswith("-"):
                    j += 1
                else:
                    break
            if j < len(токены) and токены[j] == "commit":
                return True
    return False


def целевая_папка(данные, команда):
    """Папка, в которой на самом деле выполнится коммит: учитываем
    `cd путь` и ключ `git -C путь` в самой команде, иначе — папка
    сессии из входного JSON."""
    папка = Path(данные.get("cwd") or КОРЕНЬ)

    def разрешить(путь):
        п = Path(путь)
        return п if п.is_absolute() else папка / п

    for сегмент in re.split(r"&&|;|\|\||\|", команда):
        # posix=False — иначе shlex съедает обратные слэши, и путь
        # Windows (D:\Program\…) превращается в мусор; кавычки при
        # этом остаются в токене, снимаем их сами.
        try:
            токены = [т.strip("\"'") for т in shlex.split(сегмент, posix=False)]
        except ValueError:
            токены = [т.strip("\"'") for т in сегмент.split()]
        if not токены:
            continue
        if токены[0] == "cd" and len(токены) > 1 and not токены[1].startswith("-"):
            папка = разрешить(токены[1])
        for i, т in enumerate(токены):
            if (
                т.rsplit("/", 1)[-1] == "git"
                and i + 2 < len(токены)
                and токены[i + 1] == "-C"
            ):
                папка = разрешить(токены[i + 2])
    return папка


def верх_репозитория(папка):
    """Корень репозитория для папки; None — определить не удалось."""
    try:
        р = subprocess.run(
            ["git", "-C", str(папка), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
    except OSError:
        return None
    if р.returncode != 0 or not р.stdout.strip():
        return None
    try:
        return Path(р.stdout.strip()).resolve()
    except OSError:
        return None


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return 0
    команда = (данные.get("tool_input") or {}).get("command") or ""
    if not команда:
        return 0

    if not есть_вызов_коммита(команда):
        return 0

    # Регламент этого проекта — про ЭТОТ репозиторий. Коммит в чужой
    # (соседний проект, репозиторий плагина) пропускаем: его документация
    # тут ни при чём, а у него свои хуки. Неопределённость — в пользу
    # проверки: лучше лишний раз спросить ссылку, чем пропустить коммит
    # этого проекта мимо регламента.
    свой = верх_репозитория(КОРЕНЬ)
    цель = верх_репозитория(целевая_папка(данные, команда))
    if свой and цель and цель != свой:
        return 0

    if re.search(r"\bgit\s+revert\b", команда) or 'Revert "' in команда:
        return 0

    файлы, известен = файлы_коммита(команда)
    файлы = [ф.replace("\\", "/") for ф in файлы]
    только_vault = (
        известен and файлы and all(ф.startswith("docs/vault/") for ф in файлы)
    )
    есть_vault = any(ф.startswith("docs/vault/") for ф in файлы)

    # Валидатор vault — на любой коммит, задевающий docs/vault/.
    if есть_vault:
        в = subprocess.run(
            [sys.executable, str(Path(__file__).with_name("validate_vault.py"))],
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        if в.returncode != 0:
            print(
                "Валидатор vault нашёл нарушения — коммит "
                "заблокирован:\n" + (в.stdout or "") + (в.stderr or ""),
                file=sys.stderr,
            )
            return 2

    if только_vault:
        return 0

    # Код несогласованной задачи в историю не попадает — даже с меткой
    # или ссылкой на заметку в сообщении
    отказ = несогласованный_код(данные, файлы, известен)
    if отказ:
        print(отказ, file=sys.stderr)
        return 2

    ниже = команда.lower()
    if "журнал мелких правок" in ниже:
        return 0
    if any(метка in ниже for метка in МЕТКИ_ИСКЛЮЧЕНИЯ):
        return 0
    # Ссылка на заметку: vault: «Имя» — кавычки любого вида.
    м = re.search(r"vault:\s*[«\"„']([^»\"“']+)[»\"“']", команда)
    if м:
        имя = м.group(1).strip()
        if any(ф.stem == имя for ф in VAULT.rglob("*.md")):
            return 0
        print(
            f"В сообщении названа заметка «{имя}», но файла "
            f"«{имя}.md» в docs/vault/ нет. Проверь имя заметки.",
            file=sys.stderr,
        )
        return 2

    print(
        "Коммит заблокирован (правило 5 регламента): в сообщении "
        "нет ссылки на документацию. Добавь одно из:\n"
        "  - vault: «Имя заметки» (заметка должна существовать);\n"
        "  - пометку «журнал мелких правок» (малая форма);\n"
        "  - метку-исключение из устава: косметика / линтер / "
        "опечатка / откат.",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
