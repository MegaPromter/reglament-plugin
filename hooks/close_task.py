#!/usr/bin/env python3
# reglament-plugin v1.4.0
"""Автозакрытие задачи — бухгалтерия шага закрытия одним вызовом.

Полная форма:  дописывает в заметку хэш коммита, ставит статус
«сделано», обновляет дату — и коммитит.
Малая форма:   вставляет строку в журнал мелких правок — и коммитит.
Перед коммитом гоняются проверки — неприменённые миграции дев-базы и валидатор
vault; после — очищает табло.

Проверки идут ДО правок, а отказ не портит состояние: заметка, журнал и табло
остаются как были. Раньше заметка переводилась в «сделано» до валидатора и при
отказе оставалась закрытой без коммита (грабли 10.10.2026).

Близнец этого файла — `tools/close_task.py` (версия ДСХ): правки вносить в оба.
Разница сред: у ДСХ коммит идёт через склад проверяльщика в рабочей папке, здесь
— обычный git.

Запуск (полная):  python .reglament/hooks/close_task.py [--hash abc1234]
Запуск (малая):   python .reglament/hooks/close_task.py --desc "что сделано" \
                  --files "какие файлы" [--hash abc1234]
Осознанный обход проверки миграций (только по согласованию; причина обязательна и
остаётся следом в «Истории» заметки): --allow-pending "почему закрываем так".
Без --hash берётся последний коммит (HEAD).
"""

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

# Windows-консоль по умолчанию не UTF-8 — русские сообщения хуков
# превращаются в кашу; переключаем потоки явно.
for _поток in (sys.stdout, sys.stderr):
    if hasattr(_поток, "reconfigure"):
        _поток.reconfigure(encoding="utf-8")

# Неприменённая миграция в выводе `manage.py showmigrations --plan`: «[ ] app имя».
НЕПРИМЕНЁННАЯ = re.compile(r"^\s*\[\s\]\s+(\S+)\s+(\S+)")

# «Спросить не удалось» — не то же самое, что «неприменённых нет»: закрытие
# необратимо, поэтому неизвестность здесь разрешением не считается.
НЕИЗВЕСТНО = object()


def корень_проекта() -> Path:
    """Корень проекта: из `REGLAMENT_PROJECT_DIR`, а без него — по месту хука.

    Переменная среды — главный способ прежней среды сказать, о каком проекте
    речь. Но если она указывает не на корень проекта (нет ни `.reglament`, ни
    `manage.py`), доверять ей нельзя: иначе проверка миграций и правка vault
    уйдут не по тому проекту — молча и с «успехом».
    """
    из_среды = os.environ.get("REGLAMENT_PROJECT_DIR")
    if из_среды:
        путь = Path(из_среды)
        if (путь / ".reglament").is_dir() or (путь / "manage.py").is_file():
            return путь
        print(
            f"REGLAMENT_PROJECT_DIR={путь} не похож на корень проекта "
            "(нет .reglament и manage.py) — беру корень по месту хука."
        )
    return Path(__file__).resolve().parents[2]


КОРЕНЬ = корень_проекта()
ТАБЛО = КОРЕНЬ / ".reglament" / "task-state.json"
ЖУРНАЛ = КОРЕНЬ / "docs" / "vault" / "задачи" / "Мелкие правки (журнал).md"


def гит(*аргументы, проверять=True):
    р = subprocess.run(
        ["git", "-C", str(КОРЕНЬ)] + list(аргументы),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if проверять and р.returncode != 0:
        raise RuntimeError(f"git {' '.join(аргументы)}:\n{р.stdout}{р.stderr}")
    return р


def неприменённые_миграции():
    """Неприменённые миграции дев-базы.

    Список — есть неприменённые (пустой список — всё применено).
    None — проверять нечего: `manage.py` нет, проект не Django (сказано вслух).
    НЕИЗВЕСТНО — спросить не удалось; закрытие необратимо, и «неизвестно»
    разрешением здесь не считается.
    """
    manage = КОРЕНЬ / "manage.py"
    if not manage.is_file():
        print("миграции: manage.py не найден — проверка не выполнялась")
        return None
    питон = КОРЕНЬ / "venv" / "Scripts" / "python.exe"
    if питон.is_file():
        команда = [str(питон)]
    else:
        print(
            "venv не найден — миграции проверяются системным Python: версии "
            "библиотек могут расходиться с продом (долг №55)"
        )
        команда = ["python"]
    try:
        итог = subprocess.run(
            [*команда, str(manage), "showmigrations", "--plan"],
            cwd=str(КОРЕНЬ),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env={**os.environ, "PYTHONUTF8": "1"},
        )
    except OSError as ошибка:
        print(f"миграции: спросить не удалось — {ошибка}")
        return НЕИЗВЕСТНО
    if итог.returncode != 0:
        строки = f"{итог.stdout or ''}{итог.stderr or ''}".strip().splitlines()
        причина = строки[-1] if строки else "без объяснения"
        print(
            f"миграции: `manage.py showmigrations` упал "
            f"(код {итог.returncode}): {причина}"
        )
        return НЕИЗВЕСТНО
    return [
        f"{совпадение.group(1)}.{совпадение.group(2)}"
        for совпадение in (
            НЕПРИМЕНЁННАЯ.match(строка) for строка in (итог.stdout or "").splitlines()
        )
        if совпадение
    ]


def проверить_миграции(причина_обхода: str):
    """Проверка до правок: (можно закрывать, след для заметки).

    След пуст, если обходить нечего. Причина обхода без следа не бывает: обход
    обязан быть виден в заметке, иначе он неотличим от отсутствия проверки.
    """
    миграции = неприменённые_миграции()
    беда = ""
    if миграции is НЕИЗВЕСТНО:
        беда = "миграции к дев-базе: спросить не удалось"
    elif миграции:
        беда = f"миграции к дев-базе не применены ({', '.join(миграции)})"
    if not беда:
        return True, ""
    if причина_обхода:
        print(f"ВНИМАНИЕ: обход проверки миграций — {беда}; причина: {причина_обхода}")
        след = (
            f"- {date.today().isoformat()}: {беда}; "
            f"закрытие с обходом: {причина_обхода}.\n"
        )
        return True, след
    if миграции is НЕИЗВЕСТНО:
        print(
            "Закрытие остановлено: применить ли миграции к дев-базе — неизвестно,\n"
            "а «неизвестно» здесь не разрешение. Проверьте базу и повторите закрытие.\n"
            'Осознанный обход (только по согласованию): --allow-pending "причина".'
        )
    else:
        перечень = "\n".join(f"  - {имя}" for имя in миграции)
        print(
            f"В дев-базе не применены миграции:\n{перечень}\n"
            "Примените: venv\\Scripts\\python.exe manage.py migrate — и повторите "
            "закрытие.\n"
            "Закрытие остановлено: заметка, журнал и табло не тронуты.\n"
            'Осознанный обход (только по согласованию): --allow-pending "причина".'
        )
    return False, ""


def проверить_vault():
    """Валидатор vault — общий для проекта: закрывать можно только чистый."""
    итог = subprocess.run(
        [sys.executable, str(Path(__file__).with_name("validate_vault.py"))],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    print(итог.stdout, end="")
    return итог.returncode == 0


def записать_в_журнал(сегодня, хэш, сделано, файлы, причина_обхода=""):
    """Малая форма: строка в журнал мелких правок."""
    описание = (
        f"{сделано} — обход проверки миграций: {причина_обхода}"
        if причина_обхода
        else сделано
    )
    строки = ЖУРНАЛ.read_text(encoding="utf-8").splitlines(keepends=True)
    for номер, строка in enumerate(строки):
        if строка.startswith("|---"):
            строки.insert(номер + 1, f"| {сегодня} | {описание} | {файлы} | {хэш} |\n")
            break
    else:
        raise SystemExit("В журнале не найдена шапка таблицы.")
    ЖУРНАЛ.write_text("".join(строки), encoding="utf-8")


def закрыть_полную(сегодня, хэш, путь, след=""):
    """Полная форма: хэш в «Историю», статус «сделано», свежая дата."""
    текст = путь.read_text(encoding="utf-8")
    for старый in ("статус: в работе", "статус: запланировано"):
        if старый in текст:
            текст = текст.replace(старый, "статус: сделано", 1)
            break
    текст = "\n".join(
        f"обновлено: {сегодня}" if строка.startswith("обновлено:") else строка
        for строка in текст.splitlines()
    )
    if not текст.endswith("\n"):
        текст += "\n"
    if след:
        текст += след
    текст += f"- {сегодня}: реализовано в коммите {хэш}.\n"
    путь.write_text(текст, encoding="utf-8")


def main():
    п = argparse.ArgumentParser()
    п.add_argument("--hash", help="хэш коммита (по умолчанию HEAD)")
    п.add_argument("--desc", help="малая форма: что сделано")
    п.add_argument("--files", help="малая форма: какие файлы")
    п.add_argument(
        "--allow-pending",
        metavar="ПРИЧИНА",
        help=(
            "закрыть при неприменённых миграциях дев-базы: причина обязательна "
            "и остаётся следом в «Истории» заметки"
        ),
    )
    арг = п.parse_args()

    табло = {}
    if ТАБЛО.exists():
        табло = json.loads(ТАБЛО.read_text(encoding="utf-8"))
    if not табло.get("задача"):
        print("Активной задачи в табло нет — закрывать нечего.")
        return 1

    имя = табло["задача"]
    форма = табло.get("форма", "полная")
    if форма == "малая" and not (арг.desc and арг.files):
        print("Для малой формы обязательны --desc и --files.")
        return 1

    заметка = None if форма == "малая" else КОРЕНЬ / табло["заметка"]
    if заметка is not None and not заметка.exists():
        print(f"Заметка не найдена: {заметка}")
        return 1

    причина_обхода = (арг.allow_pending or "").strip()
    if арг.allow_pending is not None and not причина_обхода:
        print('Обход проверки миграций требует причины: --allow-pending "почему"')
        return 1

    # ── проверки до правок: отказ не портит состояние ──────────────────────
    можно, след = проверить_миграции(причина_обхода)
    if not можно:
        return 1

    хэш = арг.hash or гит("rev-parse", "--short", "HEAD").stdout.strip()
    сегодня = date.today().isoformat()

    изменён = ЖУРНАЛ if форма == "малая" else заметка
    исходный = изменён.read_text(encoding="utf-8")

    if форма == "малая":
        записать_в_журнал(
            сегодня,
            хэш,
            арг.desc,
            арг.files,
            причина_обхода if след else "",
        )
        сообщение = f"docs(vault): запись в журнал мелких правок ({хэш})"
    else:
        закрыть_полную(сегодня, хэш, изменён, след)
        сообщение = f"docs(vault): закрытие задачи «{имя}» — хэш {хэш}, статус сделано"

    # Валидатор — закрывать можно только чистый vault. Отказ не портит
    # состояние: правка откатывается к исходному тексту.
    if not проверить_vault():
        изменён.write_text(исходный, encoding="utf-8")
        print("Валидатор нашёл нарушения — правка откатана, закрывающий коммит не сделан.")
        return 1

    # Только явные пути этой задачи: git add -u утащил бы чужие
    # незакоммиченные правки (грабля коммита 911953b).
    гит("add", str(изменён.relative_to(КОРЕНЬ)))
    к = гит("commit", "-m", сообщение, проверять=False)
    if к.returncode != 0:
        # pre-commit мог поправить файл (пробелы) — добавить и повторить.
        гит("add", str(изменён.relative_to(КОРЕНЬ)))
        к = гит("commit", "-m", сообщение)
    новый = гит("rev-parse", "--short", "HEAD").stdout.strip()

    ТАБЛО.write_text("{}\n", encoding="utf-8")
    print(
        f"Задача «{имя}» закрыта: хэш {хэш} записан, "
        f"закрывающий коммит {новый}, табло очищено."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
