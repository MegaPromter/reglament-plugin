#!/usr/bin/env python3
# reglament-plugin v1.4.0 + planapp 2026-09-27 (хук оболочки)
"""Хук оболочки: правило 4 регламента для команд терминала — Bash и
PowerShell (vault «Блокировка правок кода через терминал до согласования»).

gate_edit.py не пускает правки кода инструментами Edit и Write, пока
заметка не согласована. Команда терминала может записать файл как угодно
(скрипт, `sed -i`, перенаправление, `cp`, `git checkout`), и по её тексту
надёжно не понять, что она запишет. Поэтому хук сравнивает состояние до и
после команды:

- PreToolUse (до команды): в табло задача, и она не согласована — хук
  запоминает отпечаток файлов кода, отличающихся от последнего коммита
  (`git status`: путь → размер и время изменения); согласована — ставит
  штамп в табло, как gate_edit.py (задача, продолженная в новой сессии,
  не согласовывается заново); табло пустое — молчит;
- PostToolUse и PostToolUseFailure (после команды, в том числе упавшей):
  отпечаток сравнивается; изменённые, созданные и удалённые командой файлы
  кода — сообщение ассистенту. Файлы, которые команда вернула к состоянию
  коммита, не в счёт: вернуть свою правку — ровно то, что от него ждут.

Файлы кода — как у gate_edit.py: всё в проекте, кроме `docs/` и
`.reglament/`; файлы вне учёта git (`.gitignore`: мокапы, кэши) не
смотрятся. Хук ничего сам не откатывает — он не знает, чья это правка
(параллельная сессия в той же папке), откатывает ассистент. Последний
барьер — контролёр коммита (check_commit.py): код несогласованной задачи
в историю не пропускается.

Правило «задача согласована?» — одно на все хуки, импортом из
gate_edit.py (оба файла лежат рядом, в .reglament/hooks/).

Выходы: 0 — пропустить; 2 после команды — сообщение ассистенту в stderr
(команда уже выполнена, хук её не отменяет). Сбой самого хука — молчим:
лучше пропустить сообщение, чем мешать работе; барьер коммита остаётся.
"""

import hashlib
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

# Правило согласования и корень проекта живут в gate_edit.py — не дублируем
from gate_edit import КОРЕНЬ, задача_согласована, прочитать_табло  # noqa: E402

# Отпечатки «до команды» — во временной папке системы, вне репозитория;
# имя файла — по номеру вызова инструмента (`tool_use_id`), им прежняя среда
# связывает события «до» и «после» одной команды
СЛЕПКИ = Path(tempfile.gettempdir()) / "reglament-gate-shell"
# Отпечаток, до которого «после» не дошло (команду не пустил другой хук),
# живёт сутки и убирается при следующем запуске
СРОК_СЛЕПКА = 24 * 3600

СОБЫТИЯ_ПОСЛЕ = ("PostToolUse", "PostToolUseFailure")


def файл_кода(путь):
    """Путь от корня проекта — файл кода (не документация и не .reglament/)."""
    п = путь.replace("\\", "/").lower()
    return not (п.startswith("docs/") or п.startswith(".reglament/"))


def отпечаток_кода():
    """{путь: отпечаток} файлов кода, отличающихся от последнего коммита.

    Отпечаток — [размер, время изменения в наносекундах] или «нет файла»
    (удалён). Источник списка — `git status` без блокировки индекса
    (`--no-optional-locks`: параллельный коммит не должен споткнуться о
    нашу проверку); `-z` — пути как есть, без экранирования кириллицы.
    git недоступен — None."""
    try:
        р = subprocess.run(
            [
                "git",
                "--no-optional-locks",
                "-C",
                str(КОРЕНЬ),
                "status",
                "--porcelain=v1",
                "-z",
                "--untracked-files=all",
            ],
            capture_output=True,
            timeout=20,
        )
    except Exception:
        return None
    if р.returncode != 0:
        return None
    поля = р.stdout.decode("utf-8", errors="replace").split("\0")
    итог = {}
    i = 0
    while i < len(поля):
        запись = поля[i]
        i += 1
        if len(запись) < 4:
            continue
        код, путь = запись[:2], запись[3:]
        # Переименование и копия: следом идёт прежнее имя — пропускаем
        if "R" in код or "C" in код:
            i += 1
        if not файл_кода(путь):
            continue
        try:
            с = (КОРЕНЬ / путь).stat()
            итог[путь] = [с.st_size, с.st_mtime_ns]
        except OSError:
            итог[путь] = "нет файла"
    return итог


def файл_слепка(данные):
    """Файл отпечатка этой команды: по номеру вызова, а без него — по
    сессии (старые версии прежняя среда номер вызова не передавали)."""
    ключ = данные.get("tool_use_id") or данные.get("session_id") or "без-ключа"
    имя = hashlib.sha1(str(ключ).encode("utf-8")).hexdigest()
    return СЛЕПКИ / f"{имя}.json"


def убрать_старые():
    """Отпечатки, до которых «после» не дошло, — через сутки в мусор."""
    граница = time.time() - СРОК_СЛЕПКА
    try:
        for ф in СЛЕПКИ.glob("*.json"):
            if ф.stat().st_mtime < граница:
                ф.unlink()
    except OSError:
        pass


def до_команды(данные):
    табло = прочитать_табло()
    задача = табло.get("задача")
    if not задача:
        return 0
    # Согласована — штамп в табло ставит сама проверка, отпечаток не нужен
    if задача_согласована(табло, данные.get("transcript_path")):
        return 0
    отпечаток = отпечаток_кода()
    if отпечаток is None:
        return 0
    СЛЕПКИ.mkdir(parents=True, exist_ok=True)
    убрать_старые()
    файл_слепка(данные).write_text(
        json.dumps({"задача": задача, "файлы": отпечаток}, ensure_ascii=False),
        encoding="utf-8",
    )
    return 0


def после_команды(данные):
    путь = файл_слепка(данные)
    if not путь.exists():
        return 0
    try:
        до = json.loads(путь.read_text(encoding="utf-8"))
    finally:
        путь.unlink(missing_ok=True)
    после = отпечаток_кода()
    if после is None:
        return 0
    было = до.get("файлы") or {}
    изменены = sorted(п for п, отп in после.items() if было.get(п) != отп)
    if not изменены:
        return 0
    перечень = "\n".join(f"  - {п}" for п in изменены[:20])
    ещё = f"\n  … и ещё {len(изменены) - 20}" if len(изменены) > 20 else ""
    print(
        f"Правка кода до согласования (правило 4 регламента): команда "
        f"изменила файлы кода, а задача «{до.get('задача')}» не "
        f"согласована:\n{перечень}{ещё}\n"
        f"Верни их (`git checkout -- <файл>`, новый файл — удали) и "
        f"дождись согласования: покажи проект заметки и задай карточку "
        f"вопроса (малая форма — «да» пользователя и фаза «согласовано»). "
        f"Если файл правила соседняя сессия, а не эта команда, — проверь "
        f"`git diff` и чужое не трогай. Коммит этих файлов контролёр не "
        f"пропустит, пока задача не согласована.",
        file=sys.stderr,
    )
    return 2


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return 0
    событие = данные.get("hook_event_name") or ""
    try:
        if событие == "PreToolUse":
            return до_команды(данные)
        if событие in СОБЫТИЯ_ПОСЛЕ:
            return после_команды(данные)
    except Exception as ошибка:  # сбой хука не должен мешать работе
        print(f"gate_shell: сбой проверки — {ошибка}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
